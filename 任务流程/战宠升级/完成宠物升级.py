from 任务流程.基础任务框架 import 基础任务
from 任务流程.战宠升级.图像算法 import 是否包含指定颜色_HSV


class 完成宠物升级任务(基础任务):
    def 执行(self) -> bool:
        #判断是否够资源升级
        区域图像=self.上下文.op.获取屏幕图像cv(514,465,654,517)
        是否有红色调偏粉色块 = 是否包含指定颜色_HSV(
            区域图像, (250, 135, 124),
            色差H=10, 色差S=10, 色差V=10,
            最少像素数=150
        )
        if 是否有红色调偏粉色块:
            self.上下文.置脚本状态("战宠升级：资源不足")
            self._安全关闭面板("关闭战宠升级页面", "关闭战宠小屋")
            return False

        ocr结果=self.执行OCR识别((514,465,654,517))
        if "确认" not in ocr结果.__str__():
            self.上下文.置脚本状态("战宠升级：未找到确认按钮")
            # OCR 转场帧或版本字体变化时，不能把当前升级详情页留在
            # 前台，否则下一轮会把“立即完成/宝石”面板当成战宠列表。
            # 只走已经确认属于本任务的两层面板关闭器，不发送无条件 BACK。
            self._安全关闭面板("关闭战宠升级页面", "关闭战宠小屋")
            return False

        点击成功 = self.上下文.点击(577,492)#点击升级
        if 点击成功 is False:
            self.上下文.置脚本状态(
                "战宠升级：确认按钮未能安全点击，未确认升级提交；关闭已授权面板"
            )
            self._安全关闭面板("关闭战宠升级页面", "关闭战宠小屋")
            return False

        if not self._安全关闭面板("关闭战宠升级页面", "关闭战宠小屋"):
            self.上下文.置脚本状态(
                "战宠升级：升级按钮已点击，但关闭战宠面板后未确认页面可继续"
            )
            return False
        return True

    def _安全关闭面板(self, *说明列表):
        安全返回键 = getattr(self.上下文, "安全返回键", None)
        if callable(安全返回键):
            for 说明 in 说明列表:
                if not 安全返回键(说明, 已确认可关闭面板=True):
                    return False
            return True
        self.上下文.置脚本状态(
            "未提供战宠升级安全关闭器，禁止发送ESC；保留当前页面等待人工确认"
        )
        return False
