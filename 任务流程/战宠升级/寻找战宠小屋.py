from pathlib import Path

import cv2

from 任务流程.基础任务框架 import 基础任务, 任务上下文
from 模块.检测.YOLO检测器 import 线程安全YOLO检测器


class 寻找战宠小屋任务(基础任务):
    """
    任务：寻找战宠小屋并点击打开
    """

    def __init__(self, 上下文: '任务上下文', 点击延时: int = 500):
        super().__init__(上下文)
        self.点击延时 = 点击延时

        # 模型路径
        模型目录 = Path(__file__).parent / "模型"
        onnx路径 = 模型目录 / "战宠小屋检测模块.onnx"

        # 初始化检测器
        self.战宠小屋检测器 = 线程安全YOLO检测器(onnx路径, ["战宠小屋"])

    def 执行(self) -> bool:
        """
        执行任务：寻找战宠小屋并点击打开
        返回:
            bool: 成功返回 True，失败返回 False
        """
        # 战宠小屋已经被上一轮打开、但按钮识别恰好漏掉时，先处理现有
        # 面板。否则下一轮会再次把地图上的目标当成小屋点击，造成面板
        # 反复打开/关闭或一直停在小屋面板。按钮模板来自旧分辨率，在
        # 自适应 1280x720 -> 800x600 画布上实测最高约 0.61，因此不能
        # 继续使用基础任务默认的 0.90 阈值；区域限制在面板底部后再用
        # 0.55 阈值，避免把主世界其它金色图标误认为打开按钮。
        if self._点击打开按钮():
            return True

        try:
            屏幕图像 = self.上下文.op.获取屏幕图像cv(0, 0, 800, 600)

            # 完整画面中战宠小屋通常只有几十个像素，直接把全图缩放到
            # YOLO 的 640x640 输入会把目标压得太小，实机置信度只有
            # 0.17~0.23，导致任务一直安全跳过。只在主世界地图的安全
            # 区域做有限的 1.5 倍放大检测，再把坐标还原回 800x600 参考
            # 画布；不扫描右下商店、左下攻击按钮等固定控件区域。
            检测结果 = self._检测放大地图区域(屏幕图像)
            if not 检测结果:
                self.上下文.置脚本状态("战宠升级：未检测到战宠小屋")
                return False

            # 根据置信度选择最佳框
            框 = max(检测结果, key=lambda d: d.get('置信度', 0))
            if '裁剪坐标' not in 框:
                self.上下文.置脚本状态("战宠升级：检测结果异常")
                return False

            # 点击战宠小屋
            x1, y1, x2, y2 = 框['裁剪坐标']
            中心x = (x1 + x2) // 2
            中心y = (y1 + y2) // 2
            置信度=框["置信度"]
            self.上下文.置脚本状态(f"战宠升级：找到战宠小屋 ({中心x},{中心y}) 置信度{置信度:.2f}")
            self.上下文.点击(中心x, 中心y, 延时=500)

        except Exception as e:
            self.上下文.置脚本状态(f"战宠升级：检测异常 {e}")
            return False


        if self._点击打开按钮():
            return True
        self.上下文.置脚本状态("战宠升级：未找到打开按钮")
        return False

    def _检测放大地图区域(self, 屏幕图像) -> list[dict]:
        """在主世界安全地图区域放大检测战宠小屋。

        模型训练图里的小屋尺寸明显大于自适应实机画面中的小屋。这里
        用两个重叠的主地图切片加两个边缘切片覆盖可见地图，每次只放大
        1.5 倍，避免长时间循环产生大图和额外内存压力。只有置信度至少
        0.55 且中心位于地图安全区的结果才允许后续点击。
        """
        if 屏幕图像 is None or not hasattr(屏幕图像, "shape"):
            return []

        高, 宽 = 屏幕图像.shape[:2]
        if 高 <= 0 or 宽 <= 0:
            return []
        if (宽, 高) != (800, 600):
            屏幕图像 = cv2.resize(
                屏幕图像, (800, 600), interpolation=cv2.INTER_AREA
            )

        放大倍数 = 1.5
        # 这些区域避开顶部资源栏、左下攻击入口和右下商店；相邻区域
        # 保留重叠，避免小屋刚好落在切片边界上。
        地图切片 = (
            (120, 80, 640, 600),
            (300, 80, 800, 600),
            (80, 180, 600, 600),
            (220, 120, 760, 600),
        )
        候选 = []
        for 左, 上, 右, 下 in 地图切片:
            左 = max(0, min(800, 左))
            上 = max(0, min(600, 上))
            右 = max(左 + 1, min(800, 右))
            下 = max(上 + 1, min(600, 下))
            切片 = 屏幕图像[上:下, 左:右]
            放大图 = cv2.resize(
                切片,
                None,
                fx=放大倍数,
                fy=放大倍数,
                interpolation=cv2.INTER_CUBIC,
            )
            try:
                结果 = self.战宠小屋检测器.检测(放大图)
            except Exception as 异常:
                if self.上下文.是否内存异常(异常):
                    self.上下文.触发内存保护("战宠小屋放大检测", 异常)
                self.上下文.置脚本状态(f"战宠升级：放大检测异常 {异常}")
                continue
            if not isinstance(结果, list):
                continue
            for 项 in 结果:
                置信度 = float(项.get("置信度", 0) or 0)
                坐标 = 项.get("裁剪坐标")
                if 置信度 < 0.55 or not isinstance(坐标, (list, tuple)) or len(坐标) < 4:
                    continue
                try:
                    x1, y1, x2, y2 = (float(值) for 值 in 坐标[:4])
                except (TypeError, ValueError):
                    continue
                # 从放大切片坐标还原为 800x600 参考坐标。
                x1 = 左 + x1 / 放大倍数
                y1 = 上 + y1 / 放大倍数
                x2 = 左 + x2 / 放大倍数
                y2 = 上 + y2 / 放大倍数
                中心x = (x1 + x2) / 2
                中心y = (y1 + y2) / 2
                if not (70 <= 中心x <= 730 and 105 <= 中心y <= 585):
                    continue
                候选.append({
                    "裁剪坐标": [int(x1), int(y1), int(x2), int(y2)],
                    "类别名称": "战宠小屋",
                    "置信度": 置信度,
                })

        # 重叠切片会重复检测同一座小屋；只保留最高置信度结果。
        去重 = []
        for 项 in sorted(候选, key=lambda 项: 项["置信度"], reverse=True):
            x1, y1, x2, y2 = 项["裁剪坐标"]
            cx, cy = (x1 + x2) / 2, (y1 + y2) / 2
            if any(abs(cx - 已x) < 35 and abs(cy - 已y) < 35 for 已x, 已y, _ in 去重):
                continue
            去重.append((cx, cy, 项))
        return [项 for _, _, 项 in 去重]

    def _点击打开按钮(self) -> bool:
        """只在战宠小屋面板底部寻找并点击“战宠”按钮。

        旧模板是在另一套画布尺寸上截取的，直接按 0.9 匹配会漏掉实际
        已打开的面板。这里连续短轮询，给面板动画留出时间；每一轮都
        限制在面板底部区域，并且点击仍经过统一的安全护栏。
        """
        try:
            for 次数 in range(3):
                是否匹配, (x, y) = self.是否出现图片(
                    "打开战宠小屋按钮.bmp|打开战宠小屋按钮1.bmp",
                    区域=(400, 360, 580, 560),
                    相似度阈值=0.55,
                )
                if 是否匹配:
                    self.上下文.点击(x, y, 延时=350, 是否精确点击=True)
                    self.上下文.置脚本状态(
                        f"战宠升级：已打开战宠小屋（按钮确认 {x},{y}）"
                    )
                    return True
                if 次数 < 2:
                    self.上下文.脚本延时(250)
        except Exception as 异常:
            self.上下文.置脚本状态(f"战宠升级：打开按钮检测异常 {异常}")
        return False
