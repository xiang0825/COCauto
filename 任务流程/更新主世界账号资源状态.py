def 检测无消耗大幅负跳变(旧资源: dict | None, 新资源: dict | None) -> list[str]:
    """检测无刷墙/升级消耗记录时的异常大幅负跳变字段。"""
    if not isinstance(旧资源, dict) or not isinstance(新资源, dict):
        return []
    try:
        已确认 = {字段: int(旧资源[字段] or 0) for 字段 in ("金币", "圣水", "黑油")}
        新读数 = {字段: int(新资源[字段] or 0) for 字段 in ("金币", "圣水", "黑油")}
    except (KeyError, TypeError, ValueError):
        return []
    if min(已确认.values()) < 0 or min(新读数.values()) < 0:
        return []
    异常字段 = []
    for 字段 in ("金币", "圣水"):
        旧值 = 已确认[字段]
        新值 = 新读数[字段]
        下降 = 旧值 - 新值
        if 旧值 >= 3_000_000 and 下降 >= max(2_000_000, int(旧值 * 0.20)):
            异常字段.append(字段)
    旧黑油 = 已确认["黑油"]
    新黑油 = 新读数["黑油"]
    if 旧黑油 >= 50_000 and (旧黑油 - 新黑油) >= max(30_000, int(旧黑油 * 0.30)):
        异常字段.append("黑油")
    return 异常字段


