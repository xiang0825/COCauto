    def _完整资源栏复核(self, 资源栏图像) -> tuple[int, int, int] | None:
        """对可疑资源栏做彩色/灰度双路径复核。

        当前 MuMu 实机的圣水数字在彩色整栏 OCR 中偶尔只返回尾段
        ``819777``，而灰度整栏 OCR 能稳定读回 ``17819777``。只有当
        灰度结果把某个资源从“明显过短”恢复到正常数量级时才采用它，
        不用灰度结果无条件覆盖正常彩色读数。
        """
        彩色读数 = self._完整资源栏复核单次(资源栏图像)
        if not hasattr(资源栏图像, "shape") or len(资源栏图像.shape) < 3:
            return 彩色读数
        # 当前复核策略只有在灰度读数跨过可信门槛时才会覆盖彩色值。
        # 彩色三项均已达标时，灰度扫描不可能改变返回结果，跳过第二次
        # 整栏 OCR，减少周期性资源检查的 CPU 和内存峰值。
        if 彩色读数 is not None and all(
            彩色读数[索引] >= 门槛
            for 索引, 门槛 in ((0, 2_000_000), (1, 2_000_000), (2, 100_000))
        ):
            return 彩色读数
        try:
            灰度图像 = cv2.cvtColor(资源栏图像, cv2.COLOR_BGR2GRAY)
            灰度读数 = self._完整资源栏复核单次(灰度图像)
        except (AttributeError, TypeError, ValueError, cv2.error):
            灰度读数 = None
        if 彩色读数 is None:
            return 灰度读数
        if 灰度读数 is None:
            return 彩色读数
        # 金币/圣水正常通常至少为百万级；黑油达到十万级即可视为
        # 已恢复。只在灰度结果跨过对应的可信门槛时替换单次结果。
        for 索引, 门槛 in ((0, 2_000_000), (1, 2_000_000), (2, 100_000)):
            if 彩色读数[索引] < 门槛 <= 灰度读数[索引]:
                return 灰度读数
        return 彩色读数

    def _完整资源栏复核单次(self, 资源栏图像) -> tuple[int, int, int] | None:
        """对可疑的三行资源栏做一次整块 OCR，并按文字坐标归位。

        单行轻量 OCR 在主世界刚回营、资源动画或上下行间距变化时，
        可能把圣水/黑水行裁到邻行，只留下较短数字。整块检测 OCR 能
        同时看到三行文字；这里只在可疑读数时调用，避免常态重复加载
        ONNX 检测模型造成内存峰值。
        """
        try:
            结果, _ = self.ocr引擎(资源栏图像, use_cls=False)
            高, 宽 = 资源栏图像.shape[:2]
            行候选 = {0: [], 1: [], 2: []}
            # 不把三行写死在固定 y 坐标。不同 MuMu/CoC 版本、转场动画
            # 和窗口缩放会让资源行在裁剪区内上下移动；实机 1280×720
            # 画面曾出现约 34/90/145，而旧测试样本是约 33/69/103。
            # 先收集右侧数字候选，随后按 y 从上到下分组。
            数字候选 = []
            for 项 in (结果 or []):
                if not isinstance(项, (list, tuple)) or len(项) < 3:
                    continue
                框, 原文, 置信度 = 项[0], 项[1], 项[2]
                try:
                    点 = [
                        (float(坐标[0]), float(坐标[1]))
                        for 坐标 in 框
                        if len(坐标) >= 2
                    ]
                    if not 点:
                        continue
                    中心x = sum(点x for 点x, _ in 点) / len(点)
                    中心y = sum(点y for _, 点y in 点) / len(点)
                    # 资源数字在裁剪区域右侧；排除左侧图标、背景噪声。
                    if 中心x < 宽 * 0.35 or 中心x > 宽 * 0.98:
                        continue
                    文本 = unicodedata.normalize("NFKC", str(原文))
                    数字 = "".join(字符 for 字符 in 文本 if 字符 in "0123456789")
                    if not 数字:
                        continue
                    数字候选.append((中心y, 中心x, 数字, float(置信度)))
                except (TypeError, ValueError, IndexError):
                    continue

            数字候选.sort(key=lambda 项: 项[0])
            行分组 = []
            行容差 = max(8.0, 高 * 0.08)
            for 候选 in 数字候选:
                if not 行分组 or abs(候选[0] - 行分组[-1][0][0]) > 行容差:
                    行分组.append([候选])
                else:
                    行分组[-1].append(候选)

            # 正常整栏 OCR 会得到三行；若检测器额外返回了背景数字，
            # 回退到每行最高置信度，仍要求三行都有明确候选。
            if len(行分组) == 3:
                for 行号, 分组 in enumerate(行分组):
                    行候选[行号] = [
                        (项[2], 项[3]) for 项 in 分组
                    ]
            else:
                # 兼容旧版固定布局样本，同时不让缺失行被猜成 0。
                目标行 = (0.20 * 高, 0.43 * 高, 0.64 * 高)
                for 中心y, _, 数字, 置信度 in 数字候选:
                    行号 = min(
                        range(3),
                        key=lambda 索引: abs(中心y - 目标行[索引]),
                    )
                    行候选[行号].append((数字, 置信度))

            读数 = []
            for 行号 in range(3):
                if not 行候选[行号]:
                    return None
                数字, _ = max(
                    行候选[行号],
                    key=lambda 项: (项[1], len(项[0])),
                )
                读数.append(int(数字))
            if 读数[2] > 1_000_000:
                return None
            return tuple(读数)
        except (AttributeError, TypeError, ValueError, IndexError):
            return None

    # 游戏里金币/圣水储存远低于一亿（现行容量约 3100 万）。实机 rc128：资源栏
    # 17,636,793 被两路 OCR 一致读成 1,138,070,872（约 64 倍，超出“十倍偏移”拦截），
    # 若写入数据库会让“资源打满”判断误停刷资源。超过这个上限的读数一律视为不可信。
    主资源读数上限 = 100_000_000

    @staticmethod
    def _取可信资源快照(资源: dict | None) -> dict | None:
        if not isinstance(资源, dict) or not 资源.get("识别成功", False):
            return None
        try:
            快照 = {
                字段: int(资源[字段] or 0)
                for 字段 in ("金币", "圣水", "黑油")
            }
        except (KeyError, TypeError, ValueError):
            return None
        return 快照 if min(快照.values()) >= 0 else None

    @classmethod
    def _资源跳变需要复核(cls, 已确认资源: dict, 新资源: dict) -> bool:
        """只对单次读数中不寻常的大跳变触发较重的独立复读。"""
        已确认 = cls._取可信资源快照({**已确认资源, "识别成功": True})
        新读数 = cls._取可信资源快照({**新资源, "识别成功": True})
        if not 已确认 or not 新读数:
            return False
        for 字段 in ("金币", "圣水"):
            之前 = 已确认[字段]
            if 之前 >= 1_000_000:
                if abs(新读数[字段] - 之前) >= max(5_000_000, int(之前 * 0.35)):
                    return True
        之前黑油 = 已确认["黑油"]
        if (
            之前黑油 >= 100_000
            and abs(新读数["黑油"] - 之前黑油)
            >= max(150_000, int(之前黑油 * 0.50))
        ):
            return True
        # 实机 rc132：黑油 70,303 被读成 157（资源栏下方多出的假数字），
        # 旧门槛只看 ≥10 万，直接放行。中等黑油量骤降过半也做一次复读；
        # 真的花掉黑油时复读会确认同一个数，不影响结果。
        return 之前黑油 >= 20_000 and 新读数["黑油"] < 之前黑油 * 0.5

    @classmethod
    def _存在无消耗大幅负跳变(
        cls, 旧资源: dict, 新资源: dict
    ) -> list[str]:
        """检测无刷墙/升级消耗记录时的异常大幅负跳变字段。"""
        return 检测无消耗大幅负跳变(旧资源, 新资源)

    @classmethod
    def _资源快照反向大跳原因(cls, 已确认资源: dict, 新资源: dict) -> str | None:
        """区分主资源反向大跳中的新 OCR 错读、旧快照错读和未知情况。"""
        已确认 = cls._取可信资源快照({**已确认资源, "识别成功": True})
        新读数 = cls._取可信资源快照({**新资源, "识别成功": True})
        if not 已确认 or not 新读数:
            return None

        金币变化 = 新读数["金币"] - 已确认["金币"]
        圣水变化 = 新读数["圣水"] - 已确认["圣水"]
        金币大跳 = abs(金币变化) >= max(
            5_000_000, int(已确认["金币"] * 0.35)
        )
        圣水大跳 = abs(圣水变化) >= max(
            5_000_000, int(已确认["圣水"] * 0.35)
        )
        黑油容差 = max(
            20_000,
            int(max(已确认["黑油"], 新读数["黑油"]) * 0.05),
        )
        if not (
            金币大跳
            and 圣水大跳
            and 金币变化 * 圣水变化 < 0
            and abs(新读数["黑油"] - 已确认["黑油"]) <= 黑油容差
        ):
            return None

        # 31m 是现有资源 OCR 错位保护采用的高余额边界。若只有新读数
        # 跨过边界，优先保留旧值；若只有旧快照跨过，则允许新读数恢复。
        旧高余额项数 = sum(
            已确认[字段] > 31_000_000 for 字段 in ("金币", "圣水")
        )
        新高余额项数 = sum(
            新读数[字段] > 31_000_000 for 字段 in ("金币", "圣水")
        )
        if 新高余额项数 > 旧高余额项数:
            return "新读数疑似错位"
        if 旧高余额项数 > 新高余额项数:
            return "旧快照疑似错位"
        return "反向大跳来源不明"

    @staticmethod
    def _资源快照相近(左: dict, 右: dict) -> bool:
        for 字段 in ("金币", "圣水"):
            容差 = max(250_000, int(max(左[字段], 右[字段]) * 0.025))
            if abs(左[字段] - 右[字段]) > 容差:
                return False
        黑油容差 = max(20_000, int(max(左["黑油"], 右["黑油"]) * 0.05))
        return abs(左["黑油"] - 右["黑油"]) <= 黑油容差

    @staticmethod
    def _资源快照疑似漏掉数字(旧资源: dict, 新资源: dict) -> str | None:
        """识别主资源漏字或约十倍骤降，允许其余主资源正常采集波动。"""
        for 字段 in ("金币", "圣水"):
            旧值 = int(旧资源.get(字段, 0) or 0)
            新值 = int(新资源.get(字段, 0) or 0)
            if 旧值 < 10_000_000 or 新值 < 1_000_000:
                continue
            旧数字, 新数字 = str(旧值), str(新值)
            漏读匹配 = len(旧数字) == len(新数字) + 1 and any(
                旧数字[:索引] + 旧数字[索引 + 1:] == 新数字
                for 索引 in range(len(旧数字))
            )
            约十倍骤降 = 8.0 <= 旧值 / 新值 <= 12.0
            if not (漏读匹配 or 约十倍骤降):
                continue
            其余字段 = ("金币", "圣水", "黑油")
            其余字段 = [其他字段 for 其他字段 in 其余字段 if 其他字段 != 字段]
            其余值相近 = True
            for 其他字段 in 其余字段:
                其他旧值 = int(旧资源.get(其他字段, 0) or 0)
                其他新值 = int(新资源.get(其他字段, 0) or 0)
                if 其他字段 == "黑油":
                    容差 = max(20_000, int(max(其他旧值, 其他新值) * 0.05))
                else:
                    容差 = max(1_000_000, int(max(其他旧值, 其他新值) * 0.08))
                if abs(其他旧值 - 其他新值) > 容差:
                    其余值相近 = False
                    break
            if 其余值相近:
                return 字段
        return None

    @staticmethod
    def _资源快照疑似多项数量级偏移(旧资源: dict, 新资源: dict) -> tuple[str, ...]:
        """识别主资源约十倍 OCR 离群值；单项超出当前游戏容量时也拦截。"""
        数量级偏移字段 = []
        上限 = 更新家乡资源状态任务.主资源读数上限
        for 字段 in ("金币", "圣水"):
            旧值 = int(旧资源.get(字段, 0) or 0)
            新值 = int(新资源.get(字段, 0) or 0)
            if 新值 > 上限 >= 旧值:
                # 超过一亿的读数不可能是真实余额（实机 1,138,070,872 ≈ 真实值的 64 倍）。
                数量级偏移字段.append(字段)
            elif (
                min(旧值, 新值) >= 1_000_000
                and max(旧值, 新值) >= 10_000_000
                and 8.0 <= max(旧值, 新值) / min(旧值, 新值) <= 12.0
            ):
                数量级偏移字段.append(字段)
        if not 数量级偏移字段:
            return ()

        if len(数量级偏移字段) == 1:
            字段 = 数量级偏移字段[0]
            旧值 = int(旧资源.get(字段, 0) or 0)
            新值 = int(新资源.get(字段, 0) or 0)
            # 旧快照可能已经被一次错误 OCR 污染；新读数回到正常范围时应允许恢复。
            if 旧值 > 31_000_000 and 新值 <= 31_000_000:
                return ()
            if 旧值 <= 31_000_000 and 新值 > 31_000_000:
                return tuple(数量级偏移字段)
            if max(旧值, 新值) <= 31_000_000:
                return ()

        for 字段 in ("金币", "圣水", "黑油"):
            if 字段 in 数量级偏移字段:
                continue
            旧值 = int(旧资源.get(字段, 0) or 0)
            新值 = int(新资源.get(字段, 0) or 0)
            if 字段 == "黑油":
                容差 = max(20_000, int(max(旧值, 新值) * 0.05))
            else:
                容差 = max(1_000_000, int(max(旧值, 新值) * 0.08))
            if abs(旧值 - 新值) > 容差:
                return ()
        return tuple(数量级偏移字段)

    def _复核异常资源跳变(self, 上下文, 首次读数: dict) -> dict | None:
        """以轻量 OCR、重新截图的轻量 OCR、整栏 OCR 三路多数值复核。"""
        候选 = [self._取可信资源快照(首次读数)]
        上下文.脚本延时(350)
        try:
            候选.append(self._取可信资源快照(self.识别当前资源(上下文)))
        except Exception as 异常:
            上下文.置脚本状态(f"资源跳变轻量复读失败：{异常}")
            候选.append(None)
        try:
            图像 = 上下文.op.获取屏幕图像cv(590, 0, 800, 160)
            完整读数 = self._完整资源栏复核(图像)
            if 完整读数 is None:
                候选.append(None)
            else:
                候选.append(self._取可信资源快照({
                    "金币": 完整读数[0],
                    "圣水": 完整读数[1],
                    "黑油": 完整读数[2],
                    "识别成功": True,
                }))
        except Exception as 异常:
            上下文.置脚本状态(f"资源跳变整栏复核失败：{异常}")
            候选.append(None)

        有效候选 = [资源 for 资源 in 候选 if 资源 is not None]
        多数结果 = []
        for 序号, 资源 in enumerate(候选):
            if 资源 is None:
                continue
            一致数 = sum(
                其他序号 != 序号
                and 其他 is not None
                and self._资源快照相近(资源, 其他)
                for 其他序号, 其他 in enumerate(候选)
            )
            if 一致数:
                多数结果.append((一致数, 序号, 资源))
        if not 多数结果:
            上下文.置脚本状态(
                f"资源大跳变复核无一致结果，保留旧快照；有效复读数={len(有效候选)}"
            )
            return None
        _, _, 确认资源 = max(多数结果, key=lambda 项: (项[0], 项[1]))
        return 确认资源

    def 执行(self) -> bool:
        上下文 = self.上下文
        # 主世界上可能自动弹出“正在升级/立即完成”详情面板。先只点
        # 已确认的右上角关闭按钮；如果关闭后无法确认主页，宁可保留
        # 上一份资源状态，也不在遮罩层上做 OCR 或写入错误的 27/0/73。
        关闭升级面板 = getattr(上下文, "关闭升级详情弹窗", None)
        if callable(关闭升级面板):
            关闭升级面板()
            if getattr(上下文, "页面恢复失败", False):
                上下文.置脚本状态(
                    "资源识别前未确认主世界主页，保留上一份资源状态"
                )
                return False
        上下文.脚本延时(random.randint(500, 1000))#等待资源界面数字固定再执行识别
        资源字典=self.识别当前资源(上下文)
        首次快照 = self._取可信资源快照(资源字典)
        旧资源快照 = None
        获取状态 = getattr(上下文.数据库, "获取最新完整状态", None)
        if callable(获取状态):
            try:
                状态 = 获取状态(上下文.机器人标志)
                状态数据 = getattr(状态, "状态数据", {}) or {}
                旧资源快照 = self._取可信资源快照(状态数据.get("家乡资源"))
            except Exception as 异常:
                上下文.置脚本状态(f"读取已确认资源快照失败，跳过跳变比较：{异常}")
        上下文._资源待校准 = False
        存在合法消耗 = bool(getattr(上下文, "_最近存在合法消耗", False))
        无消耗负跳变字段 = (
            self._存在无消耗大幅负跳变(旧资源快照, 首次快照)
            if (首次快照 and 旧资源快照 and not 存在合法消耗)
            else []
        )
        if (
            首次快照
            and 旧资源快照
            and (
                self._资源跳变需要复核(旧资源快照, 首次快照)
                or bool(无消耗负跳变字段)
            )
        ):
            if 无消耗负跳变字段 and not self._资源跳变需要复核(旧资源快照, 首次快照):
                上下文.置脚本状态(
                    f"无刷墙/升级消耗记录下{'/'.join(无消耗负跳变字段)}出现大幅负跳变，执行受控复读"
                )
            else:
                上下文.置脚本状态(
                    "资源 OCR 与上一份确认值出现大幅跳变，执行双路径独立复读"
                )
            复核快照 = self._复核异常资源跳变(上下文, 资源字典)
            if 复核快照 is None:
                上下文._资源待校准 = True
                资源字典 = dict(资源字典)
                资源字典["识别成功"] = False
                资源字典["待校准"] = True
                资源字典["识别错误"] = "资源大跳变的独立复读未形成一致结果"
            else:
                漏读字段 = self._资源快照疑似漏掉数字(
                    旧资源快照, 复核快照
                )
                数量级偏移字段 = self._资源快照疑似多项数量级偏移(
                    旧资源快照, 复核快照
                )
                需沿用旧值字段 = (
                    set(数量级偏移字段)
                    if 数量级偏移字段
                    else ({漏读字段} if 漏读字段 else set())
                )
                if 需沿用旧值字段:
                    修正快照 = dict(复核快照)
                    for 字段 in 需沿用旧值字段:
                        修正快照[字段] = 旧资源快照[字段]
                    资源字典 = {
                        **修正快照,
                        "总资源": 修正快照["金币"] + 修正快照["圣水"],
                        "识别成功": True,
                    }
                    错误说明 = (
                        f"{','.join(sorted(需沿用旧值字段))}多项资源数量级偏移"
                        if 数量级偏移字段
                        else f"{漏读字段}数字漏读或余额约十倍骤降"
                    )
                    上下文.置脚本状态(
                        f"资源异常复读仍疑似{错误说明}；"
                        "沿用此前可信读数，避免写入假资源变化"
                    )
                else:
                    反向跳变原因 = self._资源快照反向大跳原因(
                        旧资源快照, 复核快照
                    )
                    if 反向跳变原因 in {"新读数疑似错位", "反向大跳来源不明"}:
                        错误说明 = (
                            "金币与圣水反向大幅跳变且黑油稳定，"
                            "无法确认新资源读数"
                        )
                        上下文._资源待校准 = True
                        资源字典 = {
                            **复核快照,
                            "总资源": 复核快照["金币"] + 复核快照["圣水"],
                            "识别成功": False,
                            "待校准": True,
                            "识别错误": 错误说明,
                        }
                        上下文.置脚本状态(
                            f"{错误说明}；保留上一份可信快照，下一轮重读"
                        )
                    elif 反向跳变原因 == "旧快照疑似错位":
                        资源字典 = {
                            **复核快照,
                            "总资源": 复核快照["金币"] + 复核快照["圣水"],
                            "识别成功": True,
                        }
                        上下文.置脚本状态(
                            f"{资源字典}；旧快照疑似 OCR 错位，已用稳定复读恢复"
                        )
                    else:
                        复核无消耗负跳变 = (
                            self._存在无消耗大幅负跳变(旧资源快照, 复核快照)
                            if not 存在合法消耗
                            else []
                        )
                        if 复核无消耗负跳变:
                            待校准前值 = getattr(上下文, "_待校准资源快照", None)
                            允许校准落盘 = (
                                bool(getattr(上下文, "_允许待校准快照落盘", False))
                                and isinstance(待校准前值, dict)
                                and self._资源快照相近(待校准前值, 复核快照)
                            )
                            if 允许校准落盘:
                                上下文._待校准资源快照 = None
                                上下文._允许待校准快照落盘 = False
                                资源字典 = {
                                    **复核快照,
                                    "总资源": 复核快照["金币"] + 复核快照["圣水"],
                                    "识别成功": True,
                                }
                                上下文.置脚本状态(
                                    f"战前连续两轮复读均确认新资源基线，已完成待校准切换：{资源字典}"
                                )
                            else:
                                字段说明 = "/".join(复核无消耗负跳变)
                                错误说明 = (
                                    f"无刷墙/升级消耗记录下{字段说明}大幅负跳变，"
                                    "已复读并标记待校准"
                                )
                                上下文._资源待校准 = True
                                上下文._待校准资源快照 = dict(复核快照)
                                上下文._允许待校准快照落盘 = False
                                资源字典 = {
                                    **复核快照,
                                    "总资源": 复核快照["金币"] + 复核快照["圣水"],
                                    "识别成功": False,
                                    "待校准": True,
                                    "识别错误": 错误说明,
                                }
                                上下文.置脚本状态(
                                    f"{错误说明}；保留上一份可信快照，禁止写入净变化"
                                )
                        else:
                            资源字典 = {
                                **复核快照,
                                "总资源": 复核快照["金币"] + 复核快照["圣水"],
                                "识别成功": True,
                            }
                            上下文.置脚本状态(
                                f"资源异常读数已由独立复读多数确认：{资源字典}"
                            )
        if (
            资源字典.get("识别成功")
            and max(int(资源字典.get("金币", 0) or 0), int(资源字典.get("圣水", 0) or 0))
            > self.主资源读数上限
        ):
            资源字典 = dict(资源字典)
            资源字典["识别成功"] = False
            资源字典["识别错误"] = "金币/圣水读数超过一亿，判定为 OCR 错读"
            上下文.置脚本状态("金币/圣水读数超过一亿，判定为 OCR 错读；保留上一份资源状态")
        # 给调用方留下本轮识别结果。识别失败时数据库可能从未有过
        # 家乡资源状态，调用方必须把它视为“未知”，不能当作 0。
        上下文._最近资源识别结果 = dict(资源字典 or {})
        上下文._最近资源识别成功 = bool(
            资源字典.get("识别成功", False)
            and all(字段 in 资源字典 for 字段 in ("金币", "圣水", "黑油"))
        )
        上下文.置脚本状态("主世界资源识别结果："+str(资源字典))
        if not 上下文._最近资源识别成功:
            # OCR/ONNX 临时分配失败时不能把上一份真实资源覆盖成 0，
            # 否则下一轮会计算出巨额负收益并误判资源状态。
            上下文.置脚本状态("本次资源识别未完成，保留上一份资源状态，不覆盖数据库")
            return False
        上下文._最近存在合法消耗 = False
        上下文._资源待校准 = False
        上下文._待校准资源快照 = None
        上下文._允许待校准快照落盘 = False
        上下文.数据库.更新状态(上下文.机器人标志,"家乡资源",资源字典)
        return True

    def 识别当前资源(self, 上下文) -> dict:
        """从主城右上角读取金币、圣水和黑水。

        资源数字在不同版本的右上角位置会有少量变化，使用完整右侧
        210×160 区域而不是旧的 138×134 裁剪，避免数字被边界截断。
        """
        最后异常 = None
        for 尝试次数 in range(1, 3):
            try:
                全屏图像 = 上下文.op.获取屏幕图像cv(590, 0, 800, 160)

                def 切分资源行(图像):
                    """按资源栏实际占用的上方区域切分，并保留行间重叠。"""
                    h = 图像.shape[0]
                    # 请求区域高为160时，三行资源文字实际集中在前约
                    # 120px；等分整个160px会把黑油行从文字底部开始裁剪，
                    # 实机会把362,905读成36,295。每行使用约35%高度，
                    # 步长约25%，既覆盖完整数字又允许主题/缩放有小偏移。
                    行高 = max(1, int(round(h * 0.35)))
                    步长 = max(1, int(round(h * 0.25)))
                    return (
                        图像[0:min(h, 行高), :],
                        图像[步长:min(h, 步长 + 行高), :],
                        图像[2 * 步长:min(h, 2 * 步长 + 行高), :],
                    )

                金币图, 圣水图, 黑油图 = 切分资源行(全屏图像)

                资源行图像 = (金币图, 圣水图, 黑油图)
                金币文本 = 单行资源识别(self.ocr引擎, 金币图)
                圣水文本 = 单行资源识别(self.ocr引擎, 圣水图)
                黑油文本 = 单行资源识别(
                    self.ocr引擎, 黑油图, 最大值=1_000_000
                )
                已完成整栏复核 = False

                # 主资源已经是百万级、高本常见的圣水/黑水却突然变成
                # 短数字时，说明单行切分可能错位。先对整块资源栏做复核，
                # 再决定是否进入逐行完整 OCR 回退，避免错误读数先参与后续
                # 判断，也避免重复创建 OCR 会话造成内存抖动。
                需要整栏复核 = (
                    金币文本 == 0
                    or 圣水文本 == 0
                    or (0 < 金币文本 < 2_000_000)
                    or (0 < 圣水文本 < 2_000_000)
                    or (
                        # 黑油栏在当前 MuMu 1280×720 画面中会被逐行
                        # 轻量 OCR 截成 1 位（例如真实 52059 读成 7）。
                        # 不能只在主资源达到千万时复核：普通资源余额
                        # 8m/4m 同样会触发这个误读。只要主资源已确认
                        # 为正常的百万级，就用整栏坐标 OCR 重新归位。
                        max(金币文本, 圣水文本) >= 1_000_000
                        and 黑油文本 < 100_000
                    )
                )
                if 需要整栏复核:
                    完整读数 = self._完整资源栏复核(全屏图像)
                    if 完整读数 is not None:
                        金币文本, 圣水文本, 黑油文本 = 完整读数
                        已完成整栏复核 = True
                        上下文.置脚本状态(
                            "资源栏可疑读数已完成整栏OCR复核，按文字坐标重新归位"
                        )

                # 整栏 OCR 已按三行坐标读到明确数值时，不再用裁剪过的
                # 单行图覆盖它。实机圣水恰好为 1,000,000：整栏正确读出
                # 1,000,000 后，旧逻辑因“低于 2m”再跑单行 OCR 并写成 0，
                # 导致刷墙无限重试。只有整栏复核失败，或整栏仍缺失某个
                # 主资源时，才允许较窄的逐行回退覆盖结果。
                if (
                    (not 已完成整栏复核 or 金币文本 == 0 or 圣水文本 == 0)
                    and (
                        金币文本 == 0
                        or 圣水文本 == 0
                        or (0 < 金币文本 < 2_000_000)
                        or (0 < 圣水文本 < 2_000_000)
                    )
                ):
                    金币文本 = 单行资源识别(
                        self.ocr引擎, 资源行图像[0], 允许完整识别=True
                    )
                    圣水文本 = 单行资源识别(
                        self.ocr引擎, 资源行图像[1], 允许完整识别=True
                    )
                # 黑油数字通常较短；低于五位时仍可能漏掉首位，使用完整
                # OCR 复核。先完成主资源回退，再用可信的主资源判断是否
                # 值得触发这条较重路径，避免每帧都加载检测模型。
                if (
                    (黑油文本 == 0 or 黑油文本 < 100_000)
                    and max(金币文本, 圣水文本) >= 1_000_000
                    and not 已完成整栏复核
                ):
                    黑油文本 = 单行资源识别(
                        self.ocr引擎, 资源行图像[2],
                        允许完整识别=True, 最大值=1_000_000
                    )

                # 金币和圣水不应同时识别为 0；出现这种情况通常是界面仍在
                # 切换或截图被遮挡，换用更紧的右侧区域重试一次。
                if 金币文本 == 0 and 圣水文本 == 0:
                    右侧图像 = 上下文.op.获取屏幕图像cv(680, 0, 800, 160)
                    金币图, 圣水图, 黑油图 = 切分资源行(右侧图像)
                    金币文本 = 单行资源识别(
                        self.ocr引擎, 金币图, 允许完整识别=True
                    )
                    圣水文本 = 单行资源识别(
                        self.ocr引擎, 圣水图, 允许完整识别=True
                    )
                    黑油文本 = 单行资源识别(
                        self.ocr引擎, 黑油图,
                        允许完整识别=True, 最大值=1_000_000
                    )

                资源值列表 = (金币文本, 圣水文本, 黑油文本)
                非零资源 = [值 for 值 in 资源值列表 if int(值 or 0) > 0]
                低位资源 = [值 for 值 in 非零资源 if int(值) < 1000]
                # 正常主城金币/圣水容量至少是千级；两个主资源都只有
                # 两三位数，或三项合计仍很小，通常是弹窗/过渡帧被 OCR
                # 截断。不能把它当成成功结果覆盖数据库。
                # 一项主资源达到百万级而另一项为 0/极低，通常是资源行
                # 漏读，而不是可信余额。整栏复核已经按三行文字坐标重新
                # 归位时，低余额可能是真实的（例如圣水只有 2318），
                # 不能再用“低于十万”一刀切，否则刷资源永远看不到真实
                # 的低资源状态。只把低于千级的主资源视为明显漏读；这
                # 仍会拦截 27/18/73 等截断结果，同时允许稳定的四位数余额。
                主资源疑似漏读 = (
                    max(金币文本, 圣水文本) >= 1_000_000
                    and min(金币文本, 圣水文本) < 1_000
                )
                主资源超出上限 = max(金币文本, 圣水文本) > self.主资源读数上限
                OCR读数可信 = bool(非零资源) and not (
                    (金币文本 < 1000 and 圣水文本 < 1000)
                    or (len(低位资源) >= 2 and sum(资源值列表) < 2000)
                    or 主资源疑似漏读
                    or 主资源超出上限
                )
                结果 = {
                    "金币": 金币文本,
                    "圣水": 圣水文本,
                    "黑油": 黑油文本,
                    "总资源": 金币文本 + 圣水文本,
                    "识别成功": OCR读数可信,
                }
                if not OCR读数可信:
                    结果["识别错误"] = (
                        f"OCR读数疑似截断或漏读：金币={金币文本},圣水={圣水文本},黑油={黑油文本}"
                    )
                    上下文.置脚本状态(结果["识别错误"] + "；保留上一份资源状态")
                return 结果
            except Exception as e:
                最后异常 = e
                判断内存异常 = getattr(上下文, "是否内存异常", None)
                触发内存保护 = getattr(上下文, "触发内存保护", None)
                if callable(判断内存异常) and 判断内存异常(e):
                    if callable(触发内存保护):
                        触发内存保护("资源OCR", e)
                    break
                if 尝试次数 < 2:
                    上下文.置脚本状态("资源 OCR 暂时失败，释放会话后重试一次")
                    重置会话 = getattr(self.ocr引擎, "重置会话", None)
                    已重置 = False
                    if callable(重置会话):
                        try:
                            已重置 = bool(重置会话())
                        except Exception as 重置异常:
                            上下文.置脚本状态(f"资源 OCR 会话重置失败：{重置异常}")
                    if not 已重置:
                        上下文.置脚本状态("资源 OCR 会话仍在冷却窗口，跳过重复重建，避免内存抖动")
                    else:
                        gc.collect()
                    上下文.脚本延时(350)

        上下文.置脚本状态(f"资源识别失败: {最后异常}")
        return {
            "金币": 0,
            "圣水": 0,
            "黑油": 0,
            "总资源": 0,
            "识别成功": False,
            "识别错误": str(最后异常),
        }
