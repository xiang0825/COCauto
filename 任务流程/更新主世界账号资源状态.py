class 更新家乡资源状态任务(基础任务):
    """自动检测并升级城墙"""

    def _完整资源栏复核(self, 资源栏图像) -> tuple[int, int, int] | None:
        """对可疑资源栏做彩色/灰度双路径复核。

        当前 MuMu 实机的圣水数字在彩色整栏 OCR 中偶尔只返回尾段
        ``819777``，而灰度整栏 OCR 能稳定读回 ``17819777``。只有当
        灰度结果把某个资源从“明显过短”恢复到正常数量级时才采用它，
        不用灰度结果无条件覆盖正常彩色读数。
        """
        彩色读数 = self._完整资源栏复核单次(资源栏图像)
        if not hasattr(资源栏图像, "shape") or len(资源栏图像.shape) < 3:
            return 彩色读数
        try:
            灰度图像 = cv2.cvtColor(资源栏图像, cv2.COLOR_BGR2GRAY)
            灰度读数 = self._完整资源栏复核单次(灰度图像)
        except (AttributeError, TypeError, ValueError, cv2.error):
            灰度读数 = None
        if 彩色读数 is None:
            return 灰度读数
        if 灰度读数 is None:
            return 彩色读数
        # 金币/圣水正常通常至少为百万级；黑油达到十万级即可视为
        # 已恢复。只在灰度结果跨过对应的可信门槛时替换单次结果。
        for 索引, 门槛 in ((0, 2_000_000), (1, 2_000_000), (2, 100_000)):
            if 彩色读数[索引] < 门槛 <= 灰度读数[索引]:
                return 灰度读数
        return 彩色读数

    def _完整资源栏复核单次(self, 资源栏图像) -> tuple[int, int, int] | None:
        """对可疑的三行资源栏做一次整块 OCR，并按文字坐标归位。

        单行轻量 OCR 在主世界刚回营、资源动画或上下行间距变化时，
        可能把圣水/黑水行裁到邻行，只留下较短数字。整块检测 OCR 能
        同时看到三行文字；这里只在可疑读数时调用，避免常态重复加载
        ONNX 检测模型造成内存峰值。
        """
        try:
            结果, _ = self.ocr引擎(资源栏图像, use_cls=False)
            高, 宽 = 资源栏图像.shape[:2]
            行候选 = {0: [], 1: [], 2: []}
            # 不把三行写死在固定 y 坐标。不同 MuMu/CoC 版本、转场动画
            # 和窗口缩放会让资源行在裁剪区内上下移动；实机 1280×720
            # 画面曾出现约 34/90/145，而旧测试样本是约 33/69/103。
            # 先收集右侧数字候选，随后按 y 从上到下分组。
            数字候选 = []
            for 项 in (结果 or []):
                if not isinstance(项, (list, tuple)) or len(项) < 3:
                    continue
                框, 原文, 置信度 = 项[0], 项[1], 项[2]
                try:
                    点 = [
                        (float(坐标[0]), float(坐标[1]))
                        for 坐标 in 框
                        if len(坐标) >= 2
                    ]
                    if not 点:
                        continue
                    中心x = sum(点x for 点x, _ in 点) / len(点)
                    中心y = sum(点y for _, 点y in 点) / len(点)
                    # 资源数字在裁剪区域右侧；排除左侧图标、背景噪声。
                    if 中心x < 宽 * 0.35 or 中心x > 宽 * 0.98:
                        continue
                    文本 = unicodedata.normalize("NFKC", str(原文))
                    数字 = "".join(字符 for 字符 in 文本 if 字符 in "0123456789")
                    if not 数字:
                        continue
                    数字候选.append((中心y, 中心x, 数字, float(置信度)))
                except (TypeError, ValueError, IndexError):
                    continue

            数字候选.sort(key=lambda 项: 项[0])
            行分组 = []
            行容差 = max(8.0, 高 * 0.08)
            for 候选 in 数字候选:
                if not 行分组 or abs(候选[0] - 行分组[-1][0][0]) > 行容差:
                    行分组.append([候选])
                else:
                    行分组[-1].append(候选)

            # 正常整栏 OCR 会得到三行；若检测器额外返回了背景数字，
            # 回退到每行最高置信度，仍要求三行都有明确候选。
            if len(行分组) == 3:
                for 行号, 分组 in enumerate(行分组):
                    行候选[行号] = [
                        (项[2], 项[3]) for 项 in 分组
                    ]
            else:
                # 兼容旧版固定布局样本，同时不让缺失行被猜成 0。
                目标行 = (0.20 * 高, 0.43 * 高, 0.64 * 高)
                for 中心y, _, 数字, 置信度 in 数字候选:
                    行号 = min(
                        range(3),
                        key=lambda 索引: abs(中心y - 目标行[索引]),
                    )
                    行候选[行号].append((数字, 置信度))

            读数 = []
            for 行号 in range(3):
                if not 行候选[行号]:
                    return None
                数字, _ = max(
                    行候选[行号],
                    key=lambda 项: (项[1], len(项[0])),
                )
                读数.append(int(数字))
            if 读数[2] > 1_000_000:
                return None
            return tuple(读数)
        except (AttributeError, TypeError, ValueError, IndexError):
            return None

    def 执行(self) -> bool:
        上下文 = self.上下文
        # 主世界上可能自动弹出“正在升级/立即完成”详情面板。先只点
        # 已确认的右上角关闭按钮；如果关闭后无法确认主页，宁可保留
        # 上一份资源状态，也不在遮罩层上做 OCR 或写入错误的 27/0/73。
        关闭升级面板 = getattr(上下文, "关闭升级详情弹窗", None)
        if callable(关闭升级面板):
            关闭升级面板()
            if getattr(上下文, "页面恢复失败", False):
                上下文.置脚本状态(
                    "资源识别前未确认主世界主页，保留上一份资源状态"
                )
                return False
        上下文.脚本延时(random.randint(500, 1000))#等待资源界面数字固定再执行识别
        资源字典=self.识别当前资源(上下文)
        # 给调用方留下本轮识别结果。识别失败时数据库可能从未有过
        # 家乡资源状态，调用方必须把它视为“未知”，不能当作 0。
        上下文._最近资源识别结果 = dict(资源字典 or {})
        上下文._最近资源识别成功 = bool(
            资源字典.get("识别成功", False)
            and all(字段 in 资源字典 for 字段 in ("金币", "圣水", "黑油"))
        )
        上下文.置脚本状态("主世界资源识别结果："+str(资源字典))
        if not 上下文._最近资源识别成功:
            # OCR/ONNX 临时分配失败时不能把上一份真实资源覆盖成 0，
            # 否则下一轮会计算出巨额负收益并误判资源状态。
            上下文.置脚本状态("本次资源识别未完成，保留上一份资源状态，不覆盖数据库")
            return False
        上下文.数据库.更新状态(上下文.机器人标志,"家乡资源",资源字典)
        return True

    def 识别当前资源(self, 上下文) -> dict:
        """从主城右上角读取金币、圣水和黑水。

        资源数字在不同版本的右上角位置会有少量变化，使用完整右侧
        210×160 区域而不是旧的 138×134 裁剪，避免数字被边界截断。
        """
        最后异常 = None
        for 尝试次数 in range(1, 3):
            try:
                全屏图像 = 上下文.op.获取屏幕图像cv(590, 0, 800, 160)

                def 切分资源行(图像):
                    """按资源栏实际占用的上方区域切分，并保留行间重叠。"""
                    h = 图像.shape[0]
                    # 请求区域高为160时，三行资源文字实际集中在前约
                    # 120px；等分整个160px会把黑油行从文字底部开始裁剪，
                    # 实机会把362,905读成36,295。每行使用约35%高度，
                    # 步长约25%，既覆盖完整数字又允许主题/缩放有小偏移。
                    行高 = max(1, int(round(h * 0.35)))
                    步长 = max(1, int(round(h * 0.25)))
                    return (
                        图像[0:min(h, 行高), :],
                        图像[步长:min(h, 步长 + 行高), :],
                        图像[2 * 步长:min(h, 2 * 步长 + 行高), :],
                    )

                金币图, 圣水图, 黑油图 = 切分资源行(全屏图像)

                资源行图像 = (金币图, 圣水图, 黑油图)
                金币文本 = 单行资源识别(self.ocr引擎, 金币图)
                圣水文本 = 单行资源识别(self.ocr引擎, 圣水图)
                黑油文本 = 单行资源识别(
                    self.ocr引擎, 黑油图, 最大值=1_000_000
                )
                已完成整栏复核 = False

                # 主资源已经是百万级、高本常见的圣水/黑水却突然变成
                # 短数字时，说明单行切分可能错位。先对整块资源栏做复核，
                # 再决定是否进入逐行完整 OCR 回退，避免错误读数先参与后续
                # 判断，也避免重复创建 OCR 会话造成内存抖动。
                需要整栏复核 = (
                    金币文本 == 0
                    or 圣水文本 == 0
                    or (0 < 金币文本 < 2_000_000)
                    or (0 < 圣水文本 < 2_000_000)
                    or (
                        # 黑油栏在当前 MuMu 1280×720 画面中会被逐行
                        # 轻量 OCR 截成 1 位（例如真实 52059 读成 7）。
                        # 不能只在主资源达到千万时复核：普通资源余额
                        # 8m/4m 同样会触发这个误读。只要主资源已确认
                        # 为正常的百万级，就用整栏坐标 OCR 重新归位。
                        max(金币文本, 圣水文本) >= 1_000_000
                        and 黑油文本 < 100_000
                    )
                )
                if 需要整栏复核:
                    完整读数 = self._完整资源栏复核(全屏图像)
                    if 完整读数 is not None:
                        金币文本, 圣水文本, 黑油文本 = 完整读数
                        已完成整栏复核 = True
                        上下文.置脚本状态(
                            "资源栏可疑读数已完成整栏OCR复核，按文字坐标重新归位"
                        )

                # 自适应 16:9 画面中，轻量 OCR 可能漏掉主资源数字的首位，
                # 例如把 14,552,022 读成 1,455,202；这类错误仍然是七位数，
                # 不能只用“低于一百万”判断。低于 2,000,000 的主资源读数
                # 走一次完整检测 OCR；真实低余额也会得到同一个完整结果，
                # 因而不会误判资源，只增加低余额/可疑读数时的复核成本。
                if (
                    金币文本 == 0
                    or 圣水文本 == 0
                    or (0 < 金币文本 < 2_000_000)
                    or (0 < 圣水文本 < 2_000_000)
                ):
                    金币文本 = 单行资源识别(
                        self.ocr引擎, 资源行图像[0], 允许完整识别=True
                    )
                    圣水文本 = 单行资源识别(
                        self.ocr引擎, 资源行图像[1], 允许完整识别=True
                    )
                # 黑油数字通常较短；低于五位时仍可能漏掉首位，使用完整
                # OCR 复核。先完成主资源回退，再用可信的主资源判断是否
                # 值得触发这条较重路径，避免每帧都加载检测模型。
                if (
                    (黑油文本 == 0 or 黑油文本 < 100_000)
                    and max(金币文本, 圣水文本) >= 1_000_000
                    and not 已完成整栏复核
                ):
                    黑油文本 = 单行资源识别(
                        self.ocr引擎, 资源行图像[2],
                        允许完整识别=True, 最大值=1_000_000
                    )

                # 金币和圣水不应同时识别为 0；出现这种情况通常是界面仍在
                # 切换或截图被遮挡，换用更紧的右侧区域重试一次。
                if 金币文本 == 0 and 圣水文本 == 0:
                    右侧图像 = 上下文.op.获取屏幕图像cv(680, 0, 800, 160)
                    金币图, 圣水图, 黑油图 = 切分资源行(右侧图像)
                    金币文本 = 单行资源识别(
                        self.ocr引擎, 金币图, 允许完整识别=True
                    )
                    圣水文本 = 单行资源识别(
                        self.ocr引擎, 圣水图, 允许完整识别=True
                    )
                    黑油文本 = 单行资源识别(
                        self.ocr引擎, 黑油图,
                        允许完整识别=True, 最大值=1_000_000
                    )

                资源值列表 = (金币文本, 圣水文本, 黑油文本)
                非零资源 = [值 for 值 in 资源值列表 if int(值 or 0) > 0]
                低位资源 = [值 for 值 in 非零资源 if int(值) < 1000]
                # 正常主城金币/圣水容量至少是千级；两个主资源都只有
                # 两三位数，或三项合计仍很小，通常是弹窗/过渡帧被 OCR
                # 截断。不能把它当成成功结果覆盖数据库。
                # 一项主资源达到百万级而另一项为 0/极低，通常是资源行
                # 漏读，而不是可信余额。整栏复核已经按三行文字坐标重新
                # 归位时，低余额可能是真实的（例如圣水只有 2318），
                # 不能再用“低于十万”一刀切，否则刷资源永远看不到真实
                # 的低资源状态。只把低于千级的主资源视为明显漏读；这
                # 仍会拦截 27/18/73 等截断结果，同时允许稳定的四位数余额。
                主资源疑似漏读 = (
                    max(金币文本, 圣水文本) >= 1_000_000
                    and min(金币文本, 圣水文本) < 1_000
                )
                OCR读数可信 = bool(非零资源) and not (
                    (金币文本 < 1000 and 圣水文本 < 1000)
                    or (len(低位资源) >= 2 and sum(资源值列表) < 2000)
                    or 主资源疑似漏读
                )
                结果 = {
                    "金币": 金币文本,
                    "圣水": 圣水文本,
                    "黑油": 黑油文本,
                    "总资源": 金币文本 + 圣水文本,
                    "识别成功": OCR读数可信,
                }
                if not OCR读数可信:
                    结果["识别错误"] = (
                        f"OCR读数疑似截断或漏读：金币={金币文本},圣水={圣水文本},黑油={黑油文本}"
                    )
                    上下文.置脚本状态(结果["识别错误"] + "；保留上一份资源状态")
                return 结果
            except Exception as e:
                最后异常 = e
                判断内存异常 = getattr(上下文, "是否内存异常", None)
                触发内存保护 = getattr(上下文, "触发内存保护", None)
                if callable(判断内存异常) and 判断内存异常(e):
                    if callable(触发内存保护):
                        触发内存保护("资源OCR", e)
                    break
                if 尝试次数 < 2:
                    上下文.置脚本状态("资源 OCR 暂时失败，释放会话后重试一次")
                    重置会话 = getattr(self.ocr引擎, "重置会话", None)
                    已重置 = False
                    if callable(重置会话):
                        try:
                            已重置 = bool(重置会话())
                        except Exception as 重置异常:
                            上下文.置脚本状态(f"资源 OCR 会话重置失败：{重置异常}")
                    if not 已重置:
                        上下文.置脚本状态("资源 OCR 会话仍在冷却窗口，跳过重复重建，避免内存抖动")
                    else:
                        gc.collect()
                    上下文.脚本延时(350)

        上下文.置脚本状态(f"资源识别失败: {最后异常}")
        return {
            "金币": 0,
            "圣水": 0,
            "黑油": 0,
            "总资源": 0,
            "识别成功": False,
            "识别错误": str(最后异常),
        }
