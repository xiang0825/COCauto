import gc

from 任务流程.基础任务框架 import 任务上下文, 基础任务
from 模块.检测.OCR识别器 import 安全OCR引擎
from 模块.检测.YOLO检测器 import 线程安全YOLO检测器
from 模块.检测.模板匹配器 import 模板匹配引擎
import random
from 工具包.工具函数 import 单行资源识别


class 更新家乡资源状态任务(基础任务):
    """自动检测并升级城墙"""

    def 执行(self) -> bool:
        上下文 = self.上下文
        # 主世界上可能自动弹出“正在升级/立即完成”详情面板。先只点
        # 已确认的右上角关闭按钮；如果关闭后无法确认主页，宁可保留
        # 上一份资源状态，也不在遮罩层上做 OCR 或写入错误的 27/0/73。
        关闭升级面板 = getattr(上下文, "关闭升级详情弹窗", None)
        if callable(关闭升级面板):
            关闭升级面板()
            if getattr(上下文, "页面恢复失败", False):
                上下文.置脚本状态(
                    "资源识别前未确认主世界主页，保留上一份资源状态"
                )
                return False
        上下文.脚本延时(random.randint(500, 1000))#等待资源界面数字固定再执行识别
        资源字典=self.识别当前资源(上下文)
        # 给调用方留下本轮识别结果。识别失败时数据库可能从未有过
        # 家乡资源状态，调用方必须把它视为“未知”，不能当作 0。
        上下文._最近资源识别结果 = dict(资源字典 or {})
        上下文._最近资源识别成功 = bool(
            资源字典.get("识别成功", False)
            and all(字段 in 资源字典 for 字段 in ("金币", "圣水", "黑油"))
        )
        上下文.置脚本状态("主世界资源识别结果："+str(资源字典))
        if not 上下文._最近资源识别成功:
            # OCR/ONNX 临时分配失败时不能把上一份真实资源覆盖成 0，
            # 否则下一轮会计算出巨额负收益并误判资源状态。
            上下文.置脚本状态("本次资源识别未完成，保留上一份资源状态，不覆盖数据库")
            return False
        上下文.数据库.更新状态(上下文.机器人标志,"家乡资源",资源字典)
        return True

    def 识别当前资源(self, 上下文) -> dict:
        """从主城右上角读取金币、圣水和黑水。

        资源数字在不同版本的右上角位置会有少量变化，使用完整右侧
        210×160 区域而不是旧的 138×134 裁剪，避免数字被边界截断。
        """
        最后异常 = None
        for 尝试次数 in range(1, 3):
            try:
                全屏图像 = 上下文.op.获取屏幕图像cv(590, 0, 800, 160)

                h = 全屏图像.shape[0]
                row_h = h // 3

                金币图 = 全屏图像[0:row_h, :]
                圣水图 = 全屏图像[row_h:row_h*2, :]
                黑油图 = 全屏图像[row_h*2:h, :]

                资源行图像 = (金币图, 圣水图, 黑油图)
                金币文本 = 单行资源识别(self.ocr引擎, 金币图)
                圣水文本 = 单行资源识别(self.ocr引擎, 圣水图)
                黑油文本 = 单行资源识别(
                    self.ocr引擎, 黑油图, 最大值=1_000_000
                )

                # 自适应 16:9 画面中，轻量 OCR 可能漏掉主资源数字的首位，
                # 例如把 14,552,022 读成 1,455,202；这类错误仍然是七位数，
                # 不能只用“低于一百万”判断。低于 2,000,000 的主资源读数
                # 走一次完整检测 OCR；真实低余额也会得到同一个完整结果，
                # 因而不会误判资源，只增加低余额/可疑读数时的复核成本。
                if (
                    金币文本 == 0
                    or 圣水文本 == 0
                    or (0 < 金币文本 < 2_000_000)
                    or (0 < 圣水文本 < 2_000_000)
                ):
                    金币文本 = 单行资源识别(
                        self.ocr引擎, 资源行图像[0], 允许完整识别=True
                    )
                    圣水文本 = 单行资源识别(
                        self.ocr引擎, 资源行图像[1], 允许完整识别=True
                    )
                # 黑油数字通常较短；低于五位时仍可能漏掉首位，使用完整
                # OCR 复核。先完成主资源回退，再用可信的主资源判断是否
                # 值得触发这条较重路径，避免每帧都加载检测模型。
                if (
                    (黑油文本 == 0 or 黑油文本 < 10_000)
                    and max(金币文本, 圣水文本) >= 1_000_000
                ):
                    黑油文本 = 单行资源识别(
                        self.ocr引擎, 资源行图像[2],
                        允许完整识别=True, 最大值=1_000_000
                    )

                # 金币和圣水不应同时识别为 0；出现这种情况通常是界面仍在
                # 切换或截图被遮挡，换用更紧的右侧区域重试一次。
                if 金币文本 == 0 and 圣水文本 == 0:
                    右侧图像 = 上下文.op.获取屏幕图像cv(680, 0, 800, 160)
                    h = 右侧图像.shape[0]
                    金币文本 = 单行资源识别(
                        self.ocr引擎, 右侧图像[:h // 3, :], 允许完整识别=True
                    )
                    圣水文本 = 单行资源识别(
                        self.ocr引擎,
                        右侧图像[h // 3:h * 2 // 3, :],
                        允许完整识别=True,
                    )
                    黑油文本 = 单行资源识别(
                        self.ocr引擎, 右侧图像[h * 2 // 3:h, :],
                        允许完整识别=True, 最大值=1_000_000
                    )

                资源值列表 = (金币文本, 圣水文本, 黑油文本)
                非零资源 = [值 for 值 in 资源值列表 if int(值 or 0) > 0]
                低位资源 = [值 for 值 in 非零资源 if int(值) < 1000]
                # 正常主城金币/圣水容量至少是千级；两个主资源都只有
                # 两三位数，或三项合计仍很小，通常是弹窗/过渡帧被 OCR
                # 截断。不能把它当成成功结果覆盖数据库。
                OCR读数可信 = bool(非零资源) and not (
                    (金币文本 < 1000 and 圣水文本 < 1000)
                    or (len(低位资源) >= 2 and sum(资源值列表) < 2000)
                )
                结果 = {
                    "金币": 金币文本,
                    "圣水": 圣水文本,
                    "黑油": 黑油文本,
                    "总资源": 金币文本 + 圣水文本,
                    "识别成功": OCR读数可信,
                }
                if not OCR读数可信:
                    结果["识别错误"] = (
                        f"OCR读数疑似截断：金币={金币文本},圣水={圣水文本},黑油={黑油文本}"
                    )
                    上下文.置脚本状态(结果["识别错误"] + "；保留上一份资源状态")
                return 结果
            except Exception as e:
                最后异常 = e
                判断内存异常 = getattr(上下文, "是否内存异常", None)
                触发内存保护 = getattr(上下文, "触发内存保护", None)
                if callable(判断内存异常) and 判断内存异常(e):
                    if callable(触发内存保护):
                        触发内存保护("资源OCR", e)
                    break
                if 尝试次数 < 2:
                    上下文.置脚本状态("资源 OCR 暂时失败，释放会话后重试一次")
                    重置会话 = getattr(self.ocr引擎, "重置会话", None)
                    已重置 = False
                    if callable(重置会话):
                        try:
                            已重置 = bool(重置会话())
                        except Exception as 重置异常:
                            上下文.置脚本状态(f"资源 OCR 会话重置失败：{重置异常}")
                    if not 已重置:
                        上下文.置脚本状态("资源 OCR 会话仍在冷却窗口，跳过重复重建，避免内存抖动")
                    else:
                        gc.collect()
                    上下文.脚本延时(350)

        上下文.置脚本状态(f"资源识别失败: {最后异常}")
        return {
            "金币": 0,
            "圣水": 0,
            "黑油": 0,
            "总资源": 0,
            "识别成功": False,
            "识别错误": str(最后异常),
        }
