import random
import time
from dataclasses import dataclass

import numpy as np

from 任务流程.基础任务框架 import 基础任务, 任务上下文
from 工具包.工具函数 import 生成贝塞尔轨迹
from 模块.检测.模板匹配器 import 模板匹配引擎
from 任务流程.世界跳转.世界识别器 import 世界识别器

@dataclass
class 滑动配置:
    起点: tuple[int, int]
    终点: tuple[int, int]

class 进入世界任务基类(基础任务):
    # 世界切换船在当前国际服自适应画布中位于左下地图边缘。旧实现
    # 在全屏搜索 15~24 像素模板，容易把顶部资源/地图纹理当成船；
    # 这里限制搜索区，避免误点其它 UI。区域按 800×600 逻辑画布工作，
    # 由 ADB 屏幕层自动映射到任意实际分辨率。
    # 排除左下角护盾/攻城入口等固定 UI。拖动地图后，1280×720 实机
    # 的飞艇会落在 800×600 参考坐标约 x=225、y=417；旧区域只搜底边，
    # 会漏掉飞艇并把底部地图纹理当成入口。
    世界入口搜索区域 = (100, 350, 400, 590)
    # 旧船局部模板在首次主世界画面中容易得到 0.55~0.65 的地图纹理
    # 假分数；颜色/几何候选只用于记录和搜索线索，模板只保留高置信命中。
    世界入口最低分数 = 0.78
    # 镜头移动后飞艇可能离开原左下区域。子类可声明地图备用区；
    # 备用区仍只允许高置信模板命中，颜色候选绝不授权点击。
    世界入口备用搜索区域 = None

    def __init__(self, 上下文: 任务上下文, 判断图标路径: str, 船模板路径: str, 状态文本: str,滑动参数: 滑动配置):
        super().__init__(上下文)
        self.判断图标路径 = 判断图标路径
        self.船模板路径 = 船模板路径
        self.状态文本 = 状态文本
        self.滑动配置 = 滑动参数
        self.世界识别 = 世界识别器(self.模板识别)
        self._上次世界识别日志 = None
        self._上次世界识别日志时间 = 0.0

    def 执行(self) -> bool:
        try:
            上下文 = self.上下文
            # 活动/奖励面板会保留主世界 HUD，不能让世界识别器直接把
            # 背景主页当成可点击页面。先只关闭已经被专用检测器确认的
            # 右上角 X，失败或未识别时不发送任何额外输入。
            清理活动弹窗 = getattr(上下文, "清理主世界活动弹窗", None)
            if callable(清理活动弹窗) and 清理活动弹窗():
                上下文.置脚本状态("已关闭主世界活动/奖励弹窗，重新确认世界后再切换")
                上下文.脚本延时(500)
            关闭升级面板 = getattr(上下文, "关闭升级详情弹窗", None)
            if callable(关闭升级面板) and 关闭升级面板():
                上下文.置脚本状态("已关闭升级详情面板，重新确认世界后再切换")
                上下文.脚本延时(500)
            if getattr(上下文, "页面恢复失败", False):
                上下文.置脚本状态("切换世界前未确认主页，禁止入口点击")
                return False
            if self.是否在目标世界():
                上下文.置脚本状态(f"已经在{self.状态文本}")
                return True
            if self._页面级确认目标世界(上下文):
                上下文.置脚本状态(f"页面识别已确认在{self.状态文本}，跳过入口点击")
                return True
            else:
                上下文.置脚本状态(f"开始尝试进入{self.状态文本}")

            按钮区域 = (0, 0, 800, 600)
            超时时间 = 30
            开始时间 = time.time()
            未知页面轮次 = 0
            上次入口坐标 = None
            同一点点击次数 = 0
            搜索滑动序号 = 0

            while time.time() - 开始时间 < 超时时间:
                if callable(清理活动弹窗) and 清理活动弹窗():
                    上下文.置脚本状态("切换前再次关闭活动/奖励弹窗，暂停后重新识别")
                    上下文.脚本延时(500)
                if callable(关闭升级面板) and 关闭升级面板():
                    上下文.置脚本状态("切换前关闭升级详情面板，暂停后重新识别")
                    上下文.脚本延时(500)
                if getattr(上下文, "页面恢复失败", False):
                    上下文.置脚本状态("切换前面板处理后未确认主页，禁止入口点击")
                    return False
                当前世界 = self.识别当前世界().当前世界
                if 当前世界 == self.状态文本:
                    上下文.置脚本状态(f"成功进入{self.状态文本}")
                    return True
                if self._页面级确认目标世界(上下文):
                    上下文.置脚本状态(f"页面识别已确认成功进入{self.状态文本}")
                    return True

                # 未确认页面时绝不能点击、滑动或发送 ESC。过去这里会
                # 继续尝试拖动地图，启动中的 CoC 可能尚未完成渲染，任何
                # 手势都会把状态机带到不可复现的页面。连续短暂观察后安全
                # 停止，由上层记录现场，而不是“猜测”下一步操作。
                if 当前世界 == "未知":
                    未知页面轮次 += 1
                    上下文.置脚本状态(
                        f"世界未确认（第{未知页面轮次}/3次），禁止点击、滑动、ESC或返回键"
                    )
                    if 未知页面轮次 >= 3:
                        上下文.置脚本状态(
                            "世界识别连续失败，未发送任何输入；安全停止当前任务以保留游戏前台"
                        )
                        return False
                    上下文.脚本延时(1000)
                    continue

                屏幕图像 = 上下文.op.获取屏幕图像cv(*按钮区域)
                是否匹配, (x, y), 入口分数 = self.查找世界入口(屏幕图像)

                if 是否匹配:
                    当前入口坐标 = (int(x), int(y))
                    if 当前入口坐标 == 上次入口坐标:
                        同一点点击次数 += 1
                    else:
                        上次入口坐标 = 当前入口坐标
                        同一点点击次数 = 1
                    # 真正的世界切换入口一次点击就应进入转场；同一
                    # 坐标连续两次仍停留在原世界，说明是低分误匹配或
                    # 入口被遮挡。停止输入并保留画面，禁止循环连点。
                    if 同一点点击次数 >= 2:
                        上下文.置脚本状态(
                            f"同一世界入口{当前入口坐标[0]},{当前入口坐标[1]}连续点击后仍未转场，"
                            "停止入口点击并保留当前页面"
                        )
                        return False
                    点击结果 = 上下文.点击(x, y)
                    if 点击结果 is False:
                        上下文.页面恢复失败 = True
                        上下文.置脚本状态(
                            f"世界入口{x},{y}未被输入层接受，停止继续切换和拖动"
                        )
                        return False
                    上下文.置脚本状态(
                        f"已确认世界入口（分数{入口分数:.2f}），尝试进入{self.状态文本}"
                    )
                    # 点击入口后先进入一个无输入确认窗口。转场动画可能
                    # 暂时保留上一世界资源栏；若立刻拖动地图，会把已经
                    # 成功切换的目标世界再次拖乱，随后永远等不到目标。
                    if self._等待目标世界确认(上下文):
                        上下文.置脚本状态(f"入口转场确认成功进入{self.状态文本}")
                        return True
                    continue

                # 只有已确认处于另一世界时，才允许拖动地图寻找入口。
                # 这条路径没有任何 ESC/返回键恢复逻辑。
                上下文.置脚本状态(
                    f"当前已确认处于{当前世界}，未找到{self.状态文本}入口；仅拖动地图搜索"
                )
                上次入口坐标 = None
                同一点点击次数 = 0
                滑动参数 = self._获取本轮搜索滑动配置(搜索滑动序号)
                搜索滑动序号 += 1
                self.滑动屏幕(上下文, 滑动参数.起点, 滑动参数.终点)
                上下文.脚本延时(1000)

            raise RuntimeError(f"操作超时：未找到{self.状态文本}入口")
        except Exception as e:
            self.异常处理(e)
            return False


    def _页面级确认目标世界(self, 上下文) -> bool:
        """用点击护栏的页级结果补充世界资源识别的转场过渡帧。

        世界切换后的短暂画面可能同时保留上一世界资源栏和当前世界
        的主页 UI，单独依赖资源模板会把已经完成的切换误判为原世界。
        页级识别只有在明确得到目标主页、目标世界和足够置信度时才可
        确认，不会对未知页或战斗/结算页发送任何输入。
        """
        识别 = getattr(上下文, "识别点击画面", None)
        if not callable(识别):
            return False
        try:
            try:
                结果 = 识别(强制=True)
            except TypeError:
                结果 = 识别()
        except Exception as 异常:
            上下文.置脚本状态(f"页面级世界确认失败：{异常}")
            return False
        页面 = str(getattr(结果, "页面", "") or "")
        世界 = str(getattr(结果, "世界", "") or "")
        可信度 = float(getattr(结果, "可信度", 0.0) or 0.0)
        return (
            页面 == f"{self.状态文本}主页"
            and 世界 == self.状态文本
            and 可信度 >= 0.70
        )

    def _等待目标世界确认(self, 上下文, 尝试次数: int = 5) -> bool:
        """点击入口后用多帧确认目标世界，期间不发送任何输入。"""
        尝试次数 = max(1, int(尝试次数))
        for 序号 in range(尝试次数):
            try:
                if self.识别当前世界().当前世界 == self.状态文本:
                    return True
            except Exception as 异常:
                上下文.置脚本状态(f"入口转场世界识别失败：{异常}")
            if self._页面级确认目标世界(上下文):
                return True
            if 序号 + 1 < 尝试次数:
                上下文.脚本延时(500)
        return False

    def _获取本轮搜索滑动配置(self, 序号: int) -> 滑动配置:
        """返回不会触碰系统/功能栏的地图搜索方向。"""
        路径列表 = getattr(self, "世界入口搜索滑动路径", None)
        if not 路径列表:
            return self.滑动配置
        try:
            return 路径列表[int(序号) % len(路径列表)]
        except (TypeError, ValueError, IndexError):
            return self.滑动配置


    def 是否在目标世界(self) -> bool:
        """用资源栏和世界入口共同确认当前世界。

        旧实现把一个 15~19 像素的小图标放在整屏搜索，地图动画很容易
        误命中。现在世界识别器只搜索右上角资源栏和左下角入口，并记录
        主/夜两套分数；分数接近时返回 False，让执行流程先恢复页面，
        不在未知页面继续点击。
        """
        识别结果 = self.识别当前世界()
        return 识别结果.当前世界 == self.状态文本

    def 查找世界入口(self, 屏幕图像):
        """只在左下安全区域查找世界切换船并返回逻辑画布坐标。

        船素材是早期采集的极小局部图，当前测试服缩放后分数会随镜头
        变化。这里使用多模板最佳分数而不是首个模板布尔命中，再叠加
        固定安全区域、可选地图备用区域和 0.78 下限。模板命中的是船帆
        局部，实机可点击的船体中心约在其左 25、下 26 个逻辑像素，
        所以点击后仍会重新识别世界，不会把普通地图纹理当成成功转场。
        """
        if not isinstance(屏幕图像, np.ndarray) or 屏幕图像.ndim < 2:
            return False, (0, 0), 0.0
        # 世界入口坐标和模板区域统一按 800×600 逻辑画布计算。正常
        # 路径会由 ADB屏幕先完成缩放，但部分旧适配器/启动过渡帧可能
        # 直接传入 MuMu 的 1280×720 原图；若把原图按逻辑坐标裁剪，
        # 右上飞艇会被裁到搜索区之外，表现为“入口明明在画面上却找不到”。
        # 这里再做一次轻量归一化，保证入口识别不会依赖调用方的截图层。
        if 屏幕图像.shape[1] != 800 or 屏幕图像.shape[0] != 600:
            try:
                import cv2
                屏幕图像 = cv2.resize(
                    屏幕图像, (800, 600), interpolation=cv2.INTER_AREA
                )
            except Exception:
                return False, (0, 0), 0.0
        左, 上, 右, 下 = self.世界入口搜索区域
        高, 宽 = 屏幕图像.shape[:2]
        左 = max(0, min(宽, int(左)))
        右 = max(左, min(宽, int(右)))
        上 = max(0, min(高, int(上)))
        下 = max(上, min(高, int(下)))
        区域 = 屏幕图像[上:下, 左:右]
        if 区域.size == 0:
            return False, (0, 0), 0.0

        # 当前国际服实机的船体会随拉远视距缩放，旧采集模板有时只会
        # 命中船帆旁边的地图纹理。颜色/几何条件只用于诊断和搜索线索，
        # 不直接生成点击；最终必须由安全区域内的高置信船模板授权。
        try:
            import cv2

            hsv = cv2.cvtColor(区域, cv2.COLOR_BGR2HSV)
            橙红 = cv2.inRange(
                hsv,
                np.array((0, 70, 60), dtype=np.uint8),
                np.array((28, 255, 255), dtype=np.uint8),
            )
            橙红 |= cv2.inRange(
                hsv,
                np.array((168, 70, 60), dtype=np.uint8),
                np.array((180, 255, 255), dtype=np.uint8),
            )
            橙红 = cv2.morphologyEx(
                橙红,
                cv2.MORPH_CLOSE,
                cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (7, 7)),
            )
            数量, _, 统计, 重心 = cv2.connectedComponentsWithStats(橙红, 8)
            颜色候选 = []
            for 索引 in range(1, 数量):
                局部x, 局部y, 方宽, 方高, 面积 = [int(v) for v in 统计[索引]]
                if (
                    面积 < 300
                    or 方宽 < 25
                    or 方高 < 25
                    or 方宽 > 90
                    or 方高 > 90
                    or not 0.35 <= 方宽 / max(1, 方高) <= 2.5
                ):
                    continue
                中心x, 中心y = 重心[索引]
                全局中心x = float(中心x) + 左
                全局中心y = float(中心y) + 上
                # 真实飞艇位于左下海岸带；普通地图建筑也会产生橙色
                # 连通块，实机曾将 x≈166,y≈384 的建筑误判成飞艇。
                # 收窄到真实海岸船体的 x/y 带，模板低分时也不能靠
                # 任意橙色块直接点击。
                if not (200 <= 全局中心x <= 320 and 390 <= 全局中心y <= 500):
                    continue
                颜色候选.append((面积, 局部x, 局部y, 方宽, 方高, 重心[索引]))
            if 颜色候选:
                # 颜色候选只作为调试/搜索线索，禁止单独产生点击。
                # 实机已复现普通建筑也能满足橙色几何条件；只有后面的
                # 高置信船模板才能授权输入，未命中时让上层拖动地图后
                # 重新搜索。
                pass
        except (AttributeError, TypeError, ValueError, cv2.error):
            pass

        最佳匹配 = getattr(self.模板识别, "执行最佳匹配", None)
        if callable(最佳匹配):
            # 先扫原有窄区域，保留历史坐标与误点护栏；低分时再扫
            # 子类声明的地图备用区，解决镜头移动后飞艇离开左下带的问题。
            区域列表 = [(区域, 左, 上)]
            备用区域 = getattr(self, "世界入口备用搜索区域", None)
            if 备用区域:
                try:
                    备用左, 备用上, 备用右, 备用下 = [int(v) for v in 备用区域]
                    if (备用左, 备用上, 备用右, 备用下) != (左, 上, 右, 下):
                        备用左 = max(0, min(宽, 备用左))
                        备用右 = max(备用左, min(宽, 备用右))
                        备用上 = max(0, min(高, 备用上))
                        备用下 = max(备用上, min(高, 备用下))
                        备用图像 = 屏幕图像[备用上:备用下, 备用左:备用右]
                        if 备用图像.size:
                            区域列表.append((备用图像, 备用左, 备用上))
                except (TypeError, ValueError):
                    pass

            最高分数 = 0.0
            for 候选区域, 候选左, 候选上 in 区域列表:
                try:
                    分数, 中心, _ = 最佳匹配(候选区域, self.船模板路径)
                    分数 = float(分数)
                    最高分数 = max(最高分数, 分数)
                    if 分数 >= self.世界入口最低分数:
                        点击x = int(中心[0]) + 候选左 - 25
                        点击y = int(中心[1]) + 候选上 + 26
                        return True, (点击x, 点击y), 分数
                except Exception:
                    continue
            return False, (0, 0), 最高分数

        # 兼容旧测试替身/旧识图引擎，没有最佳分数接口时仍使用安全区域。
        try:
            命中, 中心, _ = self.模板识别.执行匹配(
                区域, self.船模板路径, 相似度阈值=self.世界入口最低分数
            )
            if 命中:
                点击x = int(中心[0]) + 左 - 25
                点击y = int(中心[1]) + 上 + 26
                return True, (点击x, 点击y), 1.0
        except Exception:
            pass
        return False, (0, 0), 0.0

    def 识别当前世界(self):
        """返回当前截图的完整世界识别结果，供任务和日志复用。"""
        屏幕图像 = self.上下文.op.获取屏幕图像cv(0, 0, 800, 600)
        识别结果 = self.世界识别.识别(屏幕图像)
        self._最近世界识别结果 = 识别结果
        self._记录世界识别结果(识别结果)
        return 识别结果

    def _记录世界识别结果(self, 识别结果):
        """节流记录识别依据，便于从运行日志定位误判。"""
        摘要 = 识别结果.摘要()
        现在 = time.monotonic()
        日志键 = (识别结果.当前世界, 摘要)
        if (
            日志键 != self._上次世界识别日志
            or 现在 - self._上次世界识别日志时间 >= 3.0
        ):
            self.上下文.置脚本状态(f"世界识别：{摘要}")
            self._上次世界识别日志 = 日志键
            self._上次世界识别日志时间 = 现在

