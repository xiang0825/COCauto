import random
import time
from dataclasses import dataclass

import numpy as np

from 任务流程.基础任务框架 import 基础任务, 任务上下文
from 工具包.工具函数 import 生成贝塞尔轨迹
from 模块.检测.模板匹配器 import 模板匹配引擎
from 任务流程.世界跳转.世界识别器 import 世界识别器

@dataclass
class 滑动配置:
    起点: tuple[int, int]
    终点: tuple[int, int]

class 进入世界任务基类(基础任务):
    # 世界切换船在当前国际服自适应画布中位于左下地图边缘。旧实现
    # 在全屏搜索 15~24 像素模板，容易把顶部资源/地图纹理当成船；
    # 这里限制搜索区，避免误点其它 UI。区域按 800×600 逻辑画布工作，
    # 由 ADB 屏幕层自动映射到任意实际分辨率。
    # 排除左下角护盾/攻城入口等固定 UI。1280×720 实机在游戏内拉远
    # 后，船体会落在 800×600 参考坐标约 x=188、y=562；旧区域下边界
    # y=525 会漏掉船体，只在地图纹理上得到低分假匹配。
    世界入口搜索区域 = (160, 450, 280, 590)
    世界入口最低分数 = 0.48

    def __init__(self, 上下文: 任务上下文, 判断图标路径: str, 船模板路径: str, 状态文本: str,滑动参数: 滑动配置):
        super().__init__(上下文)
        self.判断图标路径 = 判断图标路径
        self.船模板路径 = 船模板路径
        self.状态文本 = 状态文本
        self.滑动配置 = 滑动参数
        self.世界识别 = 世界识别器(self.模板识别)
        self._上次世界识别日志 = None
        self._上次世界识别日志时间 = 0.0

    def 执行(self) -> bool:
        try:
            上下文 = self.上下文
            # 活动/奖励面板会保留主世界 HUD，不能让世界识别器直接把
            # 背景主页当成可点击页面。先只关闭已经被专用检测器确认的
            # 右上角 X，失败或未识别时不发送任何额外输入。
            清理活动弹窗 = getattr(上下文, "清理主世界活动弹窗", None)
            if callable(清理活动弹窗) and 清理活动弹窗():
                上下文.置脚本状态("已关闭主世界活动/奖励弹窗，重新确认世界后再切换")
                上下文.脚本延时(500)
            if self.是否在目标世界():
                上下文.置脚本状态(f"已经在{self.状态文本}")
                return True
            else:
                上下文.置脚本状态(f"开始尝试进入{self.状态文本}")

            按钮区域 = (0, 0, 800, 600)
            超时时间 = 30
            开始时间 = time.time()
            未知页面轮次 = 0
            上次入口坐标 = None
            同一点点击次数 = 0

            while time.time() - 开始时间 < 超时时间:
                if callable(清理活动弹窗) and 清理活动弹窗():
                    上下文.置脚本状态("切换前再次关闭活动/奖励弹窗，暂停后重新识别")
                    上下文.脚本延时(500)
                当前世界 = self.识别当前世界().当前世界
                if 当前世界 == self.状态文本:
                    上下文.置脚本状态(f"成功进入{self.状态文本}")
                    return True

                # 未确认页面时绝不能点击、滑动或发送 ESC。过去这里会
                # 继续尝试拖动地图，启动中的 CoC 可能尚未完成渲染，任何
                # 手势都会把状态机带到不可复现的页面。连续短暂观察后安全
                # 停止，由上层记录现场，而不是“猜测”下一步操作。
                if 当前世界 == "未知":
                    未知页面轮次 += 1
                    上下文.置脚本状态(
                        f"世界未确认（第{未知页面轮次}/3次），禁止点击、滑动、ESC或返回键"
                    )
                    if 未知页面轮次 >= 3:
                        上下文.置脚本状态(
                            "世界识别连续失败，未发送任何输入；安全停止当前任务以保留游戏前台"
                        )
                        return False
                    上下文.脚本延时(1000)
                    continue

                屏幕图像 = 上下文.op.获取屏幕图像cv(*按钮区域)
                是否匹配, (x, y), 入口分数 = self.查找世界入口(屏幕图像)

                if 是否匹配:
                    当前入口坐标 = (int(x), int(y))
                    if 当前入口坐标 == 上次入口坐标:
                        同一点点击次数 += 1
                    else:
                        上次入口坐标 = 当前入口坐标
                        同一点点击次数 = 1
                    # 真正的世界切换入口一次点击就应进入转场；同一
                    # 坐标连续两次仍停留在原世界，说明是低分误匹配或
                    # 入口被遮挡。停止输入并保留画面，禁止循环连点。
                    if 同一点点击次数 >= 2:
                        上下文.置脚本状态(
                            f"同一世界入口{当前入口坐标[0]},{当前入口坐标[1]}连续点击后仍未转场，"
                            "停止入口点击并保留当前页面"
                        )
                        return False
                    上下文.点击(x, y)
                    上下文.置脚本状态(
                        f"已确认世界入口（分数{入口分数:.2f}），尝试进入{self.状态文本}"
                    )
                    # 点击入口后只等待画面稳定；下一轮重新确认世界，不在
                    # 转场动画中叠加滑动手势。
                    上下文.脚本延时(1000)
                    continue

                # 只有已确认处于另一世界时，才允许拖动地图寻找入口。
                # 这条路径没有任何 ESC/返回键恢复逻辑。
                上下文.置脚本状态(
                    f"当前已确认处于{当前世界}，未找到{self.状态文本}入口；仅拖动地图搜索"
                )
                上次入口坐标 = None
                同一点点击次数 = 0
                self.滑动屏幕(上下文, self.滑动配置.起点, self.滑动配置.终点)
                上下文.脚本延时(1000)

            raise RuntimeError(f"操作超时：未找到{self.状态文本}入口")
        except Exception as e:
            self.异常处理(e)
            return False


    def 是否在目标世界(self) -> bool:
        """用资源栏和世界入口共同确认当前世界。

        旧实现把一个 15~19 像素的小图标放在整屏搜索，地图动画很容易
        误命中。现在世界识别器只搜索右上角资源栏和左下角入口，并记录
        主/夜两套分数；分数接近时返回 False，让执行流程先恢复页面，
        不在未知页面继续点击。
        """
        识别结果 = self.识别当前世界()
        return 识别结果.当前世界 == self.状态文本

    def 查找世界入口(self, 屏幕图像):
        """只在左下安全区域查找世界切换船并返回逻辑画布坐标。

        船素材是早期采集的极小局部图，当前测试服缩放后分数通常低于
        旧的 0.80 阈值。这里使用多模板最佳分数而不是首个模板布尔命中，
        再叠加固定安全区域和 0.48 下限。模板命中的是船帆局部，实机
        可点击的船体中心约在其左 25、下 26 个逻辑像素，所以点击后
        仍会重新识别世界，因而不会把普通地图纹理当成成功转场。
        """
        if not isinstance(屏幕图像, np.ndarray) or 屏幕图像.ndim < 2:
            return False, (0, 0), 0.0
        左, 上, 右, 下 = self.世界入口搜索区域
        高, 宽 = 屏幕图像.shape[:2]
        左 = max(0, min(宽, int(左)))
        右 = max(左, min(宽, int(右)))
        上 = max(0, min(高, int(上)))
        下 = max(上, min(高, int(下)))
        区域 = 屏幕图像[上:下, 左:右]
        if 区域.size == 0:
            return False, (0, 0), 0.0

        最佳匹配 = getattr(self.模板识别, "执行最佳匹配", None)
        if callable(最佳匹配):
            try:
                分数, 中心, _ = 最佳匹配(区域, self.船模板路径)
                分数 = float(分数)
                if 分数 >= self.世界入口最低分数:
                    点击x = int(中心[0]) + 左 - 25
                    点击y = int(中心[1]) + 上 + 26
                    return True, (点击x, 点击y), 分数
                return False, (0, 0), 分数
            except Exception:
                pass

        # 兼容旧测试替身/旧识图引擎，没有最佳分数接口时仍使用安全区域。
        try:
            命中, 中心, _ = self.模板识别.执行匹配(
                区域, self.船模板路径, 相似度阈值=self.世界入口最低分数
            )
            if 命中:
                点击x = int(中心[0]) + 左 - 25
                点击y = int(中心[1]) + 上 + 26
                return True, (点击x, 点击y), 1.0
        except Exception:
            pass
        return False, (0, 0), 0.0

    def 识别当前世界(self):
        """返回当前截图的完整世界识别结果，供任务和日志复用。"""
        屏幕图像 = self.上下文.op.获取屏幕图像cv(0, 0, 800, 600)
        识别结果 = self.世界识别.识别(屏幕图像)
        self._最近世界识别结果 = 识别结果
        self._记录世界识别结果(识别结果)
        return 识别结果

    def _记录世界识别结果(self, 识别结果):
        """节流记录识别依据，便于从运行日志定位误判。"""
        摘要 = 识别结果.摘要()
        现在 = time.monotonic()
        日志键 = (识别结果.当前世界, 摘要)
        if (
            日志键 != self._上次世界识别日志
            or 现在 - self._上次世界识别日志时间 >= 3.0
        ):
            self.上下文.置脚本状态(f"世界识别：{摘要}")
            self._上次世界识别日志 = 日志键
            self._上次世界识别日志时间 = 现在

    def 滑动屏幕(self, 上下文, 起点坐标, 终点坐标):
        """使用贝塞尔曲线模拟人类滑动操作"""
        起点x, 起点y = 起点坐标
        终点x, 终点y = 终点坐标

        # 随机偏移增强人类行为模拟
        起点x += random.randint(-5, 5)
        起点y += random.randint(-5, 5)
        终点x += random.randint(-5, 5)
        终点y += random.randint(-5, 5)

        # 控制点随机生成在起点和终点附近
        控制点1 = (
            起点x + (终点x - 起点x) * 0.3 + random.randint(-30, 30),
            起点y + (终点y - 起点y) * 0.3 + random.randint(-30, 30),
        )
        控制点2 = (
            起点x + (终点x - 起点x) * 0.6 + random.randint(-30, 30),
            起点y + (终点y - 起点y) * 0.6 + random.randint(-30, 30),
        )

        路径点 = 生成贝塞尔轨迹((起点x, 起点y), 控制点1, 控制点2, (终点x, 终点y), 步数=random.randint(25, 40))

        上下文.鼠标.移动到(路径点[0][0], 路径点[0][1])
        上下文.鼠标.左键按下()

        for 当前点 in 路径点[1:]:
            上下文.鼠标.移动到(当前点[0], 当前点[1])
            上下文.脚本延时(random.randint(5, 15))  # 模拟人类微小不规律移动

        上下文.鼠标.左键抬起()
        上下文.脚本延时(random.randint(500, 1000))

