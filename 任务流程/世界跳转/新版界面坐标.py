"""新版 CoC 主页 HUD 的统一入口坐标（800×600 逻辑画布）。

坐标来自 MuMu 当前实际画面；入口点击之后仍须由页面/OCR 状态机确认
菜单已打开。这里仅集中管理固定 HUD 坐标，不允许其单独授权升级操作。
"""

主世界战斗菜单 = (62, 546)
主世界建造菜单 = (746, 538)
# 新版建造/英雄列表固定在右侧约 585..800 的逻辑画布范围内。
新版建造面板OCR区域 = (585, 0, 800, 600)
# 建造菜单展开时会遮住右下角“建造”入口；点击面板外的左下海面可安全收起。
建造面板外侧安全点 = (53, 528)
# 新版主页把空闲工人计数移至右下角 HUD。
# 右下 HUD：建筑工人计数；有“建筑学徒”时其计数(如 1/1)出现在右侧，
# 工人计数被挤到左侧(16:9 画面约 x=728)。读整条 HUD 后取最左的合法计数。
新版工人计数OCR区域 = (690, 415, 799, 495)


# HUD 锚点：这些坐标在 16:9 拉伸画布上校准。任意尺寸的 16:9 与 800×600
# 参考尺寸下 ``锚定`` 返回原值；其它长宽比按设备高度等比缩放并贴边换算
# （见 模块/画面几何.py）。调用方在使用时换算，常量本身保持不变。
_锚点表 = {
    主世界战斗菜单: "左下",
    主世界建造菜单: "右下",
    新版建造面板OCR区域: "右",
    建造面板外侧安全点: "左下",
    新版工人计数OCR区域: "右下",
}


def 锚定(值):
    """按登记的 HUD 锚点把坐标/区域换算到当前设备；未登记的值原样返回。"""
    try:
        键 = tuple(int(v) for v in 值)
    except (TypeError, ValueError):
        return 值
    锚 = _锚点表.get(键)
    if 锚 is None:
        return 值
    from 模块.画面几何 import 锚点坐标, 锚点区域

    if len(键) == 2:
        return 锚点坐标(键[0], 键[1], 锚)
    if len(键) == 4:
        return 锚点区域(键, 锚)
    return 值
