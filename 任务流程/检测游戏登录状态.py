import time

import cv2
import numpy as np

from 任务流程.基础任务框架 import 基础任务, 任务上下文
from 模块.检测.模板匹配器 import 模板匹配引擎
from 模块.检测.页面识别器 import 页面识别器

class 检测游戏登录状态任务(基础任务):

    # 脚本延时的单位是毫秒；顶号弹窗需要给另一端留出明确的 200 秒
    # 释放连接时间，不能把 200*60 误写成只有 12 秒。
    顶号等待毫秒 = 200 * 1000

    def __init__(self, 上下文: '任务上下文'):
        super().__init__(上下文)
        self.第一次检测游戏登录=True
        self._断线弹窗恢复次数 = 0
        self._前台状态已记录 = False

    def _启动阶段处理结算页(
        self,
        屏幕图像: np.ndarray,
        识图引擎: 模板匹配引擎,
        页面识别: 页面识别器,
    ) -> bool:
        """启动/重连时先处理已知结算页，避免误判成主页。"""
        上下文 = self.上下文
        当前页面 = 页面识别.识别(屏幕图像, 战斗中=False)
        if 当前页面.页面 == "战斗结算":
            是否匹配, (x, y), _ = 识图引擎.执行匹配(
                屏幕图像,
                "回营.bmp|回营1.bmp|回营2.bmp|回营3.bmp|领取奖励.bmp|回营_领取奖励.bmp",
                相似度阈值=0.80,
            )
            if 是否匹配:
                上下文.置脚本状态(
                    "启动时检测到战斗结算页，先点击回营再继续检测主页"
                )
                if not 上下文.点击已确认安全按钮(x, y, 延时=180):
                    上下文.置脚本状态(
                        "启动时回营按钮未能安全点击，保留结算页并停止任务",
                        30,
                    )
                    上下文.页面恢复失败 = True
                    上下文.停止事件.set()
                    return True
                上下文.脚本延时(1200)
                return True
            上下文.置脚本状态(
                "已识别战斗结算页但未找到回营按钮，暂不判断为主页",
                30,
            )
            return True
        if 当前页面.页面 == "战斗奖励选择":
            上下文.置脚本状态(
                "启动时检测到战斗奖励选择页，禁止误点奖励；保留当前画面并停止任务",
                30,
            )
            上下文.页面恢复失败 = True
            上下文.停止事件.set()
            return True
        return False

    """等待游戏进入时返回"""
    def 执行(self, 首次登录:bool=True) -> bool:
        """等待游戏进入时返回"""
        上下文 = self.上下文
        识图引擎 = 模板匹配引擎()
        页面识别 = 页面识别器(识图引擎)

        if 首次登录 == True:
            上下文.置脚本状态("检测登录情况，最长等待约200秒", 200)
        else:
            上下文.置脚本状态("检测登录情况")

        # 每次进入登录/重连流程都重新计算次数；如果本次成功回到主页，
        # 下一次运行不应继承上一次的断线记录。
        self._断线弹窗恢复次数 = 0
        开始检测时间 = time.monotonic()
        检测轮次 = 0
        while True:
            检测轮次 += 1
            上下文.脚本延时(500)
            屏幕图像 = 上下文.op.获取屏幕图像cv(0, 0, 800, 600)  # 每一个循环获取一次屏幕图像

            # 先确认“应用是否存在”，再判断“账号是否已登录”。两者不是
            # 同一个状态：测试服常会在 CoC 已经打开时显示连接中断弹窗。
            # 只记录一次，避免每轮额外调用 dumpsys 拖慢截图和 OCR。
            if not getattr(self, "_前台状态已记录", False):
                self._前台状态已记录 = True
                try:
                    设备 = getattr(getattr(上下文, "op", None), "设备", None)
                    获取前台包名 = getattr(设备, "获取当前前台包名", None)
                    目标包名 = str(getattr(getattr(上下文, "设置", None), "部落冲突包名", "") or "")
                    当前包名 = 获取前台包名() if callable(获取前台包名) else ""
                    if 目标包名 and 当前包名 == 目标包名:
                        上下文.置脚本状态(
                            "已确认 CoC 游戏已开启并在前台；现在检测登录/连接状态"
                        )
                    else:
                        上下文.置脚本状态(
                            f"未确认 CoC 前台（当前={当前包名 or '未知'}）；"
                            "保留现有页面，不发送返回键"
                        , 30)
                except Exception as 异常:
                    # 前台查询失败不能把已成功取得的游戏截图判定为“游戏未开”。
                    上下文.置脚本状态(
                        f"CoC 前台状态查询暂时失败：{异常}；继续使用截图识别"
                    , 30)

            # 登录页/加载页可能持续几十秒；周期性刷新日志超时，避免
            # 监控线程把正常等待误判成无心跳并重启机器人。
            if 检测轮次 % 20 == 0:
                已等待秒数 = int(time.monotonic() - 开始检测时间)
                上下文.置脚本状态(
                    f"仍在等待游戏主页识别，已等待约{已等待秒数}秒；不重启游戏"
                , 30)
            if time.monotonic() - 开始检测时间 >= 200:
                # 超时画面可能已经退到 Android 启动器或其他应用。此时
                # 发送 Android BACK/ESC 会把游戏进一步退出前台，正是
                # “运行一半游戏自己关了”的根因；超时只能安全停机，
                # 交给用户确认页面后从界面手动继续。
                上下文.置脚本状态(
                    "登录识别超过200秒，禁止发送ESC/返回键，保留当前前台页面并安全停止"
                , 30)
                try:
                    设备 = getattr(getattr(上下文, "op", None), "设备", None)
                    获取前台包名 = getattr(设备, "获取当前前台包名", None)
                    当前包名 = 获取前台包名() if callable(获取前台包名) else "未知"
                except Exception as 异常:
                    当前包名 = f"读取失败：{异常}"
                上下文.置脚本状态(
                    f"登录超时现场前台包名：{当前包名}；不打开其他应用、不重试返回键"
                , 30)
                上下文.页面恢复失败 = True
                上下文.停止事件.set()
                return False

            # 某些测试服/模拟器版本的断线弹窗与旧模板差异较大，
            # 用中央深色弹窗和左对齐“重新载入游戏”文字做兜底识别。
            断线按钮, 断线坐标 = self._检测断线弹窗(屏幕图像)
            if 断线按钮:
                self._断线弹窗恢复次数 += 1
                if self._断线弹窗恢复次数 > 3:
                    上下文.置脚本状态(
                        "断线弹窗连续恢复3次仍未消失，停止继续点击；保留CoC前台，"
                        "请确认测试服/网络后手动继续"
                    , 30)
                    上下文.页面恢复失败 = True
                    停止事件 = getattr(上下文, "停止事件", None)
                    if 停止事件 is not None:
                        停止事件.set()
                    return False
                上下文.置脚本状态(
                    "已确认 CoC 仍在前台，但当前账号连接中断；"
                    "只尝试游戏内重新登入，不重启或关闭游戏"
                , 30)
                上下文.置脚本状态(
                    f"检测到游戏断线弹窗，第{self._断线弹窗恢复次数}次尝试重新载入游戏"
                )
                if not 上下文.点击已确认安全按钮(断线坐标[0], 断线坐标[1], 延时=180):
                    上下文.置脚本状态(
                        "断线弹窗恢复按钮未能安全点击，停止任务并保留CoC前台"
                    , 30)
                    上下文.页面恢复失败 = True
                    停止事件 = getattr(上下文, "停止事件", None)
                    if 停止事件 is not None:
                        停止事件.set()
                    return False
                上下文.脚本延时(5000)
                开始检测时间 = time.monotonic()
                检测轮次 = 0
                continue

            # 检查是否需重新载入
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像[219:377, 196:607], "重新载入游戏.bmp|连接中断.bmp", 相似度阈值=0.9)
            if 是否匹配:
                上下文.置脚本状态("重新载入游戏,继续检测登录情况", 200)
                if not 上下文.点击已确认安全按钮(x + 196, y + 219):  # 转换为全屏坐标
                    上下文.置脚本状态(
                        "重新载入按钮未能安全点击，停止登录恢复并保留当前页面",
                        30,
                    )
                    上下文.页面恢复失败 = True
                    上下文.停止事件.set()
                    return False
                上下文.脚本延时(1000)
                上下文.脚本延时(5 * 1000)
                continue

            # 检查登录弹窗确定按钮
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "顶号_重新载入.bmp", 相似度阈值=0.9)
            if 是否匹配:
                上下文.置脚本状态("另一个设备在连接此村庄，等待操作账号,200秒后重连,继续检测登录情况")
                上下文.脚本延时(self.顶号等待毫秒)
                if not 上下文.点击已确认安全按钮(x, y):
                    上下文.置脚本状态(
                        "顶号弹窗恢复按钮未能安全点击，停止登录恢复并保留当前页面",
                        30,
                    )
                    上下文.页面恢复失败 = True
                    上下文.停止事件.set()
                    return False
                上下文.脚本延时(100)
                continue

            # 检查登录弹窗确定按钮
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "登录弹窗的确定.bmp|登录的确定按钮1.bmp|收集胜利之星的确定.bmp|收集胜利之星的确定[1].bmp|收集胜利之星的确定[2].bmp|收集胜利之星的确定[3].bmp", 相似度阈值=0.9)
            if 是否匹配:
                上下文.置脚本状态("点击确定，继续检测登录情况")
                上下文.点击已确认安全按钮(x, y)
                上下文.脚本延时(100)
                continue

            # 检查登录弹窗确定按钮
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "开宝箱界面.bmp", 相似度阈值=0.9)
            if 是否匹配:
                上下文.置脚本状态("开宝箱咯")
                for _ in range(5):
                    上下文.点击已确认安全按钮(x, y)
                    上下文.脚本延时(100)
                上下文.脚本延时(2000)
                continue

            # 开宝箱后的继续界面
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "开宝箱界面_继续.bmp|开宝箱界面_继续[1].bmp",相似度阈值=0.8)
            上下文.脚本延时(50)
            if 是否匹配:
                上下文.置脚本状态("出现开宝箱后的继续界面，点击,继续检测登录状态")
                上下文.点击已确认安全按钮(x, y)
                上下文.脚本延时(100)
                continue

            # 检查登录弹窗确定按钮
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "卡包[1].bmp", 相似度阈值=0.9)
            if 是否匹配:
                上下文.置脚本状态("点击卡包咯")
                for _ in range(5):
                    上下文.点击已确认安全按钮(x, y)
                    上下文.脚本延时(100)
                上下文.脚本延时(500)
                continue

            # 机器人可能在上一场战斗结算页时被关闭/重启。结算页中也
            # 可能残留“家乡进攻图标”的相似图案，必须先用页面识别器确认
            # 结算，再安全点击“回营”；否则会把结算页误判成主页，随后
            # 拉远视距和到主世界流程会在错误页面上超时。
            if self._启动阶段处理结算页(屏幕图像, 识图引擎, 页面识别):
                if getattr(上下文, "停止事件", None) is not None and 上下文.停止事件.is_set():
                    return False
                开始检测时间 = time.monotonic()
                检测轮次 = 0
                continue

            # 检查家乡进攻图标
            # 模拟器窗口缩放、渲染锐化和不同版本 UI 会让主页按钮
            # 相似度稳定落在 0.75~0.89；0.90 会把已加载主页当成未登录。
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "家乡进攻图标.bmp|家乡进攻图标1.bmp|家乡进攻图标2.bmp|家乡进攻图标3.bmp", 相似度阈值=0.75)
            上下文.脚本延时(50)
            if 是否匹配:
                上下文.置脚本状态("出现家乡进攻图标，已经成功登录")
                break

            # 检查宝石图标
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像[4:227, 740:792], "宝石.bmp|宝石1.bmp|宝石2.bmp|宝石3.bmp", 相似度阈值=0.8)
            上下文.脚本延时(50)
            if 是否匹配:
                上下文.置脚本状态("出现宝石图标，已经成功登录")
                上下文.脚本延时(1000)
                break

        if self.第一次检测游戏登录==True:
            if not self._确认首次启动稳定():
                return False
            self.第一次检测游戏登录=False
            上下文.置脚本状态("首次启动稳定性检查通过；准备执行已确认的游戏内拉远视距")

            # 稳定检查结束后重新取一帧，避免拿加载阶段的旧截图判断视距。
            屏幕图像 = 上下文.op.获取屏幕图像cv(0, 0, 800, 600, 强制刷新=True)

        # 检查视距调整
        是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "不用拉远视距[7].bmp|不用拉远视距[6].bmp|不用拉远视距[5].bmp|不用拉远视距[4].bmp|不用拉远视距[3].bmp|不用拉远视距[2].bmp|不用拉远视距[1].bmp|夜世界_不用拉远视距[1].bmp", 相似度阈值=0.7)
        if 是否匹配:
            上下文.置脚本状态("无需拉远视距")
        else:
            上下文.置脚本状态("正在拉远视距")
            try:
                已执行 = 上下文.游戏内拉远视距(次数=5)
            except Exception as 异常:
                上下文.置脚本状态(
                    f"游戏内拉远视距失败：{异常}；禁止继续进入战斗"
                , 30)
                return False
            if not 已执行:
                上下文.置脚本状态(
                    "游戏内拉远视距未确认执行成功；禁止继续进入战斗"
                , 30)
                return False
            上下文.置脚本状态(
                "游戏内真实双指拉远视距已执行，未切换到模拟器桌面"
            )

        return True

    def _确认首次启动稳定(self) -> bool:
        """主页首次识别后静默观察，避免加载中的游戏被任务手势打断。"""
        上下文 = self.上下文
        设备 = getattr(getattr(上下文, "op", None), "设备", None)
        获取前台包名 = getattr(设备, "获取当前前台包名", None)
        目标包名 = str(getattr(getattr(上下文, "设置", None), "部落冲突包名", "") or "")
        if not callable(获取前台包名) or not 目标包名:
            # 单元测试或旧适配器没有前台查询接口时，不能猜测页面状态；
            # 不额外发送输入，交给现有任务护栏处理。
            上下文.置脚本状态("首次主页稳定性检查不可用：缺少前台查询接口；不发送额外输入")
            return True

        上下文.置脚本状态("主页已识别，开始12秒无操作稳定性检查")
        截止时间 = time.monotonic() + 12.0
        while time.monotonic() < 截止时间:
            if getattr(上下文, "停止事件", None) is not None and 上下文.停止事件.is_set():
                return False
            try:
                当前包名 = 获取前台包名()
            except Exception as 异常:
                上下文.置脚本状态(f"启动稳定性检查无法读取前台：{异常}；停止后续任务")
                上下文.页面恢复失败 = True
                上下文.停止事件.set()
                return False
            if 当前包名 != 目标包名:
                上下文.置脚本状态(
                    "CoC启动稳定性检查失败：游戏在无脚本输入期间离开前台"
                    f"（当前={当前包名 or '未知'}）；停止任务，不重启游戏、不发送返回键"
                )
                上下文.页面恢复失败 = True
                上下文.停止事件.set()
                return False
            上下文.脚本延时(500)

        上下文.置脚本状态("CoC启动稳定性检查通过：12秒内未发送任何游戏输入")
        return True

    @staticmethod
    def _检测断线弹窗(屏幕图像: np.ndarray) -> tuple[bool, tuple[int, int]]:
        """模板失效时识别测试服断线弹窗，并返回文字按钮的点击中心。

        不能只看绿色按钮：战斗结算页底部也有绿色“回营”按钮，
        会导致把正常结算页误判为断线。这里先找中央近似均匀的深色
        弹窗主体，再确认标题、正文和左对齐操作文字三段白色文字。
        """
        if not isinstance(屏幕图像, np.ndarray) or 屏幕图像.ndim != 3:
            return False, (0, 0)
        高度, 宽度 = 屏幕图像.shape[:2]
        if 高度 < 300 or 宽度 < 400:
            return False, (0, 0)
        # 取屏幕中心的弹窗底色作为参考，允许渲染/缩放造成的小幅色差。
        参考点 = 屏幕图像[高度 // 2, 宽度 // 2].astype(np.int16)
        差异 = np.max(
            np.abs(屏幕图像.astype(np.int16) - 参考点), axis=2
        )
        区域左, 区域上 = int(宽度 * 0.08), int(高度 * 0.16)
        区域右, 区域下 = int(宽度 * 0.92), int(高度 * 0.86)
        近似面板 = (差异[区域上:区域下, 区域左:区域右] <= 3).astype(np.uint8) * 255
        近似面板 = cv2.morphologyEx(
            近似面板, cv2.MORPH_CLOSE, np.ones((3, 3), dtype=np.uint8)
        )
        轮廓列表, _ = cv2.findContours(
            近似面板, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE
        )
        灰度 = cv2.cvtColor(屏幕图像, cv2.COLOR_BGR2GRAY)
        for 轮廓 in sorted(轮廓列表, key=cv2.contourArea, reverse=True):
            x, y, w, h = cv2.boundingRect(轮廓)
            x += 区域左
            y += 区域上
            面积 = cv2.contourArea(轮廓)
            # 部分国际服/测试服使用右锚定的断线面板，不能只接受
            # 旧版居中面板，否则“重新登入游戏”会被识别为未知页面。
            居中面板 = 宽度 * 0.14 <= x <= 宽度 * 0.30
            右锚面板 = (
                宽度 * 0.32 <= x <= 宽度 * 0.48
                and x + w >= 宽度 * 0.88
            )
            if not (
                面积 >= 宽度 * 高度 * 0.15
                and 宽度 * 0.42 <= w <= 宽度 * 0.75
                and 高度 * 0.25 <= h <= 高度 * 0.55
                and (居中面板 or 右锚面板)
                and 高度 * 0.22 <= y <= 高度 * 0.45
            ):
                continue
            # 断线弹窗固定有标题、正文、操作文字三段；操作文字在
            # 面板左侧，正好区别于底部居中的“回营”按钮。
            面板灰度 = 灰度[y:y + h, x:x + w]
            if 面板灰度.size == 0:
                continue
            def 亮像素(上比例, 下比例, 左比例=0.04, 右比例=0.92):
                上边 = max(0, min(h - 1, int(h * 上比例)))
                下边 = max(上边 + 1, min(h, int(h * 下比例)))
                左边 = max(0, min(w - 1, int(w * 左比例)))
                右边 = max(左边 + 1, min(w, int(w * 右比例)))
                return 面板灰度[上边:下边, 左边:右边] > 120

            标题像素 = 亮像素(0.10, 0.35)
            正文像素 = 亮像素(0.35, 0.72)
            操作像素 = 亮像素(0.72, 0.95, 0.04, 0.58)
            if (
                int(np.count_nonzero(标题像素)) < 180
                or int(np.count_nonzero(正文像素)) < 120
                or int(np.count_nonzero(操作像素)) < 120
            ):
                continue
            操作y1, 操作y2 = int(h * 0.72), int(h * 0.95)
            操作x1, 操作x2 = int(w * 0.04), int(w * 0.58)
            ys, xs = np.where(面板灰度[操作y1:操作y2, 操作x1:操作x2] > 120)
            if len(xs) == 0:
                continue
            return True, (
                x + 操作x1 + int((xs.min() + xs.max()) / 2),
                y + 操作y1 + int((ys.min() + ys.max()) / 2),
            )
        return False, (0, 0)





