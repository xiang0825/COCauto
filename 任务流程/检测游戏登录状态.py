import time

import cv2
import numpy as np

from 任务流程.基础任务框架 import 基础任务, 任务上下文
from 模块.检测.模板匹配器 import 模板匹配引擎

class 检测游戏登录状态任务(基础任务):

    def __init__(self, 上下文: '任务上下文'):
        super().__init__(上下文)
        self.第一次检测游戏登录=True

    """等待游戏进入时返回"""
    def 执行(self, 首次登录:bool=True) -> bool:
        """等待游戏进入时返回"""
        上下文 = self.上下文
        识图引擎 = 模板匹配引擎()

        if 首次登录 == True:
            上下文.置脚本状态("检测登录情况，最长等待约200秒", 200)
        else:
            上下文.置脚本状态("检测登录情况")

        开始检测时间 = time.monotonic()
        检测轮次 = 0
        while True:
            检测轮次 += 1
            上下文.脚本延时(500)
            屏幕图像 = 上下文.op.获取屏幕图像cv(0, 0, 800, 600)  # 每一个循环获取一次屏幕图像

            # 登录页/加载页可能持续几十秒；周期性刷新日志超时，避免
            # 监控线程把正常等待误判成无心跳并重启机器人。
            if 检测轮次 % 20 == 0:
                已等待秒数 = int(time.monotonic() - 开始检测时间)
                上下文.置脚本状态(
                    f"仍在等待游戏主页识别，已等待约{已等待秒数}秒；不重启游戏"
                , 30)
            if time.monotonic() - 开始检测时间 >= 200:
                # 超时画面可能已经退到 Android 启动器或其他应用。此时
                # 发送 Android BACK/ESC 会把游戏进一步退出前台，正是
                # “运行一半游戏自己关了”的根因；超时只能安全停机，
                # 交给用户确认页面后从界面手动继续。
                上下文.置脚本状态(
                    "登录识别超过200秒，禁止发送ESC/返回键，保留当前前台页面并安全停止"
                , 30)
                try:
                    设备 = getattr(getattr(上下文, "op", None), "设备", None)
                    获取前台包名 = getattr(设备, "获取当前前台包名", None)
                    当前包名 = 获取前台包名() if callable(获取前台包名) else "未知"
                except Exception as 异常:
                    当前包名 = f"读取失败：{异常}"
                上下文.置脚本状态(
                    f"登录超时现场前台包名：{当前包名}；不打开其他应用、不重试返回键"
                , 30)
                上下文.页面恢复失败 = True
                上下文.停止事件.set()
                return False

            # 某些测试服/模拟器版本的断线弹窗与旧模板差异较大，
            # 用中央深色弹窗和左对齐“重新载入游戏”文字做兜底识别。
            断线按钮, 断线坐标 = self._检测断线弹窗(屏幕图像)
            if 断线按钮:
                上下文.置脚本状态(
                    "检测到游戏断线弹窗，仅点击重新载入游戏并继续登录检测"
                )
                上下文.点击已确认安全按钮(断线坐标[0], 断线坐标[1], 延时=180)
                上下文.脚本延时(5000)
                开始检测时间 = time.monotonic()
                检测轮次 = 0
                continue

            # 检查是否需重新载入
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像[219:377, 196:607], "重新载入游戏.bmp|连接中断.bmp", 相似度阈值=0.9)
            if 是否匹配:
                上下文.置脚本状态("重新载入游戏,继续检测登录情况", 200)
                上下文.点击已确认安全按钮(x + 196, y + 219)  # 转换为全屏坐标
                上下文.脚本延时(1000)
                上下文.脚本延时(5 * 1000)
                continue

            # 检查登录弹窗确定按钮
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "顶号_重新载入.bmp", 相似度阈值=0.9)
            if 是否匹配:
                上下文.置脚本状态("另一个设备在连接此村庄，等待操作账号,200秒后重连,继续检测登录情况")
                上下文.脚本延时(200*60)
                上下文.点击已确认安全按钮(x, y)
                上下文.脚本延时(100)
                continue

            # 检查登录弹窗确定按钮
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "登录弹窗的确定.bmp|登录的确定按钮1.bmp|收集胜利之星的确定.bmp|收集胜利之星的确定[1].bmp|收集胜利之星的确定[2].bmp|收集胜利之星的确定[3].bmp", 相似度阈值=0.9)
            if 是否匹配:
                上下文.置脚本状态("点击确定，继续检测登录情况")
                上下文.点击已确认安全按钮(x, y)
                上下文.脚本延时(100)
                continue

            # 检查登录弹窗确定按钮
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "开宝箱界面.bmp", 相似度阈值=0.9)
            if 是否匹配:
                上下文.置脚本状态("开宝箱咯")
                for _ in range(5):
                    上下文.点击已确认安全按钮(x, y)
                    上下文.脚本延时(100)
                上下文.脚本延时(2000)
                continue

            # 开宝箱后的继续界面
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "开宝箱界面_继续.bmp|开宝箱界面_继续[1].bmp",相似度阈值=0.8)
            上下文.脚本延时(50)
            if 是否匹配:
                上下文.置脚本状态("出现开宝箱后的继续界面，点击,继续检测登录状态")
                上下文.点击已确认安全按钮(x, y)
                上下文.脚本延时(100)
                continue

            # 检查登录弹窗确定按钮
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "卡包[1].bmp", 相似度阈值=0.9)
            if 是否匹配:
                上下文.置脚本状态("点击卡包咯")
                for _ in range(5):
                    上下文.点击已确认安全按钮(x, y)
                    上下文.脚本延时(100)
                上下文.脚本延时(500)
                continue

            # 检查家乡进攻图标
            # 模拟器窗口缩放、渲染锐化和不同版本 UI 会让主页按钮
            # 相似度稳定落在 0.75~0.89；0.90 会把已加载主页当成未登录。
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "家乡进攻图标.bmp|家乡进攻图标1.bmp|家乡进攻图标2.bmp|家乡进攻图标3.bmp", 相似度阈值=0.75)
            上下文.脚本延时(50)
            if 是否匹配:
                上下文.置脚本状态("出现家乡进攻图标，已经成功登录")
                break

            # 检查宝石图标
            是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像[4:227, 740:792], "宝石.bmp|宝石1.bmp|宝石2.bmp|宝石3.bmp", 相似度阈值=0.8)
            上下文.脚本延时(50)
            if 是否匹配:
                上下文.置脚本状态("出现宝石图标，已经成功登录")
                上下文.脚本延时(1000)
                break

        if self.第一次检测游戏登录==True:
            self.第一次检测游戏登录=False
            上下文.置脚本状态("首次启动,正在拉远视距")
            for _ in range(5):
                上下文.键盘.按字符按压("f5")
                上下文.脚本延时(200)
            return True

        # 检查视距调整
        是否匹配, (x, y), _ = 识图引擎.执行匹配(屏幕图像, "不用拉远视距[7].bmp|不用拉远视距[6].bmp|不用拉远视距[5].bmp|不用拉远视距[4].bmp|不用拉远视距[3].bmp|不用拉远视距[2].bmp|不用拉远视距[1].bmp|夜世界_不用拉远视距[1].bmp", 相似度阈值=0.7)
        if 是否匹配:
            上下文.置脚本状态("无需拉远视距")
        else:
            上下文.置脚本状态("正在拉远视距")
            for _ in range(5):
                上下文.键盘.按字符按压("f5")
                上下文.脚本延时(180)

        return True

    @staticmethod
    def _检测断线弹窗(屏幕图像: np.ndarray) -> tuple[bool, tuple[int, int]]:
        """模板失效时识别测试服断线弹窗，并返回文字按钮的点击中心。

        不能只看绿色按钮：战斗结算页底部也有绿色“回营”按钮，
        会导致把正常结算页误判为断线。这里先找中央近似均匀的深色
        弹窗主体，再确认标题、正文和左对齐操作文字三段白色文字。
        """
        if not isinstance(屏幕图像, np.ndarray) or 屏幕图像.ndim != 3:
            return False, (0, 0)
        高度, 宽度 = 屏幕图像.shape[:2]
        if 高度 < 300 or 宽度 < 400:
            return False, (0, 0)
        # 取屏幕中心的弹窗底色作为参考，允许渲染/缩放造成的小幅色差。
        参考点 = 屏幕图像[高度 // 2, 宽度 // 2].astype(np.int16)
        差异 = np.max(
            np.abs(屏幕图像.astype(np.int16) - 参考点), axis=2
        )
        区域左, 区域上 = int(宽度 * 0.08), int(高度 * 0.16)
        区域右, 区域下 = int(宽度 * 0.92), int(高度 * 0.86)
        近似面板 = (差异[区域上:区域下, 区域左:区域右] <= 3).astype(np.uint8) * 255
        近似面板 = cv2.morphologyEx(
            近似面板, cv2.MORPH_CLOSE, np.ones((3, 3), dtype=np.uint8)
        )
        轮廓列表, _ = cv2.findContours(
            近似面板, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE
        )
        灰度 = cv2.cvtColor(屏幕图像, cv2.COLOR_BGR2GRAY)
        for 轮廓 in sorted(轮廓列表, key=cv2.contourArea, reverse=True):
            x, y, w, h = cv2.boundingRect(轮廓)
            x += 区域左
            y += 区域上
            面积 = cv2.contourArea(轮廓)
            if not (
                面积 >= 宽度 * 高度 * 0.15
                and 宽度 * 0.42 <= w <= 宽度 * 0.75
                and 高度 * 0.25 <= h <= 高度 * 0.55
                and 宽度 * 0.14 <= x <= 宽度 * 0.30
                and 高度 * 0.22 <= y <= 高度 * 0.45
            ):
                continue
            # 断线弹窗固定有标题、正文、操作文字三段；操作文字在
            # 面板左侧，正好区别于底部居中的“回营”按钮。
            面板灰度 = 灰度[y:y + h, x:x + w]
            if 面板灰度.size == 0:
                continue
            def 亮像素(上比例, 下比例, 左比例=0.04, 右比例=0.92):
                上边 = max(0, min(h - 1, int(h * 上比例)))
                下边 = max(上边 + 1, min(h, int(h * 下比例)))
                左边 = max(0, min(w - 1, int(w * 左比例)))
                右边 = max(左边 + 1, min(w, int(w * 右比例)))
                return 面板灰度[上边:下边, 左边:右边] > 120

            标题像素 = 亮像素(0.10, 0.35)
            正文像素 = 亮像素(0.35, 0.72)
            操作像素 = 亮像素(0.72, 0.95, 0.04, 0.58)
            if (
                int(np.count_nonzero(标题像素)) < 180
                or int(np.count_nonzero(正文像素)) < 120
                or int(np.count_nonzero(操作像素)) < 120
            ):
                continue
            操作y1, 操作y2 = int(h * 0.72), int(h * 0.95)
            操作x1, 操作x2 = int(w * 0.04), int(w * 0.58)
            ys, xs = np.where(面板灰度[操作y1:操作y2, 操作x1:操作x2] > 120)
            if len(xs) == 0:
                continue
            return True, (
                x + 操作x1 + int((xs.min() + xs.max()) / 2),
                y + 操作y1 + int((ys.min() + ys.max()) / 2),
            )
        return False, (0, 0)





