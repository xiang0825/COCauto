from 任务流程.基础任务框架 import 基础任务, 任务上下文

class 模拟器等待超时错误(Exception):
    pass


class 启动模拟器任务(基础任务):
    """验证已连接的 Android 设备并在需要时将游戏切到前台。"""

    def 执行(self) -> bool:
        try:
            上下文 = self.上下文
            包名 = 上下文.数据库.获取机器人设置(上下文.机器人标志).部落冲突包名
            模拟器 = 上下文.雷电模拟器
            模拟器.确认在线()
            if not 模拟器.是否已启动():
                raise 模拟器等待超时错误("ADB 已连接，但 Android 系统尚未完成启动；请在模拟器中等待启动完成。")
            上下文.置脚本状态("ADB 模拟器已连接，检查游戏前台状态")
            模拟器.打开应用(包名)

            获取目标显示ID = getattr(模拟器, "获取目标显示ID", None)
            if callable(获取目标显示ID):
                目标显示ID = 获取目标显示ID()
                if 目标显示ID:
                    上下文.置脚本状态(
                        f"已绑定 CoC 游戏显示层 display {目标显示ID}；截图、拉伸和点击均发送到同一显示层"
                    )

            # 打开应用是幂等操作：如果 CoC 已经在 MuMu 的游戏显示层中，
            # ADB 适配器不会 force-stop 或重新创建进程。这里再读一次前台
            # 包名，把“游戏已打开但正在加载/弹窗中”和“游戏没有启动”明确
            # 区分，避免登录检测阶段只显示“等待主页”而让用户误以为程序
            # 没有检测到游戏。
            获取前台包名 = getattr(模拟器, "获取当前前台包名", None)
            if callable(获取前台包名):
                当前包名 = 获取前台包名()
                if 当前包名 == 包名:
                    上下文.置脚本状态(
                        "已检测到 CoC 正在前台运行，复用当前游戏实例；不重启、不关闭游戏"
                    )
                else:
                    上下文.置脚本状态(
                        f"已请求打开 CoC，等待前台确认（当前={当前包名 or '未知'}）"
                    , 15)
                    # 应用刚从启动器切入时，Activity 可能需要几秒才出现在
                    # dumpsys 中。只等待并复查，不发送返回键，也不 force-stop。
                    for _ in range(8):
                        上下文.脚本延时(500)
                        当前包名 = 获取前台包名()
                        if 当前包名 == 包名:
                            上下文.置脚本状态(
                                "已确认 CoC 应用进入前台，继续检测游戏画面"
                            )
                            break
                    else:
                        上下文.置脚本状态(
                            f"暂未确认 CoC 前台（当前={当前包名 or '未知'}），"
                            "保留现有页面并停止，不切换到其他应用"
                        , 30)
                        return False
            return True

        except Exception as e:
            self.异常处理(e, 是否重启游戏=False)
            return False


