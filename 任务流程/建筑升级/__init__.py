from datetime import datetime, timedelta
from 任务流程.夜世界.夜世界打鱼.夜世界基础任务类 import 夜世界基础任务
from 任务流程.建筑升级.升级普通建筑 import 升级普通建筑任务
from 任务流程.建筑升级.升级英雄 import 升级英雄任务

from 任务流程.建筑升级.寻找建筑 import 寻找建筑, 建筑查找模式
from 任务流程.建筑升级.更新工人状态 import 更新工人状态任务
from 任务流程.兵种或法术升级.打开研究面板 import 打开研究面板任务


class 建筑升级任务(夜世界基础任务):
    """循环执行建筑升级，直到没有空闲工人为止；失败记录并一天内不重试"""

    def __init__(self, 上下文):
        super().__init__(上下文)
        self.空闲工人: bool = False
        self.当前建筑: str | None = None

    def 执行(self) -> bool:
        try:
            指定建筑 = self.上下文.设置.欲升级的英雄或建筑
            启用建议建筑 = self.上下文.设置.是否升级建议升级的建筑

            if not 指定建筑 and not 启用建议建筑:
                self.上下文.置脚本状态("建筑升级任务,要升级的建筑列表为空,并且没有启用升级建议建筑,跳过升级建筑任务")
                # building 和 hero 共用这个任务入口；未配置目标时是正常
                # 跳过，不能被调度器当成页面恢复失败，从而阻断后面的
                # 刷资源、战宠和研究任务。
                return True

            # 研究流程被外部停止时，CoC 会把“请选择要升级的目标”留在
            # 画面上；该页仍露出主世界资源栏，通用主页识别可能误报为
            # 主世界。建筑任务必须先用研究页自己的 OCR/红色 X 收尾，
            # 否则后面的工人 OCR 和建筑入口点击都会落到错误页面。
            if not self._清理残留研究目标页():
                self.上下文.置脚本状态(
                    "建筑升级开始前未能清理残留研究目标页，禁止继续输入"
                )
                return False

            # 先检查上次失败时间
            完整状态 = self.数据库.获取最新完整状态(self.机器人标志).状态数据
            上次失败 = 完整状态.get("建筑升级失败记录")
            if 上次失败:
                失败时间 = datetime.fromtimestamp(上次失败.get("时间", 0))
                if datetime.now() - 失败时间 < timedelta(hours=self.上下文.设置.建筑升级检查间隔):
                    self.上下文.置脚本状态( F"建筑升级任务：上次失败距离现在不到 {self.上下文.设置.建筑升级检查间隔} 小时，暂不重试，等间隔过去后将再次尝试")
                    # 冷却期是正常的本轮跳过，不应触发任务计划的页面
                    # 故障保护。
                    return True


            self.上下文.置脚本状态("开始执行循环建筑升级任务")

            if 指定建筑:
                self.上下文.置脚本状态(f"设置了要升级的固定建筑，将优先升级: {指定建筑}")
                # 使用本轮副本；每个成功提交的固定目标都要从副本中移除，
                # 否则英雄/建筑升级不消耗同一类工人时，下一轮会再次
                # 打开同一个“正在升级”目标，形成死循环。
                升级列表 = list(指定建筑)
                查找模式 = 建筑查找模式.指定建筑
            elif 启用建议建筑:
                self.上下文.置脚本状态("没有指定固定建筑，将升级建议列表中的第一个可用建筑")
                升级列表 = None  # 在寻找任务里动态确定，将会设置为升级建议列表中的建筑
                查找模式 = 建筑查找模式.建议升级中的第一个可用建筑

            本轮已提交建筑: set[str] = set()
            # 建议升级列表是在每次打开面板时动态 OCR 的。记录本轮已经
            # 看到过的候选，避免所有候选都被安全跳过后又回到循环顶部做
            # 一次转场首帧工人 OCR；该首帧偶尔没有 1/2 文本，会被误报为
            # “更新工人状态任务失败”。
            本轮建议候选: set[str] = set()
            while True:
                # 1. 更新工人状态
                工人任务 = 更新工人状态任务(self.上下文)
                成功 = 工人任务.执行()
                if not 成功:
                    self.记录失败("更新工人状态任务失败")
                    return False

                self.空闲工人 = 工人任务.是否有空闲工人()
                if not self.空闲工人:
                    self.上下文.置脚本状态("无空闲工人，建筑升级结束")
                    self._请求建筑任务退避("无空闲工人")
                    return True

                # 2. 寻找可升级建筑
                寻找任务 = 寻找建筑(
                    self.上下文,
                    升级列表,
                    查找模式,
                    排除建筑名称=(本轮已提交建筑 if 查找模式 == 建筑查找模式.建议升级中的第一个可用建筑 else None),
                )

                成功 = 寻找任务.执行()
                if 查找模式 == 建筑查找模式.建议升级中的第一个可用建筑:
                    本轮建议候选.update(
                        str(名称).strip()
                        for 名称 in (getattr(寻找任务, "建筑列表", None) or [])
                        if str(名称).strip()
                    )
                if not 成功:
                    if getattr(寻找任务, "安全跳过", False):
                        self.上下文.置脚本状态(
                            "当前建筑/英雄未确认可升级，已安全跳过，不阻断后续任务"
                        )
                        if 查找模式 == 建筑查找模式.建议升级中的第一个可用建筑:
                            # 建议列表无可安全提交目标时，必须沿用建筑
                            # 任务的退避机制；否则调度器会把正常跳过当作
                            # 5 秒常规轮询，反复打开同一列表并 OCR。
                            self._请求建筑任务退避("建议列表无可安全提交目标")
                        return True
                    self.记录失败("寻找建筑任务执行失败")
                    return False

                self.当前建筑 = 寻找任务.当前建筑
                if not self.当前建筑:
                    self.上下文.置脚本状态("未找到可升级建筑")
                    self._请求建筑任务退避("没有可安全升级的建筑")
                    return True

                # 3. 升级找到的建筑
                if self.当前建筑 in ["野蛮人之王", "弓箭女皇", "亡灵王子", "飞盾战神", "大守护者","飞龙公爵"]:
                   升级任务 = 升级英雄任务(self.上下文, self.当前建筑)
                else:
                    升级任务 = 升级普通建筑任务(self.上下文, self.当前建筑)


                成功 = 升级任务.执行()
                if not 成功:
                    if getattr(升级任务, "安全跳过", False):
                        self.上下文.置脚本状态(
                            f"{self.当前建筑}当前不可安全提交升级，已跳过，不阻断后续任务"
                        )
                        本轮已提交建筑.add(self.当前建筑)
                        if 查找模式 == 建筑查找模式.指定建筑:
                            升级列表 = [
                                名称 for 名称 in 升级列表
                                if 名称 != self.当前建筑
                            ]
                            if not 升级列表:
                                self.上下文.置脚本状态(
                                    "本轮固定建筑/英雄均已处理，结束建筑升级任务"
                                )
                                self._请求建筑任务退避("固定目标暂不可安全提交")
                                return True
                        elif (
                            查找模式 == 建筑查找模式.建议升级中的第一个可用建筑
                            and 本轮建议候选
                            and 本轮建议候选.issubset(本轮已提交建筑)
                        ):
                            # 当前建议列表的候选已经全部安全处理完毕。不要
                            # 再回到 while 顶部读取工人 OCR，直接交给调度器
                            # 按检查间隔退避，避免转场空帧造成假失败。
                            self.上下文.置脚本状态(
                                "本轮建议候选均已安全处理，结束扫描并等待下次检查"
                            )
                            self._请求建筑任务退避("建议列表候选均已安全处理")
                            return True
                        continue
                    self.记录失败(f"升级建筑 {self.当前建筑} 失败")
                    return False

                self.上下文.置脚本状态(f"已完成建筑升级: {self.当前建筑}")
                本轮已提交建筑.add(self.当前建筑)
                # 无论固定目标列表是否已经处理完，都必须先关闭升级详情
                # 并连续确认回到主世界；不能在列表为空时提前 return，
                # 否则下一项任务可能把“立即完成/宝石”面板当作主页继续点。
                if not self._升级提交后确认主世界():
                    self.记录失败("升级提交后未确认回到主世界，阻止下一轮点击")
                    return False
                if 查找模式 == 建筑查找模式.指定建筑:
                    升级列表 = [
                        名称 for 名称 in 升级列表
                        if 名称 != self.当前建筑
                    ]
                    if not 升级列表:
                        self.上下文.置脚本状态("本轮固定建筑/英雄均已提交，结束建筑升级任务")
                        self._请求建筑任务退避("固定升级目标已处理")
                        return True

        except Exception as e:
            self.异常处理(e, 是否重启机器人=False)
            self.记录失败(f"任务异常: {str(e)}")
            return False

    def 记录失败(self, 原因: str):
        """将失败状态记录到数据库"""
        失败记录 = {
            "时间": datetime.now().timestamp(),
            "原因": 原因
        }
        self.数据库.更新状态(self.机器人标志, "建筑升级失败记录", 失败记录)
        self.上下文.置脚本状态(f"建筑升级失败记录已写入数据库: {原因}")

    def _请求建筑任务退避(self, 原因: str) -> None:
        """建筑暂时没有可安全处理目标时，降低下一轮扫描频率。"""
        try:
            配置间隔小时 = max(
                0.0, float(getattr(self.上下文.设置, "建筑升级检查间隔", 0.0) or 0.0)
            )
        except (TypeError, ValueError):
            配置间隔小时 = 0.0
        等待秒 = min(3600.0, max(60.0, 配置间隔小时 * 3600.0))
        请求等待 = getattr(self.上下文, "请求任务计划等待", None)
        if callable(请求等待):
            请求等待(等待秒, f"建筑升级：{原因}")
        else:
            # 兼容旧版上下文和轻量单元测试对象。
            try:
                当前等待 = max(
                    0.0, float(getattr(self.上下文, "任务计划等待秒", 0.0) or 0.0)
                )
            except (TypeError, ValueError):
                当前等待 = 0.0
            self.上下文.任务计划等待秒 = max(当前等待, 等待秒)
            self.上下文._任务计划等待原因 = f"建筑升级：{原因}"
        self.上下文.置脚本状态(
            f"建筑升级暂时退避：{原因}，约{int(等待秒 // 60)}分钟后再检查"
        )

    def _升级提交后确认主世界(self) -> bool:
        """升级提交后关闭详情面板，并用两帧识别确认主世界。

        这是建筑/英雄共用的收尾护栏。关闭器返回 False 只代表没有检测到
        升级详情面板；仍需继续做主页识别，不能把“没有检测到”当成主页。
        """
        关闭器 = getattr(self.上下文, "关闭升级详情弹窗", None)
        if callable(关闭器):
            try:
                关闭器()
            except Exception as 异常:
                self.上下文.置脚本状态(f"升级详情面板收尾失败：{异常}")
                return False
            if getattr(self.上下文, "页面恢复失败", False):
                self.上下文.置脚本状态(
                    "升级详情面板已处理但未确认主世界，禁止开始下一轮建筑操作"
                )
                return False

        识别 = getattr(self.上下文, "识别点击画面", None)
        if not callable(识别):
            self.上下文.置脚本状态("升级收尾无法执行主页复核，禁止继续点击")
            return False

    def _清理残留研究目标页(self) -> bool:
        """只清理 OCR 已确认的研究目标页，不发送盲目 ESC/BACK。"""
        if not callable(getattr(self.上下文, "点击", None)):
            return True
        try:
            清理任务 = 打开研究面板任务(self.上下文)
            结果 = 清理任务._清理残留研究面板()
            if 结果:
                return True
            self.上下文.页面恢复失败 = True
            self.上下文.置脚本状态(
                "残留研究目标页清理失败，保留当前页面并停止建筑任务"
            )
            return False
        except Exception as 异常:
            self.上下文.页面恢复失败 = True
            self.上下文.置脚本状态(f"残留研究目标页检查失败，停止建筑任务：{异常}")
            return False

        连续确认 = 0
        for _ in range(2):
            try:
                try:
                    结果 = 识别(强制=True)
                except TypeError:
                    结果 = 识别()
            except Exception as 异常:
                self.上下文.置脚本状态(f"升级收尾主页复核失败：{异常}")
                return False
            if (
                getattr(结果, "页面", "") == "主世界主页"
                and getattr(结果, "世界", "") == "主世界"
                and float(getattr(结果, "可信度", 0.0) or 0.0) >= 0.70
            ):
                连续确认 += 1
                if 连续确认 >= 2:
                    self.上下文.置脚本状态("升级详情已关闭，连续确认回到主世界主页")
                    return True
            else:
                连续确认 = 0
            延时 = getattr(self.上下文, "脚本延时", None)
            if callable(延时):
                延时(250)

        self.上下文.置脚本状态("升级收尾未连续确认主世界，保留画面并停止后续操作")
        return False
