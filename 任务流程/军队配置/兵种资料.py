def 下兵职责排序值(名称: str) -> int:
    """未登记的兵种排在已登记职责之后、保持原兵栏顺序。"""
    值 = 职责(名称)
    return 职责顺序.get(值, len(职责顺序)) if 值 else len(职责顺序)


def 按权重分配(权重表: dict[str, float], 总空间: int, 人口表: dict[str, int]) -> dict[str, int]:
    """按权重把空间分给各单位，返回 {名称: 个数}。读不到人口的单位跳过。

    先按权重向下取整，剩余空间按权重从高到低补给能放下的单位，尽量填满。
    """
    可用 = [名 for 名, 权 in 权重表.items() if 权 > 0 and 人口表.get(名, 0) > 0]
    if not 可用 or 总空间 <= 0:
        return {}
    总权重 = sum(权重表[名] for 名 in 可用)
    结果 = {名: int(总空间 * 权重表[名] / 总权重 // 人口表[名]) for 名 in 可用}
    剩余 = 总空间 - sum(结果[名] * 人口表[名] for 名 in 可用)
    按权重 = sorted(可用, key=lambda 名: (-权重表[名], 人口表[名]))
    补充 = True
    while 剩余 > 0 and 补充:
        补充 = False
        for 名 in 按权重:
            if 人口表[名] <= 剩余:
                结果[名] += 1
                剩余 -= 人口表[名]
                补充 = True
                break
    return {名: 数量 for 名, 数量 in 结果.items() if 数量 > 0}


def 分配兵量(勾选: list[str], 总人口: int, 人口表: dict[str, int]) -> dict[str, int]:
    """自定义勾选：按兵种默认权重分配军营人口。"""
    return 按权重分配(
        {名: 兵种映射[名].权重 for 名 in 勾选 if 名 in 兵种映射}, 总人口, 人口表
    )
