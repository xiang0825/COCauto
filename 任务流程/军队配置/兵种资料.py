def 显示名(名称: str) -> str:
    资料 = 兵种映射.get(名称)
    return 资料.显示名 if 资料 else 名称


def 职责(名称: str) -> str | None:
    资料 = 兵种映射.get(str(名称 or "").removesuffix(".bmp").removeprefix("兵种_"))
    return 资料.职责 if 资料 else None


def 下兵职责排序值(名称: str) -> int:
    """未登记的兵种排在已登记职责之后、保持原兵栏顺序。"""
    值 = 职责(名称)
    return 职责顺序.get(值, len(职责顺序)) if 值 else len(职责顺序)


def 分配兵量(勾选: list[str], 总人口: int, 人口表: dict[str, int]) -> dict[str, int]:
    """按权重把军营人口分给勾选的兵种，返回 {名称: 个数}。

    ``人口表`` 是从游戏卡片上读到的每个兵种占用人口；读不到人口的兵种跳过。
    先按权重向下取整，剩余人口按权重从高到低补给能放下的兵种，尽量填满。
    """
    可用 = [名 for 名 in 勾选 if 名 in 兵种映射 and 人口表.get(名, 0) > 0]
    if not 可用 or 总人口 <= 0:
        return {}
    总权重 = sum(兵种映射[名].权重 for 名 in 可用)
    结果 = {
        名: int(总人口 * 兵种映射[名].权重 / 总权重 // 人口表[名]) for 名 in 可用
    }
    剩余 = 总人口 - sum(结果[名] * 人口表[名] for 名 in 可用)
    按权重 = sorted(可用, key=lambda 名: (-兵种映射[名].权重, 人口表[名]))
    补充 = True
    while 剩余 > 0 and 补充:
        补充 = False
        for 名 in 按权重:
            if 人口表[名] <= 剩余:
                结果[名] += 1
                剩余 -= 人口表[名]
                补充 = True
                break
    return {名: 数量 for 名, 数量 in 结果.items() if 数量 > 0}
