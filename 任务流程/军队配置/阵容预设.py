def 分配法术(法术个数: dict[str, int], 容量: int, 人口表: dict[str, int]) -> dict[str, int]:
    """按预设顺序放法术，放不下的个数截断；容量有剩余时用第一个能放下的补满。"""
    结果, 剩余 = {}, 容量
    for 名, 个数 in 法术个数.items():
        占用 = 人口表.get(名, 0)
        if 占用 <= 0:
            continue
        可放 = min(个数, 剩余 // 占用)
        if 可放 > 0:
            结果[名] = 可放
            剩余 -= 可放 * 占用
    for 名 in 法术个数:
        占用 = 人口表.get(名, 0)
        if 占用 and 剩余 >= 占用 and 名 in 结果:
            加 = 剩余 // 占用
            结果[名] += 加
            剩余 -= 加 * 占用
    return 结果


def 生效玩法(设置) -> tuple[bool, str]:
    """战斗时实际使用的 (是否自动配兵, 玩法)：开启自动配兵且选了预设时由预设决定。"""
    自动配兵 = bool(getattr(设置, "是否自动配兵", False))
    玩法 = getattr(设置, "自动配兵玩法", "资源优先") or "资源优先"
    if getattr(设置, "是否自动配置军队", False):
        方案 = 预设映射.get(getattr(设置, "阵容预设", ""))
        if 方案:
            return True, 方案.玩法
    return 自动配兵, 玩法
