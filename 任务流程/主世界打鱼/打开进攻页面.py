from __future__ import annotations

import re
import time

import cv2
import numpy as np

from 任务流程.基础任务框架 import 基础任务, 任务上下文
from 任务流程.检测游戏登录状态 import 检测游戏登录状态任务
from 任务流程.主世界打鱼.搜索页面识别 import 搜索页面识别器


class 打开进攻页面任务(基础任务):
    """从主世界进入敌方搜索页。

    这里不能再依赖固定的第三次坐标点击。MuMu/其他模拟器的实际画布
    可能是 1280×720，而任务坐标是 800×600；固定点会落在军队页的空白
    区域，随后搜索任务就会一直等待“下一个”按钮。改为从归一化画面中
    找右下角绿色“攻击!”按钮，并在点击后确认搜索页已经出现。
    """

    _参考宽度 = 800
    _参考高度 = 600
    _军队容量检查间隔秒 = 2.0
    # 测试服/网络切换可能在入口点击后超过45秒才给出稳定的战斗锚点；
    # 入口已经发送过攻击输入时，超时边界仍只读确认一小段时间，不能
    # 把正在进行的战斗误报成“入口失败”而跳过下兵。
    _进攻入口超时后确认秒 = 20.0

    @staticmethod
    def _已收到停止请求(上下文: 任务上下文) -> bool:
        """停止信号必须在任何入口点击前重新检查。"""
        事件 = getattr(上下文, "停止事件", None)
        return bool(事件 is not None and 事件.is_set())

    @staticmethod
    def _标记本场资源评分不可用(上下文: 任务上下文, 原因: str) -> None:
        """记录没有敌方搜索页时的真实状态，禁止沿用上一场评分。"""
        上下文.本场资源易窃取评分 = None
        上下文.本场资源评估 = {
            "状态": "不可用",
            "评分": None,
            "原因": 原因,
        }
        上下文.本场资源评分状态 = "不可用"
        上下文.本场资源评分说明 = 原因
        上下文.本场目标战利品 = {
            "金币": None,
            "圣水": None,
            "黑油": None,
            "战利品评分": None,
            "资源易窃取评分": None,
            "资源易窃取评分依据": dict(上下文.本场资源评估),
            "资源评分状态": "不可用",
            "资源评分原因": 原因,
        }
        上下文.置脚本状态(
            f"本场未经过敌方搜索页，资源战利品/易窃取评分不可用：{原因}；"
            "不沿用上一场评分，不伪造评分数据，继续交给战斗流程"
        )


    def 执行(self) -> bool:
        上下文 = self.上下文
        if self._已收到停止请求(上下文):
            上下文.置脚本状态("打开进攻页面收到停止请求，禁止发送入口点击")
            return False
        # 这个标志只代表“本轮入口已确认，但军队还在恢复”，由上层
        # 主世界任务消费；每次新建入口任务前先清除，避免把上一轮状态
        # 带入下一轮。
        上下文._军队未满待机 = False
        上下文.置脚本状态("开始进攻,打开进攻页面")
        # 机器人可能在上一场战斗中被关闭或因 ADB 短暂异常重新启动。
        # 这时画面已经不是主世界，不能继续点击固定入口，否则一次
        # 恢复就会把输入发到战场、结算页或其它遮罩层。先把已有战斗
        # 状态交给后面的进攻/回营状态机接管。
        既有页面 = self._识别已存在的战斗页面(上下文, 强制=True)
        if 既有页面 == "战斗中":
            上下文._入口已进入战斗 = True
            self._标记本场资源评分不可用(
                上下文, "启动时已在战斗页，当前画面没有可评分的敌方搜索页"
            )
            上下文.置脚本状态("启动时已确认仍在战斗页，跳过主世界入口和搜索页点击")
            return True
        if 既有页面 == "战斗结算":
            上下文._入口已进入结算 = True
            上下文.置脚本状态("启动时已确认仍在战斗结算页，跳过主世界入口和搜索页点击")
            return True
        if 既有页面 == "战斗奖励选择":
            上下文.页面恢复失败 = True
            上下文.停止事件.set()
            上下文.置脚本状态(
                "启动时检测到战斗奖励选择页，禁止自动选择奖励并停止输入"
            )
            return False
        # 升级详情面板可能在战后或收集资源后自动弹出。先用安全关闭
        # 按钮处理它并确认主页，绝不让后面的两个入口点击落到遮罩层。
        关闭升级面板 = getattr(上下文, "关闭升级详情弹窗", None)
        if callable(关闭升级面板):
            关闭升级面板()
            if getattr(上下文, "页面恢复失败", False):
                上下文.置脚本状态(
                    "升级详情弹窗关闭后未确认主世界主页，禁止打开进攻页面"
                )
                return False
        # 选中建筑详情面板不是升级弹窗：它会保留主页锚点和攻击按钮，
        # 但吞掉攻击点击。只有上下文识别到安全右上角 X 时才关闭，
        # 不发送 ESC，也不触碰“立即完成/宝石/商店”。
        清理活动 = getattr(上下文, "清理主世界活动弹窗", None)
        if callable(清理活动):
            if 清理活动():
                if getattr(上下文, "页面恢复失败", False):
                    上下文.置脚本状态(
                        "主世界建筑详情面板关闭后未确认页面，禁止打开进攻页面"
                    )
                    return False
                上下文.脚本延时(250)
        if not self._确认主世界主页(上下文):
            上下文.置脚本状态(
                "打开进攻页面已阻断：未连续确认主世界主页，禁止误点夜世界或其它页面"
            )
            return False
        if self._已收到停止请求(上下文):
            上下文.置脚本状态("主世界主页确认后收到停止请求，禁止点击进攻入口")
            return False
        if not 上下文.点击(62, 546, 1000):
            上下文.置脚本状态("打开进攻页面失败：主世界进攻入口未点击")
            return False
        # 主世界攻击入口会先打开“多人游戏/单人模式/教学模式”选择面板。
        # 旧版直接点击固定的 (156,426)，在自适应画布和繁体布局下可能
        # 落在面板空白处；现在交给下面的状态机动态识别“寻找战斗目标”，
        # 再进入军队配置页，不再发送第二个盲点。
        return self._等待并点击攻击按钮(上下文, 主世界入口已点击=True)

    @classmethod
    def _规范军队容量OCR文本(cls, 文本) -> str:
        """规范容量 OCR 的斜杠和常见误识别字符。"""
        文本 = str(文本 or "")
        return (
            文本.replace("／", "/")
            .replace("\\", "/")
            .replace("|", "/")
            .replace("I", "1")
            .replace("l", "1")
            .replace("O", "0")
            .replace("o", "0")
        )

    @classmethod
    def _从军队容量OCR提取(cls, OCR结果) -> tuple[int, int] | None:
        """从军队页顶部容量区域提取 ``当前/上限``。

        只接受同一条 OCR 文本中的斜杠分数，避免把军队页其它的
        ``11/11`` 法术或 ``3/3`` 攻城器状态当成主军队容量。
        """
        if isinstance(OCR结果, tuple):
            OCR结果 = OCR结果[0]
        候选文本 = []
        for 项 in OCR结果 or []:
            try:
                文本 = cls._规范军队容量OCR文本(项[1])
            except (IndexError, TypeError, ValueError):
                continue
            if "/" in 文本:
                候选文本.append(文本)
        for 文本 in 候选文本:
            匹配 = re.search(r"(?<!\d)(\d{1,4})\s*/\s*(\d{1,4})(?!\d)", 文本)
            if not 匹配:
                continue
            当前, 上限 = (int(匹配.group(1)), int(匹配.group(2)))
            if 上限 > 0 and 0 <= 当前 <= 上限:
                return 当前, 上限
        return None

    def _检查军队容量(self, 上下文: 任务上下文, 屏幕图像: np.ndarray) -> bool:
        """在攻击按钮前确认军队已恢复；无法 OCR 时安全放行。

        训练中的军队不能进入下一场，否则会出现战斗页能打开但兵栏
        没有可部署兵种、随后一直识别和空点的问题。容量检查只在攻击
        按钮已被视觉识别后触发，并做 2 秒节流，避免增加 ADB/OCR 压力。
        """
        当前时间 = time.monotonic()
        上次检查 = float(getattr(self, "_军队容量上次检查时间", 0.0) or 0.0)
        最近状态 = getattr(self, "_最近军队容量状态", None)
        if 当前时间 - 上次检查 < self._军队容量检查间隔秒:
            return not (
                isinstance(最近状态, tuple)
                and 最近状态[0] < 最近状态[1]
            )

        self._军队容量上次检查时间 = 当前时间
        try:
            图像 = 屏幕图像
            if 图像.shape[1] != self._参考宽度 or 图像.shape[0] != self._参考高度:
                图像 = cv2.resize(
                    图像,
                    (self._参考宽度, self._参考高度),
                    interpolation=cv2.INTER_AREA,
                )
            # 实机 800×600 中主军队容量位于约 x=360..435,y=130..150；
            # 留出布局变化，但不包含左侧 2/4 或下方法术/攻城器计数。
            区域 = 图像[105:175, 285:505]
            获取OCR = getattr(上下文, "获取OCR引擎", None)
            if not callable(获取OCR):
                return True
            OCR返回 = 获取OCR()(区域)
            状态 = self._从军队容量OCR提取(OCR返回)
        except Exception as 异常:
            # OCR 属于增强证据，不得因为 native OCR 短暂异常阻断正常
            # 战斗；训练未完成只有在明确读到 current/total 时才拦截。
            上下文.置脚本状态(f"军队容量 OCR 暂时失败，跳过本次容量拦截：{异常}")
            return True

        if 状态 is None:
            return True
        self._最近军队容量状态 = 状态
        当前, 上限 = 状态
        if 当前 < 上限:
            上下文._军队未满待机 = True
            请求等待 = getattr(上下文, "请求任务计划等待", None)
            if callable(请求等待):
                请求等待(60, "军队容量未满")
            else:
                上下文.任务计划等待秒 = max(
                    60.0, float(getattr(上下文, "任务计划等待秒", 0.0) or 0.0)
                )
                上下文._任务计划等待原因 = "军队容量未满"
            上次记录 = getattr(self, "_上次军队容量日志", None)
            if 上次记录 != 状态:
                上下文.置脚本状态(
                    f"军队容量未恢复：{当前}/{上限}，暂不点击攻击，等待训练完成"
                )
                self._上次军队容量日志 = 状态
            return False

        if getattr(self, "_上次军队容量日志", None) is not None:
            上下文.置脚本状态(f"军队容量已恢复：{当前}/{上限}，允许进入战斗")
            self._上次军队容量日志 = None
        上下文._军队未满待机 = False
        return True

    @staticmethod
    def _确认主世界主页(上下文) -> bool:
        """进攻入口前要求两帧连续的主世界主页证据。

        资源任务只允许从主世界主页开始。单帧“夜世界红徽章”或未知页
        不能授权固定入口点击；若检测器暂不可用则保守停止，避免把点击
        发到夜世界、战斗页或模拟器其它画面。
        """
        识别 = getattr(上下文, "识别点击画面", None)
        if not callable(识别):
            上下文.置脚本状态("主世界主页复核不可用，阻止打开进攻页面")
            return False
        连续确认 = 0
        for _ in range(2):
            try:
                try:
                    结果 = 识别(强制=True)
                except TypeError:
                    结果 = 识别()
            except Exception as 异常:
                上下文.置脚本状态(f"主世界主页复核失败，阻止入口点击：{异常}")
                return False
            if (
                getattr(结果, "页面", "") == "主世界主页"
                and getattr(结果, "世界", "") == "主世界"
                and float(getattr(结果, "可信度", 0.0) or 0.0) >= 0.70
            ):
                连续确认 += 1
                if 连续确认 >= 2:
                    return True
            else:
                连续确认 = 0
            延时 = getattr(上下文, "脚本延时", None)
            if callable(延时):
                延时(250)
        return False

    @staticmethod
    def _识别已存在的战斗页面(
            上下文,
            强制: bool = False,
            屏幕图像: np.ndarray | None = None,
    ) -> str | None:
        """读取一次轻量页面状态，避免把战斗/结算当成入口等待页。"""
        if isinstance(屏幕图像, np.ndarray) and 屏幕图像.size:
            try:
                获取识别器 = getattr(上下文, "_获取点击页面识别器", None)
                if callable(获取识别器):
                    结果 = 获取识别器().识别(
                        屏幕图像,
                        战斗中=bool(getattr(上下文, "_战斗中", False)),
                    )
                    页面 = str(getattr(结果, "页面", "") or "")
                    if 页面 in {"战斗中", "战斗结算", "战斗奖励选择"}:
                        return 页面
            except Exception as 异常:
                上下文.置脚本状态(f"进攻入口新帧战斗识别失败：{异常}")
        识别 = getattr(上下文, "识别点击画面", None)
        if not callable(识别):
            return None
        try:
            结果 = 识别(强制=强制)
        except TypeError:
            # 测试替身或旧上下文可能只接受无参调用。
            结果 = 识别()
        except Exception as 异常:
            上下文.置脚本状态(f"进攻入口页面复核失败，暂不发送入口点击：{异常}")
            return None
        页面 = str(getattr(结果, "页面", "") or "")
        if 页面 in {"战斗中", "战斗结算", "战斗奖励选择"}:
            return 页面
        return None

    def _超时后接管已进入战斗(
            self,
            上下文: 任务上下文,
            已点击攻击入口: bool,
            已点击寻找目标: bool,
    ) -> bool:
        """入口超时边界再确认战斗/结算，避免放弃已开始的本场。

        实机曾出现：点击军队页攻击后，CoC 已经进入战斗，但页面识别器
        在过渡帧持续返回未知/结算视觉，恰好越过入口任务的45秒截止点。
        原流程直接返回 False，外层便不会调用下兵任务，造成“进入战斗
        但一个兵都没下”。这里只读确认，不发送任何输入；检测到战斗就
        交给下兵流程，连续两帧结算则交给回营流程。
        """
        if not (已点击攻击入口 or 已点击寻找目标):
            return False
        try:
            截止时间 = time.monotonic() + max(
                0.0, float(self._进攻入口超时后确认秒)
            )
        except (TypeError, ValueError):
            截止时间 = time.monotonic() + 20.0
        连续结算 = 0
        while time.monotonic() < 截止时间:
            if self._已收到停止请求(上下文):
                上下文.置脚本状态(
                    "进攻入口超时确认期间收到停止请求，禁止继续接管输入"
                )
                return False
            页面 = self._识别已存在的战斗页面(上下文, 强制=True)
            if 页面 == "战斗中":
                上下文._入口已进入战斗 = True
                self._标记本场资源评分不可用(
                    上下文, "攻击入口超时边界确认当前仍在战斗页，未渲染敌方搜索页"
                )
                上下文.置脚本状态(
                    "进攻入口超时边界确认仍在战斗页，交给下兵流程"
                )
                return True
            if 页面 == "战斗结算":
                连续结算 += 1
                if 连续结算 >= 2:
                    上下文._入口已进入结算 = True
                    上下文.置脚本状态(
                        "进攻入口超时边界连续确认战斗结算页，交给回营流程"
                    )
                    return True
            else:
                连续结算 = 0
            上下文.脚本延时(350)
        return False

    def _检测攻击按钮(self, 屏幕图像: np.ndarray) -> tuple[int, int] | None:
        """在确认军队配置面板后找右下角绿色攻击按钮中心。"""
        if not isinstance(屏幕图像, np.ndarray) or 屏幕图像.size == 0:
            return None
        if len(屏幕图像.shape) != 3 or 屏幕图像.shape[2] < 3:
            return None

        # 调用方通常已经返回逻辑画布；旧截图适配器可能直接传入
        # 1280×720 原图，先统一尺寸，避免候选坐标被按错画布解释。
        if 屏幕图像.shape[1] != self._参考宽度 or 屏幕图像.shape[0] != self._参考高度:
            try:
                屏幕图像 = cv2.resize(
                    屏幕图像,
                    (self._参考宽度, self._参考高度),
                    interpolation=cv2.INTER_AREA,
                )
            except (AttributeError, TypeError, ValueError, cv2.error):
                return None

        图像高度, 图像宽度 = 屏幕图像.shape[:2]
        hsv = cv2.cvtColor(屏幕图像, cv2.COLOR_BGR2HSV)
        # 主世界商店、任务徽章和资源按钮也会出现绿色大块。军队配置
        # 页才会同时拥有中央大面积浅色面板；没有这项独立证据时，
        # 即使右下出现绿色矩形也不能授权点击。
        面板 = hsv[
            int(图像高度 * 0.13):int(图像高度 * 0.88),
            int(图像宽度 * 0.12):int(图像宽度 * 0.88),
        ]
        浅色面板比例 = float(
            ((面板[:, :, 1] <= 130) & (面板[:, :, 2] >= 130)).mean()
        ) if 面板.size else 0.0
        棕色配置面板比例 = float(
            (
                (面板[:, :, 0] <= 30)
                & (面板[:, :, 1] >= 50)
                & (面板[:, :, 2] >= 60)
            ).mean()
        ) if 面板.size else 0.0
        if 浅色面板比例 < 0.35 and 棕色配置面板比例 < 0.35:
            return None
        # 当前 CoC 的攻击按钮为高亮黄绿色；只看画面右下区域，避免把
        # 资源按钮、强化按钮或地图内容当成攻击按钮。
        x起点 = max(0, int(图像宽度 * 0.58))
        y起点 = max(0, int(图像高度 * 0.72))
        区域 = hsv[y起点:, x起点:]
        绿色遮罩 = cv2.inRange(
            区域,
            np.array([32, 55, 90], dtype=np.uint8),
            np.array([92, 255, 255], dtype=np.uint8),
        )
        核心 = np.ones((3, 3), dtype=np.uint8)
        绿色遮罩 = cv2.morphologyEx(绿色遮罩, cv2.MORPH_CLOSE, 核心, iterations=2)
        绿色遮罩 = cv2.morphologyEx(绿色遮罩, cv2.MORPH_OPEN, 核心, iterations=1)

        轮廓列表, _ = cv2.findContours(
            绿色遮罩, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE
        )
        候选 = []
        for 轮廓 in 轮廓列表:
            x, y, 宽, 高 = cv2.boundingRect(轮廓)
            if 宽 < 图像宽度 * 0.12 or 高 < 图像高度 * 0.035:
                continue
            if 宽 / max(高, 1) < 2.0 or 宽 / max(高, 1) > 9.0:
                continue
            全局x = x + x起点
            全局y = y + y起点
            中心x = 全局x + 宽 // 2
            中心y = 全局y + 高 // 2
            # 攻击按钮应位于最下方；同时保留右侧限制，避免误识别地图。
            if 中心x < 图像宽度 * 0.68 or 中心y < 图像高度 * 0.79:
                continue
            候选.append((中心y, 宽 * 高, 中心x, 中心y))

        if not 候选:
            return None
        _, _, 中心x, 中心y = max(候选, key=lambda 项: (项[0], 项[1]))
        # 转回任务统一使用的 800×600 参考坐标。
        return (
            round(中心x * self._参考宽度 / 图像宽度),
            round(中心y * self._参考高度 / 图像高度),
        )

    def _是否出现下一个(self, 上下文: 任务上下文, 屏幕图像: np.ndarray) -> bool:
        try:
            命中, _, 依据, 分数 = 搜索页面识别器.查找下一个按钮(
                屏幕图像, self.模板识别
            )
            if 命中:
                self._最近搜索页识别依据 = 依据
                self._最近搜索页识别分数 = 分数
            return bool(命中)
        except Exception as 异常:
            上下文.置脚本状态(f"搜索页面识别失败：{异常}")
            return False

    def _检测寻找目标按钮(self, 屏幕图像: np.ndarray) -> tuple[int, int] | None:
        """识别主世界攻击选择面板中的橙色“寻找战斗目标”按钮。

        该按钮只在第一次点击主世界“攻击!”后出现，位于参考画布左下
        的多人游戏卡片内。这里只扫描左下卡片区域，并同时限制按钮的
        宽高比、尺寸和橙色饱和度，避免把主世界装饰、任务徽章或底部
        主入口当成继续按钮。
        """
        if not isinstance(屏幕图像, np.ndarray) or 屏幕图像.size == 0:
            return None
        if len(屏幕图像.shape) != 3 or 屏幕图像.shape[2] < 3:
            return None
        try:
            if 屏幕图像.shape[1] != self._参考宽度 or 屏幕图像.shape[0] != self._参考高度:
                屏幕图像 = cv2.resize(
                    屏幕图像,
                    (self._参考宽度, self._参考高度),
                    interpolation=cv2.INTER_AREA,
                )
            高度, 宽度 = 屏幕图像.shape[:2]
            # 选择面板按钮在 x=40..250、y=390..500；预留少量主题布局
            # 变化空间，但不扩大到中央内容或右下商店区域。
            左, 上 = int(宽度 * 0.02), int(高度 * 0.58)
            右, 下 = int(宽度 * 0.38), int(高度 * 0.86)
            区域 = 屏幕图像[上:下, 左:右]
            hsv = cv2.cvtColor(区域, cv2.COLOR_BGR2HSV)
            橙色遮罩 = cv2.inRange(
                hsv,
                np.array([6, 110, 135], dtype=np.uint8),
                np.array([38, 255, 255], dtype=np.uint8),
            )
            核心 = np.ones((5, 5), dtype=np.uint8)
            橙色遮罩 = cv2.morphologyEx(
                橙色遮罩, cv2.MORPH_CLOSE, 核心, iterations=2
            )
            橙色遮罩 = cv2.morphologyEx(
                橙色遮罩, cv2.MORPH_OPEN, np.ones((3, 3), dtype=np.uint8), iterations=1
            )
            轮廓列表, _ = cv2.findContours(
                橙色遮罩, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE
            )
            候选 = []
            for 轮廓 in 轮廓列表:
                x, y, 宽, 高 = cv2.boundingRect(轮廓)
                面积 = 宽 * 高
                if 宽 < 宽度 * 0.14 or 高 < 高度 * 0.045:
                    continue
                if 宽 > 宽度 * 0.34 or 高 > 高度 * 0.18:
                    continue
                if not 2.0 <= 宽 / max(1, 高) <= 5.5:
                    continue
                中心x = x + 左 + 宽 // 2
                中心y = y + 上 + 高 // 2
                if not (
                    宽度 * 0.04 <= 中心x <= 宽度 * 0.34
                    and 高度 * 0.63 <= 中心y <= 高度 * 0.84
                ):
                    continue
                饱和橙色比例 = float(
                    np.count_nonzero(橙色遮罩[y:y + 高, x:x + 宽])
                ) / max(1, 面积)
                if 饱和橙色比例 < 0.35:
                    continue
                候选.append((面积, 中心x, 中心y))
            if not 候选:
                return None
            _, 中心x, 中心y = max(候选, key=lambda 项: 项[0])
            return (
                round(中心x * self._参考宽度 / 宽度),
                round(中心y * self._参考高度 / 高度),
            )
        except (AttributeError, TypeError, ValueError, cv2.error):
            return None

    def _等待并点击攻击按钮(
            self,
            上下文: 任务上下文,
            主世界入口已点击: bool = False,
    ) -> bool:
        """点击动态攻击按钮，并确认已经切换到敌方搜索页面。"""
        # 测试服搜索/战斗过渡可能先显示白屏、放大镜或倒计时，超过
        # 20 秒才渲染战斗锚点。等待期间只读新截图，不发送额外输入；
        # 允许最多 45 秒，避免把已点击成功的本场战斗误判成入口失败。
        截止时间 = time.monotonic() + 45.0
        已点击 = False
        已点击寻找目标 = False
        断线恢复次数 = 0
        上次提示时间 = 0.0
        连续搜索页命中 = 0
        # 攻击按钮点击后的过渡帧偶尔会短暂命中“战斗结算”视觉特征，
        # 但下一帧实际是战斗倒计时。结算页必须连续确认，单帧只等待
        # 并禁止任何输入，避免跳过下兵流程。
        连续结算页命中 = 0
        上次主世界入口重试时间 = time.monotonic()
        主世界入口重试次数 = 0
        # 某些 MuMu/CoC 过渡帧会接受 ADB tap 但不弹出选择面板；
        # 只在新帧再次确认“主世界主页”后，最多补点两次入口。
        # 不能用 ESC 或盲点其它区域代替，避免误触夜世界/商店。
        最大主世界入口重试次数 = 2
        try:
            主世界入口重试间隔秒 = max(
                0.0, float(getattr(self, "主世界入口重试间隔秒", 4.0))
            )
        except (TypeError, ValueError):
            主世界入口重试间隔秒 = 4.0
        while time.monotonic() < 截止时间:
            if self._已收到停止请求(上下文):
                上下文.置脚本状态("进攻入口等待期间收到停止请求，禁止继续点击")
                return False
            try:
                屏幕图像 = 上下文.op.获取屏幕图像cv(0, 0, 800, 600)
            except Exception as 异常:
                上下文.置脚本状态(f"进入进攻页面截图失败：{异常}")
                上下文.脚本延时(500)
                continue

            # 敌方搜索页也会保留左下角“结束战斗/放弃”按钮，不能先用
            # 战斗页特征判断。先确认右侧“下一個”搜索按钮，连续两帧命中
            # 才交给资源 OCR/阵营评分；这样不会把搜索页误当成已在战斗，
            # 也不会丢失本场的战利品筛选。
            if self._是否出现下一个(上下文, 屏幕图像):
                连续搜索页命中 += 1
                if 连续搜索页命中 >= 2:
                    依据 = getattr(self, "_最近搜索页识别依据", "按钮区域")
                    分数 = getattr(self, "_最近搜索页识别分数", 0.0)
                    上下文.本场资源评分状态 = "待评分"
                    上下文.本场资源评分说明 = "已确认敌方搜索页，等待资源 OCR/阵营识别"
                    上下文.置脚本状态(
                        f"已确认进入敌方搜索页面：{依据}，评分{分数:.2f}"
                    )
                    return True
            else:
                连续搜索页命中 = 0

            # 第一帧搜索按钮只能作为候选证据。先等待一帧，避免同一
            # 过渡帧同时命中“结束战斗”特征后被错误交给下兵流程；如果
            # 下一帧按钮消失，下一轮仍会正常回退到战斗页识别。
            if 连续搜索页命中:
                上下文.脚本延时(180)
                continue

            # 点击军队页攻击按钮后，测试服/网络切换可能直接进入战斗，
            # 或搜索页已经被旧进程打开。此时“下一個”按钮不再存在，
            # 旧逻辑会在这里假装一直等待，最后把真正的战斗留在 0%。
            既有页面 = self._识别已存在的战斗页面(上下文, 屏幕图像=屏幕图像)
            if 既有页面 != "战斗结算":
                连续结算页命中 = 0
            if 既有页面 == "战斗中":
                上下文._入口已进入战斗 = True
                self._标记本场资源评分不可用(
                    上下文, "当前测试服从军队配置页直接进入战斗，未渲染敌方搜索页"
                )
                上下文.置脚本状态(
                    "进攻入口已确认进入战斗页，跳过搜索按钮等待并交给下兵流程"
                )
                return True
            if 既有页面 == "战斗结算":
                # 测试服/部分网络切换会在点击攻击后先把上一场的结果层
                # 留在画面上几帧，随后才出现新的战斗倒计时。此时即使
                # 连续命中也不能当作本场已结算，否则会跳过下兵并把
                # 新战斗交给回营任务。只有入口尚未发送攻击输入时，
                # 结算页才允许走稳定确认分支（启动时已有结算由执行()
                # 的入口复核负责）。
                if 已点击寻找目标 or 已点击:
                    上下文.置脚本状态(
                        "攻击后出现战斗结算视觉过渡层，继续等待搜索/战斗页；禁止跳过下兵"
                    )
                    上下文.脚本延时(350)
                    continue
                连续结算页命中 += 1
                if 连续结算页命中 >= 2:
                    上下文._入口已进入结算 = True
                    上下文.置脚本状态(
                        "进攻入口连续确认战斗结算页，跳过搜索和下兵，交给回营流程"
                    )
                    return True
                上下文.置脚本状态(
                    "进攻入口单帧命中战斗结算特征，等待下一帧确认；禁止跳过下兵"
                )
                上下文.脚本延时(350)
                continue
            if 既有页面 == "战斗奖励选择":
                上下文.页面恢复失败 = True
                上下文.停止事件.set()
                上下文.置脚本状态(
                    "进攻入口检测到战斗奖励选择页，禁止选择奖励并停止输入"
                )
                return False

            # 断线弹窗会遮住军队页，但底层绿色按钮仍然可见；必须先
            # 处理弹窗，否则视觉检测会误把弹窗后的按钮当成可点击目标。
            断线弹窗, 断线按钮点 = 检测游戏登录状态任务._检测断线弹窗(屏幕图像)
            if 断线弹窗:
                断线恢复次数 += 1
                if 断线恢复次数 > 2:
                    上下文.置脚本状态(
                        "进攻入口连续两次检测到连接中断，停止点击并保留CoC前台"
                    )
                    return False
                上下文.置脚本状态(
                    f"进攻入口检测到连接中断，第{断线恢复次数}次尝试游戏内重新登入"
                )
                if not 上下文.点击已确认安全按钮(
                    断线按钮点[0], 断线按钮点[1], 延时=180
                ):
                    上下文.置脚本状态("连接中断恢复按钮点击失败，停止进攻入口")
                    return False
                已点击 = False
                上下文.脚本延时(5000)
                continue

            # 进入军队页或等待攻击按钮期间也可能出现升级详情面板；
            # 关闭后必须从新帧重新判断，不能沿用面板出现前的按钮位置。
            关闭升级面板 = getattr(上下文, "关闭升级详情弹窗", None)
            if callable(关闭升级面板) and 关闭升级面板(屏幕图像):
                上下文.脚本延时(250)
                已点击 = False
                连续搜索页命中 = 0
                continue
            if getattr(上下文, "页面恢复失败", False):
                上下文.置脚本状态(
                    "升级详情弹窗处理后未确认主世界主页，停止进攻入口"
                )
                return False

            if not 已点击寻找目标:
                寻找目标点 = self._检测寻找目标按钮(屏幕图像)
                if 寻找目标点 is not None:
                    if self._已收到停止请求(上下文):
                        上下文.置脚本状态(
                            "识别到寻找战斗目标按钮后收到停止请求，禁止点击"
                        )
                        return False
                    上下文.置脚本状态(
                        f"识别到寻找战斗目标按钮，动态点击{寻找目标点[0]},{寻找目标点[1]}"
                    )
                    if not 上下文.点击(
                        寻找目标点[0], 寻找目标点[1], 延时=700, 是否精确点击=True
                    ):
                        上下文.置脚本状态("寻找战斗目标按钮点击被安全护栏拒绝")
                        return False
                    已点击寻找目标 = True
                    continue

            if not 已点击:
                攻击点 = self._检测攻击按钮(屏幕图像)
                if 攻击点 is not None:
                    if self._已收到停止请求(上下文):
                        上下文.置脚本状态(
                            "识别到军队配置攻击按钮后收到停止请求，禁止点击"
                        )
                        return False
                    if not self._检查军队容量(上下文, 屏幕图像):
                        上下文.脚本延时(350)
                        continue
                    上下文.置脚本状态(
                        f"识别到军队配置页攻击按钮，动态点击{攻击点[0]},{攻击点[1]}"
                    )
                    if not 上下文.点击(
                        攻击点[0], 攻击点[1], 延时=700, 是否精确点击=True
                    ):
                        上下文.置脚本状态("攻击按钮点击被安全护栏拒绝")
                        return False
                    已点击 = True
                    continue

            # 首次主世界入口点击没有产生任何选择面板时，读取一帧新的
            # 页面证据再补点；军队配置页、搜索页、战斗页均不会进入该
            # 分支。重试次数很小，避免在异常页面持续发送输入。
            当前时间 = time.monotonic()
            if (
                主世界入口已点击
                and not 已点击寻找目标
                and not 已点击
                and 主世界入口重试次数 < 最大主世界入口重试次数
                and 当前时间 - 上次主世界入口重试时间 >= 主世界入口重试间隔秒
            ):
                if self._已收到停止请求(上下文):
                    上下文.置脚本状态(
                        "主世界进攻入口重试前收到停止请求，禁止点击"
                    )
                    return False
                try:
                    主页证据 = 上下文.识别点击画面(强制=True)
                except TypeError:
                    主页证据 = 上下文.识别点击画面()
                except Exception as 异常:
                    上下文.置脚本状态(f"主世界进攻入口重试前页面识别失败：{异常}")
                    主页证据 = None
                if (
                    getattr(主页证据, "页面", "") == "主世界主页"
                    and getattr(主页证据, "世界", "") == "主世界"
                    and float(getattr(主页证据, "可信度", 0.0) or 0.0) >= 0.70
                ):
                    主世界入口重试次数 += 1
                    上次主世界入口重试时间 = 当前时间
                    上下文.置脚本状态(
                        f"主世界进攻入口未弹出选择面板，第{主世界入口重试次数}次安全重试"
                    )
                    if not 上下文.点击(62, 546, 700, 是否精确点击=True):
                        上下文.置脚本状态("主世界进攻入口重试被安全护栏拒绝")
                        return False
                    continue

            if 当前时间 - 上次提示时间 >= 3.0:
                上下文.置脚本状态(
                    "等待军队配置页攻击按钮或敌方搜索页面，避免误点击其他页面"
                )
                上次提示时间 = 当前时间
            上下文.脚本延时(350)

        # 不能因为最后一帧恰好越过截止时间就丢掉已经开始的战斗。入口
        # 一旦发送过攻击输入，追加的确认只读、不点击、不返回键。
        if self._超时后接管已进入战斗(
            上下文,
            已点击攻击入口=已点击,
            已点击寻找目标=已点击寻找目标,
        ):
            return True
        if getattr(上下文, "_军队未满待机", False):
            上下文.置脚本状态(
                "军队容量在等待窗口内仍未恢复，本轮跳过进攻；下一轮继续检查"
            )
            return True
        上下文.置脚本状态("进入进攻页面失败：45秒内未确认军队配置、搜索页或战斗页")
        return False

