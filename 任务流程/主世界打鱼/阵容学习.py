"""阵容学习：记录每场使用的阵容，按真实战果比较哪套阵容更适合当前玩法。

机器人不会训练部队，阵容由游戏内军队决定。这里做三件事：

1. 识别本场阵容（兵种、攻城器械、英雄），生成稳定的“阵容签名”；
2. 按玩法评估阵容适配度，阵容与玩法明显冲突时在日志里给出建议；
3. 按阵容累计胜负、星数、摧毁率和战后资源净变化，样本足够后比较各阵容。

资源净变化来自战前/战后资源 OCR，是近似值（可能混入收集或消耗），
所以比较时要求每套阵容至少有 ``比较最少样本`` 场有效收益数据。
"""
from __future__ import annotations

import time

状态类型 = "阵容学习"
比较最少样本 = 10
最多保留阵容 = 12

# 兵栏模板名（去掉“兵种_”前缀）分类。依据游戏内各兵种的优先目标：
# 资源型会优先打资源建筑；防御型只打防御建筑，打资源时基本无收益。
资源型兵种 = {"超级哥布林", "哥布林", "收债哥布林"}
防御型兵种 = {
    "气球兵", "野猪骑士", "巨人", "霸天巨人", "石头人", "戈仑冰人",
    "攻城气球", "龙骑士", "根蔓骑士", "天狗",
}

推荐阵容 = {
    "资源优先": (
        "隐秘哥布林为主力（约 70%~80% 人口），超级野蛮人或弓箭手补边，"
        "攻城器械选攻城训练营或不带；法术带急速/狂暴。隐秘哥布林需在兵营用黑油或超级药水激活"
    ),
    "快速速刷": "超级野蛮人或瓦基丽武神为主，少量哥布林；目标是快速投完兵结束战斗",
    "稳健三星": "按自己最熟练的推进阵容配置（如巨人/戈仑+法师+皮卡），本玩法以星数为目标而非资源",
}


def _短名(名称) -> str:
    文本 = str(名称 or "").removesuffix(".bmp")
    for 前缀 in ("兵种_", "英雄_", "法术_"):
        if 文本.startswith(前缀):
            return 文本[len(前缀):]
    return 文本


def 阵容签名(兵栏清单) -> str:
    """兵种/攻城器械带数量，英雄只记名字；法术和未识别槽位不计入。"""
    兵种, 英雄 = [], []
    for 项 in 兵栏清单 or []:
        if not isinstance(项, dict):
            continue
        类别 = 项.get("类别")
        名 = _短名(项.get("名称"))
        if not 名 or "未匹配" in 名:
            continue
        if 类别 in ("兵种", "攻城器械"):
            try:
                数量 = int(项.get("数量") or 0)
            except (TypeError, ValueError):
                数量 = 0
            兵种.append(f"{名}x{数量}" if 数量 > 1 else 名)
        elif 类别 == "英雄":
            英雄.append(名)
    if not 兵种 and not 英雄:
        return ""
    return "+".join(兵种 + sorted(英雄))


def 评估适配度(兵栏清单, 玩法: str) -> tuple[int | None, list[str]]:
    """返回 (适配度百分比, 冲突兵种)。只对“资源优先/快速速刷”给出评分。

    按单位个数估算（不是人口），资源型计 1 分、普通兵种 0.6 分、
    只打防御的兵种 0 分。英雄、法术不计入。
    """
    if 玩法 not in ("资源优先", "快速速刷"):
        return None, []
    总数 = 0
    得分 = 0.0
    冲突 = []
    for 项 in 兵栏清单 or []:
        if not isinstance(项, dict) or 项.get("类别") not in ("兵种", "攻城器械"):
            continue
        名 = _短名(项.get("名称"))
        if not 名 or "未匹配" in 名:
            continue
        try:
            数量 = max(1, int(项.get("数量") or 1))
        except (TypeError, ValueError):
            数量 = 1
        总数 += 数量
        if 名 in 资源型兵种:
            得分 += 数量
        elif 名 in 防御型兵种:
            冲突.append(名)
        else:
            得分 += 数量 * 0.6
    if 总数 == 0:
        return None, []
    return round(得分 / 总数 * 100), 冲突


def 阵容提示(兵栏清单, 玩法: str) -> str:
    适配度, 冲突 = 评估适配度(兵栏清单, 玩法)
    签名 = 阵容签名(兵栏清单) or "未识别"
    if 适配度 is None:
        return f"阵容学习：当前阵容 {签名}（{玩法}玩法不评估资源适配度）"
    文本 = f"阵容学习：当前阵容 {签名}，与【{玩法}】适配度 {适配度}%"
    if 冲突:
        文本 += f"；{'、'.join(dict.fromkeys(冲突))} 只攻击防御建筑，打资源时基本不贡献战利品"
    if 适配度 < 60 and 玩法 in 推荐阵容:
        文本 += f"。建议在游戏里改为：{推荐阵容[玩法]}"
    return 文本


def _空统计() -> dict:
    return {
        "场次": 0, "胜场": 0, "星数和": 0.0, "摧毁率和": 0.0, "结果场次": 0,
        "收益场次": 0, "金币和": 0, "圣水和": 0, "黑油和": 0, "最近时间": 0,
    }


def _裁剪(学习: dict) -> dict:
    阵容 = 学习.get("阵容", {})
    if len(阵容) > 最多保留阵容:
        保留 = sorted(阵容.items(), key=lambda 项: 项[1].get("最近时间", 0), reverse=True)
        学习["阵容"] = dict(保留[:最多保留阵容])
    return 学习


def 读取(数据库, 机器人标志) -> dict:
    try:
        数据 = 数据库.获取最新完整状态(机器人标志).状态数据.get(状态类型)
    except Exception:
        数据 = None
    学习 = dict(数据) if isinstance(数据, dict) else {}
    学习["阵容"] = {k: dict(v) for k, v in (学习.get("阵容") or {}).items() if isinstance(v, dict)}
    return 学习


def 记录战斗结果(数据库, 机器人标志, 签名: str, 结果, 星数, 摧毁率) -> None:
    if not 签名:
        return
    学习 = 读取(数据库, 机器人标志)
    统计 = 学习["阵容"].setdefault(签名, _空统计())
    统计["场次"] += 1
    统计["最近时间"] = int(time.time())
    if 结果 == "胜利":
        统计["胜场"] += 1
    try:
        星 = float(星数) if 星数 is not None else None
        摧毁 = float(摧毁率) if 摧毁率 is not None else None
    except (TypeError, ValueError):
        星 = 摧毁 = None
    if 星 is not None and 摧毁 is not None:
        统计["星数和"] += 星
        统计["摧毁率和"] += 摧毁
        统计["结果场次"] += 1
    数据库.更新状态(机器人标志, 状态类型, _裁剪(学习))


# 一场战斗的净收益不可能大幅为负（训练兵种只花少量资源）。实机 rc132：黑油 70,303
# 被 OCR 读成 157，记成 −70,146；黑油按 50 倍折算后把整套阵容的收益分拉成负数，
# 学习结论变成“换回收益更低的阵容”。这类读数不进学习统计。
单场最低可信净变化 = -20_000


def 收益读数可信(净变化: dict) -> bool:
    for 资源 in ("金币", "圣水", "黑油"):
        try:
            if int(净变化.get(资源, 0) or 0) < 单场最低可信净变化:
                return False
        except (TypeError, ValueError):
            return False
    return True


def 记录资源收益(数据库, 机器人标志, 签名: str, 净变化: dict) -> bool:
    """记录一场收益；读数不可信时不记录并返回 False。"""
    if not 签名 or not isinstance(净变化, dict):
        return False
    if not 收益读数可信(净变化):
        return False
    学习 = 读取(数据库, 机器人标志)
    统计 = 学习["阵容"].setdefault(签名, _空统计())
    统计["收益场次"] += 1
    for 资源 in ("金币", "圣水", "黑油"):
        try:
            统计[f"{资源}和"] += int(净变化.get(资源, 0) or 0)
        except (TypeError, ValueError):
            pass
    统计["最近时间"] = int(time.time())
    数据库.更新状态(机器人标志, 状态类型, _裁剪(学习))
    return True


def 收益分(统计: dict, 战利品优先级: str = "均衡") -> float | None:
    """每场平均收益；均衡模式下黑油按 50 倍折算（高本金币/圣水与黑油储量比约 50:1）。"""
    场次 = 统计.get("收益场次", 0)
    if not 场次:
        return None
    金, 水, 油 = (统计.get(f"{资源}和", 0) / 场次 for 资源 in ("金币", "圣水", "黑油"))
    if 战利品优先级 == "金币":
        return 金
    if 战利品优先级 == "圣水":
        return 水
    if 战利品优先级 == "黑水":
        return 油
    return 金 + 水 + 油 * 50


def 阵容对比(学习: dict, 战利品优先级: str = "均衡") -> list[dict]:
    """返回样本足够的阵容，按每场平均收益从高到低排序。"""
    结果 = []
    for 签名, 统计 in (学习.get("阵容") or {}).items():
        if 统计.get("收益场次", 0) < 比较最少样本:
            continue
        结果场次 = max(统计.get("结果场次", 0), 1)
        结果.append({
            "阵容": 签名,
            "场次": 统计.get("场次", 0),
            "胜率": round(统计.get("胜场", 0) / max(统计.get("场次", 0), 1) * 100, 1),
            "平均星数": round(统计.get("星数和", 0) / 结果场次, 2),
            "平均摧毁率": round(统计.get("摧毁率和", 0) / 结果场次, 1),
            "场均金币": round(统计.get("金币和", 0) / 统计["收益场次"]),
            "场均圣水": round(统计.get("圣水和", 0) / 统计["收益场次"]),
            "场均黑油": round(统计.get("黑油和", 0) / 统计["收益场次"]),
            "收益分": round(收益分(统计, 战利品优先级) or 0),
        })
    return sorted(结果, key=lambda 项: 项["收益分"], reverse=True)


def 对比日志(学习: dict, 当前签名: str, 战利品优先级: str = "均衡") -> str:
    对比 = 阵容对比(学习, 战利品优先级)
    if not 对比:
        统计 = (学习.get("阵容") or {}).get(当前签名) or {}
        已有 = 统计.get("收益场次", 0)
        return f"阵容学习：当前阵容已记录 {已有} 场收益，满 {比较最少样本} 场后开始比较"
    行 = [
        f"{项['阵容']}：{项['场次']}场 胜率{项['胜率']}% 场均 金{项['场均金币']:+,} 水{项['场均圣水']:+,} 油{项['场均黑油']:+,}"
        for 项 in 对比[:3]
    ]
    文本 = "阵容学习对比（按场均收益）：" + "；".join(行)
    if len(对比) >= 2 and 对比[0]["阵容"] != 当前签名:
        文本 += f"。数据显示【{对比[0]['阵容']}】收益更高，建议换回该阵容"
    return 文本
