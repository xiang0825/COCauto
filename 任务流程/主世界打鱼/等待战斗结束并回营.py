class 等待战斗结束并回营任务(基础任务):

    # 实机 1280x720 画面归一化到 800x600 后，“回营”按钮模板的稳定
    # 分数约为 0.85。0.90 会把真实结算页误判成未结束，随后外层资源
    # 循环会在结算页再次打开进攻流程。页面识别器仍会要求结算区域和
    # 结果页特征同时成立，降低这里的模板阈值不会放宽到任意绿色按钮。
    回营按钮相似度阈值 = 0.80

    def _页面确认是结算页(self, 上下文, 屏幕图像) -> bool:
        """复用点击护栏的页面识别，确认模板命中确实是结果页。"""
        try:
            获取识别器 = getattr(上下文, "_获取点击页面识别器", None)
            if not callable(获取识别器):
                return False
            结果 = 获取识别器().识别(屏幕图像, 战斗中=False)
            return bool(
                getattr(结果, "页面", "") == "战斗结算"
                and float(getattr(结果, "可信度", 0.0)) >= self.回营按钮相似度阈值
            )
        except Exception:
            return False

    def _结果页按钮可信(self, 上下文, 屏幕图像) -> bool:
        """回营模板命中后再确认结果页，避免误点战场中的绿色区域。"""
        if getattr(上下文, "_战斗结束已确认", False):
            return True
        if self._页面确认是结算页(上下文, 屏幕图像):
            return True
        try:
            强按钮, _, _ = self.模板识别.执行匹配(
                屏幕图像,
                "领取奖励.bmp|回营_领取奖励.bmp",
                相似度阈值=0.90,
            )
            if 强按钮:
                return True
            OCR结果, _ = self.ocr引擎(屏幕图像, use_cls=False)
            文本 = "".join(str(项[1]) for 项 in (OCR结果 or []) if len(项) > 1)
            return any(
                关键词 in 文本
                for 关键词 in (
                    "胜利", "勝利", "获胜", "獲勝", "失败", "失敗",
                    "战败", "戰敗", "摧毁", "摧毀", "推毁", "推毀",
                    "你得", "你获得", "你獲得", "回营", "回營", "回誉",
                    "接力赛", "接力賽",
                )
            )
        except Exception:
            return False

    def 执行(self) -> bool:
        上下文 = self.上下文

        # 判断是否为速刷模式
        是否速刷模式 = 上下文.数据库.获取机器人设置(上下文.机器人标志).是否快速刷资源

        if 是否速刷模式:
            # 速刷模式：等待4-7秒后主动放弃战斗，直接回营
            上下文.置脚本状态("速刷模式：等待4-7秒后放弃战斗", 3*60)
            上下文.脚本延时(random.randint(4*1000, 7*1000))
            # 速刷等待期间战斗可能已经自然结束。此时画面已经是结算
            # 页，不能再把“找不到放弃按钮”当作失败，也不能盲点结算
            # 页上的其它按钮；直接交给统一回营状态机确认结果和回营。
            if self._当前已确认结算页(上下文):
                上下文.置脚本状态("速刷等待期间战斗已结束，跳过放弃确认并直接回营")
            else:
                已点击放弃 = self.点击放弃战斗按钮(上下文)
                if not 已点击放弃:
                    # 速刷等待和寻找按钮之间可能正好完成自然结算；
                    # 不能把已到结算页误报成“放弃按钮丢失”。
                    if self._当前已确认结算页(上下文):
                        上下文.置脚本状态(
                            "寻找放弃按钮期间战斗已自然结束，跳过放弃确认并直接回营"
                        )
                    else:
                        上下文.置脚本状态("未找到放弃战斗按钮，回营失败")
                        return False
                elif self._当前已确认结算页(上下文):
                    # 点击放弃后游戏可能立即完成结算，确认框已被结果页
                    # 替换时禁止再点击一次“确定”，避免误触结果页控件。
                    上下文.置脚本状态(
                        "放弃操作后战斗已进入结算页，跳过投降确认并直接回营"
                    )
                elif not self.点击确定(上下文):
                    # 确认按钮等待期间同样可能自然结算，做一次最后复核。
                    if self._当前已确认结算页(上下文):
                        上下文.置脚本状态(
                            "等待投降确认期间战斗已自然结束，跳过确认并直接回营"
                        )
                    elif self.等待主界面就绪(上下文):
                        # 测试服/部分版本点击放弃后可能直接回到主世界，
                        # 不显示“确定投降”弹窗。此时页面已经安全恢复，
                        # 但没有结算页就无法可靠记录星数和摧毁率；不能
                        # 把它写成“回营失败”，也不能放行下一场战斗。
                        上下文.置脚本状态(
                            "放弃战斗后已直接回到主世界，但未出现投降确认或结算页；"
                            "本场结果未完整确认，禁止开始下一场"
                        )
                        return False
                    else:
                        上下文.置脚本状态(
                            "未找到放弃战斗确认按钮，也未确认回到主世界；保留当前画面"
                        )
                        return False
            if not self.等待回营地按钮出现(上下文):
                return False
        else:
            # 正常模式：等待战斗自然结束
            上下文.置脚本状态("开始执行回营操作", 3*60)
            if not self.等待回营地按钮出现(上下文):
                return False

        上下文.置脚本状态("回营完成")
        return True

    def _当前已确认结算页(self, 上下文) -> bool:
        """判断速刷等待结束时是否已经自然进入结算页。"""
        if bool(getattr(上下文, "_战斗结束已确认", False)):
            return True
        识别 = getattr(上下文, "识别点击画面", None)
        if not callable(识别):
            return False
        try:
            try:
                结果 = 识别(强制=True)
            except TypeError:
                结果 = 识别()
            return getattr(结果, "页面", "") in {"战斗结算", "结算"}
        except Exception:
            return False

    def 点击放弃战斗按钮(self, 上下文) -> bool:
        """点击放弃战斗按钮"""
        def 安全点击已确认按钮(x, y) -> bool:
            # 该坐标已经同时经过战斗页与红色按钮几何/模板确认。
            # 普通点击在点击后的瞬间复核到“战斗过渡”时会把已经
            # 成功发出的放弃点击误报为失败；专用通道仍是精确点击，
            # 但允许页面从战斗切换到投降确认/结算层。
            专用点击 = getattr(上下文, "点击已确认安全按钮", None)
            if callable(专用点击):
                return bool(专用点击(x, y, 延时=100))
            return 上下文.点击(x, y) is not False

        按钮区域 = (0, 0, 800, 600)
        模板路径 = "放弃战斗1.bmp|放弃战斗2.bmp|放弃战斗3.bmp|放弃战斗4.bmp|结束战斗1.bmp"
        超时时间 = 30  # 等待30秒
        开始时间 = time.time()

        while time.time() - 开始时间 < 超时时间:
            # 获取按钮区域图像
            屏幕图像 = 上下文.op.获取屏幕图像cv(*按钮区域)
            # 执行模板匹配
            是否匹配, (x, y), _ = self.模板识别.执行匹配(屏幕图像, 模板路径, 相似度阈值=0.9)
            if 是否匹配:
                return 安全点击已确认按钮(x, y)

            # 国际服/测试服的按钮字体和缩放会变化，旧小模板在实机上
            # 只有约 0.71~0.78 分，不能继续把“等待按钮”拖满30秒。
            # 这里要求页面识别已经确认仍在战斗，再用左下角红色横向
            # 按钮的几何特征定位，避免把地图或兵栏上的红色物体当作
            # 输入目标。坐标仍是 800x600 逻辑画布，和上下文点击一致。
            红色按钮 = self._定位红色放弃按钮(上下文, 屏幕图像)
            if 红色按钮 is not None:
                上下文.置脚本状态(
                    f"模板未命中，已通过战斗页红色按钮几何定位放弃："
                    f"{红色按钮[0]},{红色按钮[1]}"
                )
                return 安全点击已确认按钮(*红色按钮)

            # 间隔检测
            上下文.脚本延时(1000)

        return False

    def 点击确定(self, 上下文) -> bool:
        """点击确定按钮"""
        按钮区域 = (0, 0, 800, 600)
        模板路径 = "点击确定1.bmp|点击确定2.bmp|点击确定3.bmp"
        超时时间 = 5  # 等待30秒
        开始时间 = time.time()

        while time.time() - 开始时间 < 超时时间:
            # 获取按钮区域图像
            屏幕图像 = 上下文.op.获取屏幕图像cv(*按钮区域)
            # 执行模板匹配
            是否匹配, (x, y), _ = self.模板识别.执行匹配(屏幕图像, 模板路径, 相似度阈值=0.9)
            if 是否匹配:
                专用点击 = getattr(上下文, "点击已确认安全按钮", None)
                if callable(专用点击):
                    return bool(专用点击(x, y, 延时=100))
                return 上下文.点击(x, y) is not False
            # “要投降吗？”确认框的繁体按钮在测试服上与旧模板差异
            # 较大。这里同时要求中央下方存在绿色“确定”和左侧橙色
            # “取消”，只返回绿色按钮中心，不会把普通主世界绿色控件
            # 当成确认输入。
            确认按钮 = self._定位放弃确认按钮(屏幕图像)
            if 确认按钮 is not None:
                上下文.置脚本状态(
                    f"模板未命中，已通过投降确认框几何定位确定："
                    f"{确认按钮[0]},{确认按钮[1]}"
                )
                # 这里已经由同一帧同时确认了绿色“确定”和橙色“取消”。
                # 测试服的该确认框会被通用页面识别归类为“断线弹窗”，
                # 普通点击因此会被战斗/断线护栏拒绝，导致速刷卡在确认框。
                # 只对这个经过双按钮几何确认的非购买按钮使用专用通道，
                # 不放宽普通点击，也不允许它触碰商店或宝石入口。
                专用点击 = getattr(上下文, "点击已确认安全按钮", None)
                if callable(专用点击):
                    return bool(专用点击(*确认按钮, 延时=100))
                return 上下文.点击(*确认按钮) is not False

            # 间隔检测
            上下文.脚本延时(1000)

        return False

    def _定位放弃确认按钮(self, 屏幕图像) -> tuple[int, int] | None:
        """定位投降确认框的绿色确定按钮，要求同时存在橙色取消按钮。"""
        if not isinstance(屏幕图像, np.ndarray) or 屏幕图像.ndim < 2:
            return None
        try:
            高, 宽 = 屏幕图像.shape[:2]
            hsv = cv2.cvtColor(屏幕图像, cv2.COLOR_BGR2HSV)

            def 最大按钮(下限, 上限, 左范围, 右范围):
                掩码 = cv2.inRange(
                    hsv,
                    np.array(下限, dtype=np.uint8),
                    np.array(上限, dtype=np.uint8),
                )
                掩码 = cv2.morphologyEx(
                    掩码,
                    cv2.MORPH_CLOSE,
                    cv2.getStructuringElement(cv2.MORPH_RECT, (5, 5)),
                )
                _, _, 统计, _ = cv2.connectedComponentsWithStats(掩码, 8)
                候选 = []
                for x, y, 方框宽, 方框高, 面积 in 统计[1:]:
                    if not (
                        面积 >= int(宽 * 高 * 0.012)
                        and 方框宽 >= int(宽 * 0.12)
                        and 方框高 >= int(高 * 0.07)
                        and 左范围 <= x <= 右范围
                        and int(高 * 0.48) <= y <= int(高 * 0.72)
                    ):
                        continue
                    候选.append((int(x), int(y), int(方框宽), int(方框高), int(面积)))
                return max(候选, key=lambda 项: 项[-1], default=None)

            绿色 = 最大按钮((25, 60, 80), (100, 255, 255), 宽 * 0.42, 宽 * 0.80)
            橙色 = 最大按钮((5, 80, 80), (28, 255, 255), 宽 * 0.18, 宽 * 0.42)
            if 绿色 is None or 橙色 is None:
                return None
            if abs(绿色[1] - 橙色[1]) > max(20, int(高 * 0.06)):
                return None
            scale_x = 800 / max(1, 宽)
            scale_y = 600 / max(1, 高)
            return (
                int((绿色[0] + 绿色[2] / 2) * scale_x),
                int((绿色[1] + 绿色[3] / 2) * scale_y),
            )
        except (AttributeError, TypeError, ValueError, cv2.error):
            return None
        return None

    def 等待回营地按钮出现(self, 上下文) -> bool:
        """使用模板匹配检测下一个按钮"""

        按钮区域 = (0, 0, 800, 600)
        模板路径 = "回营1.bmp|回营.bmp|回营2.bmp|回营3.bmp|领取奖励.bmp|回营_领取奖励.bmp"
        超时时间 = 3*60  # 等待3分钟就超时
        开始时间 = time.time()

        是否已点击回营 = False
        while time.time() - 开始时间 < 超时时间:
            # 获取按钮区域图像
            屏幕图像 = 上下文.op.获取屏幕图像cv(*按钮区域)
            # 进攻阶段可能已经快速完成回营；不要在主城画面等待三分钟。
            if getattr(上下文, "_已确认进入战斗", False):
                已回主城, _, _ = self.模板识别.执行匹配(
                    屏幕图像,
                    "家乡进攻图标.bmp|家乡进攻图标1.bmp|家乡进攻图标2.bmp|家乡进攻图标3.bmp",
                    相似度阈值=0.85,
                )
                if 已回主城:
                    结果画面 = getattr(上下文, "_战斗结束截图", None)
                    if 结果画面 is None:
                        结果画面 = 屏幕图像
                    结果统计完整 = self.记录战斗结果(
                        上下文,
                        结果画面,
                    )
                    if not 结果统计完整:
                        上下文.置脚本状态(
                            "战斗结果/星数/摧毁率未完整确认，保留结算页并禁止进入下一场",
                            30,
                        )
                        return False
                    上下文.置脚本状态("检测到已在主城，跳过重复等待回营")
                    return True
            # 执行模板匹配
            是否匹配, (x, y), _ = self.模板识别.执行匹配(
                屏幕图像,
                模板路径,
                相似度阈值=self.回营按钮相似度阈值,
            )
            # 主世界国际服的结算页常把“回营”放在左下竖向角色卡片，
            # 旧模板只覆盖中央横向按钮，容易在真实 97%/2 星结算页
            # 低分失配后一直等待。模板未命中时复用页级结算识别器，
            # 只有“结果页结构 + 左下安全卡片”同时确认才授权点击。
            视觉回营点 = None
            if not 是否匹配:
                try:
                    获取识别器 = getattr(上下文, "_获取点击页面识别器", None)
                    if callable(获取识别器):
                        页面识别器 = 获取识别器()
                        页面结果 = 页面识别器.识别(
                            屏幕图像,
                            战斗中=False,
                        )
                        if getattr(页面结果, "页面", "") == "战斗结算":
                            视觉回营点 = 页面识别器.定位结算回营按钮(屏幕图像)
                            if 视觉回营点 is not None:
                                是否匹配 = True
                                x, y = 视觉回营点
                                上下文.置脚本状态(
                                    f"模板未命中，已视觉确认结算页回营按钮：{x},{y}"
                                )
                except Exception as 异常:
                    上下文.置脚本状态(f"视觉回营按钮复核失败：{异常}")
            if 是否匹配 and (
                视觉回营点 is not None
                or self._结果页按钮可信(上下文, 屏幕图像)
            ):
                if not 是否已点击回营:
                    是否已点击回营 = True
                    # 这里的画面已经命中回营按钮，优先用同一帧记录结果，
                    # 不要再额外截图把短暂的结果页换成主城画面。
                    结果统计完整 = self.记录战斗结果(上下文, 屏幕图像)
                    if not 结果统计完整:
                        上下文.置脚本状态(
                            "战斗结果/星数/摧毁率未完整确认，保留结算页并禁止进入下一场",
                            30,
                        )
                        return False
                    上下文.置脚本状态("检测到回营按钮，点击返回主界面")
                    # 回营按钮已经由结算模板/页级视觉双重确认。结算页
                    # 普通点击护栏必须阻断输入，避免继续下兵或误触宝石；
                    # 因此回营必须走“已确认安全按钮”专用通道。保留
                    # 普通点击回退仅用于旧版测试上下文，生产上下文一定
                    # 提供该专用方法，并且点击后仍必须复核主世界主页。
                    安全点击 = getattr(上下文, "点击已确认安全按钮", None)
                    if callable(安全点击):
                        点击成功 = 安全点击(x, y)
                    else:
                        点击成功 = 上下文.点击(x, y)
                    if 点击成功 is False:
                        上下文.置脚本状态(
                            "回营按钮输入被拒绝，禁止误判为已回主界面"
                        )
                        return False
                    已回主界面 = self.等待主界面就绪(上下文)
                    if 已回主界面:
                        # 清除本场状态，避免下一场继承旧结算标志。
                        上下文._已确认进入战斗 = False
                        上下文._战斗结束已确认 = False
                        上下文._回营模板连续命中 = 0
                    return 已回主界面

            # 间隔检测
            上下文.脚本延时(500)

        return False

    def _定位红色放弃按钮(self, 上下文, 屏幕图像) -> tuple[int, int] | None:
        """仅在页面确认战斗时定位左下角红色放弃按钮。"""
        if not isinstance(屏幕图像, np.ndarray) or 屏幕图像.ndim < 2:
            return None
        try:
            获取识别器 = getattr(上下文, "_获取点击页面识别器", None)
            if not callable(获取识别器):
                return None
            页面结果 = 获取识别器().识别(屏幕图像, 战斗中=True)
            if getattr(页面结果, "页面", "") != "战斗中":
                return None
            高, 宽 = 屏幕图像.shape[:2]
            左 = 0
            右 = max(1, int(宽 * 0.22))
            上 = int(高 * 0.67)
            区域 = 屏幕图像[上:, 左:右]
            if 区域.size == 0:
                return None
            hsv = cv2.cvtColor(区域, cv2.COLOR_BGR2HSV)
            色相 = hsv[:, :, 0]
            掩码 = (
                ((色相 <= 12) | (色相 >= 170))
                & (hsv[:, :, 1] >= 90)
                & (hsv[:, :, 2] >= 80)
            ).astype(np.uint8)
            掩码 = cv2.morphologyEx(
                掩码,
                cv2.MORPH_CLOSE,
                cv2.getStructuringElement(cv2.MORPH_RECT, (3, 3)),
            )
            _, _, 统计, _ = cv2.connectedComponentsWithStats(掩码, 8)
            for x, y, 方框宽, 方框高, 面积 in 统计[1:]:
                if not (
                    面积 >= max(600, int(宽 * 高 * 0.005))
                    and 方框宽 >= max(55, int(区域.shape[1] * 0.28))
                    and 方框高 >= max(20, int(高 * 0.03))
                    and 方框宽 / max(1, 方框高) >= 1.5
                    and x <= max(40, int(区域.shape[1] * 0.25))
                    and y <= int(区域.shape[0] * 0.75)
                ):
                    continue
                scale_x = 800 / max(1, 宽)
                scale_y = 600 / max(1, 高)
                return (
                    int((x + 方框宽 / 2) * scale_x),
                    int((上 + y + 方框高 / 2) * scale_y),
                )
        except (AttributeError, TypeError, ValueError, cv2.error):
            return None
        return None

    def 等待主界面就绪(self, 上下文) -> bool:
        """点击回营后确认主界面的进攻入口已出现，防止下一轮误点卡住。"""
        模板路径 = "家乡进攻图标.bmp|家乡进攻图标1.bmp|家乡进攻图标2.bmp|家乡进攻图标3.bmp"
        开始时间 = time.time()
        主世界连续确认次数 = 0
        页级识别器可用 = callable(getattr(上下文, "_获取点击页面识别器", None))
        while time.time() - 开始时间 < 30:
            屏幕图像 = 上下文.op.获取屏幕图像cv(0, 0, 800, 600)
            # 实机缩放后“家乡进攻图标”模板可能只有 0.57 左右，但
            # 页面识别器同时确认了主世界资源栏和主世界入口。优先使用
            # 这个页级结果，避免已经回营却因单个模板阈值过高而停止。
            # 页级识别器可用时绝不能再回退到底层“家乡进攻图标”模板：
            # 断线弹窗、升级确认层或结算遮罩可能露出底层图标，模板命中
            # 不代表当前真的可以点击主世界入口。
            try:
                获取识别器 = getattr(上下文, "_获取点击页面识别器", None)
                if callable(获取识别器):
                    页面结果 = 获取识别器().识别(屏幕图像, 战斗中=False)
                    if (
                        getattr(页面结果, "页面", "") == "主世界主页"
                        and float(getattr(页面结果, "可信度", 0.0)) >= 0.50
                    ):
                        主世界连续确认次数 += 1
                        if 主世界连续确认次数 >= 2:
                            上下文.置脚本状态(
                                f"页面识别连续确认已回到主世界（置信度 {页面结果.可信度:.2f}）"
                            )
                            return True
                    else:
                        主世界连续确认次数 = 0
                        当前页面 = getattr(页面结果, "页面", "未知")
                        if 当前页面 != "主世界主页":
                            上下文.置脚本状态(
                                f"回营后尚未确认主世界（当前={当前页面}），禁止进入下一场"
                            )
                    上下文.脚本延时(500)
                    continue
            except (AttributeError, TypeError, ValueError):
                # 页级识别器在真实运行中已绑定时，识别异常也不能用底层
                # 图标模板冒险通过；继续重试直到超时并保留当前画面。
                if 页级识别器可用:
                    上下文.脚本延时(500)
                    continue
            是否匹配, _, _ = self.模板识别.执行匹配(屏幕图像, 模板路径, 相似度阈值=0.8)
            if 是否匹配:
                上下文.置脚本状态("已确认回到主界面，可进入下一场")
                return True
            上下文.脚本延时(500)
        上下文.置脚本状态("回营按钮已点击，但30秒内未确认主界面")
        return False

    @staticmethod
    def 从OCR文本判断战斗结果(OCR文本: str) -> str:
        """从结果页 OCR 文本判断胜负；识别不到时返回未知，不猜测。"""
        文本 = str(OCR文本 or "")
        if any(词 in 文本 for 词 in ("胜利", "勝利", "获胜", "獲勝", "胜出", "勝出")):
            return "胜利"
        if any(词 in 文本 for 词 in ("失败", "失敗", "战败", "戰敗")):
            return "失败"
        # 测试服/繁体结算横幅的首字经常被背景吞掉。真实截图中
        # “戰敗”会被 RapidOCR 识别成“败”或“氧败”；结果页局部
        # OCR 也可能只保留“胜”。这些单字只在结果页调用链中使用，
        # 不能再因为漏掉首字而把明确结果写成“未知”。
        if any(字 in 文本 for 字 in ("败", "敗")):
            return "失败"
        if any(字 in 文本 for 字 in ("胜", "勝")):
            return "胜利"
        return "未知"

    def 识别结果页横幅文本(self, 屏幕图像) -> str:
        """对结算横幅做一次局部 OCR，补足整屏 OCR 漏字。"""
        if not isinstance(屏幕图像, np.ndarray) or 屏幕图像.ndim < 2:
            return ""
        try:
            高, 宽 = 屏幕图像.shape[:2]
            if 高 <= 0 or 宽 <= 0:
                return ""
            # 逻辑画布为 800x600 时，战败/胜利横幅位于 x=144..656、
            # y=96..288；使用比例坐标兼容自适应分辨率。
            左 = int(宽 * 0.18)
            右 = int(宽 * 0.82)
            上 = int(高 * 0.16)
            下 = int(高 * 0.48)
            if 右 <= 左 or 下 <= 上:
                return ""
            横幅 = 屏幕图像[上:下, 左:右]
            # 结算横幅的金色丝带会把原色 OCR 的文字吞掉，尤其是
            # 繁体“戰敗/勝利”。实机截图中灰度化后反而能稳定保留
            # 文字轮廓，因此保留原图结果，同时补跑一次灰度图；只在
            # 两者都没有文字时才使用放大灰度图，避免每次结果页都
            # 额外创建多套大图和 ONNX 缓冲。
            待识别图像列表 = [横幅]
            if getattr(横幅, "ndim", 0) == 3:
                待识别图像列表.append(cv2.cvtColor(横幅, cv2.COLOR_BGR2GRAY))
                # 横幅较大时，整块灰度 OCR 容易被战利品数字抢占；
                # 再取中间的结果词区域，专门覆盖“戰敗/勝利”所在位置。
                词区 = 屏幕图像[
                    int(高 * 0.20):int(高 * 0.42),
                    int(宽 * 0.30):int(宽 * 0.70),
                ]
                if getattr(词区, "size", 0):
                    待识别图像列表.append(
                        cv2.cvtColor(词区, cv2.COLOR_BGR2GRAY)
                    )
            文本列表 = []
            for 待识别图像 in 待识别图像列表:
                OCR结果, _ = self.ocr引擎(待识别图像, use_cls=False)
                文本 = "".join(
                    str(项[1]) for 项 in (OCR结果 or []) if len(项) > 1
                )
                if 文本:
                    文本列表.append(文本)
            return "".join(文本列表)
        except Exception:
            # 结果统计不能因为补充 OCR 失败而阻塞回营；整屏 OCR
            # 或实时摧毁率仍然会保留。
            return ""

    def 识别结算帧(self, 屏幕图像):
        """识别一帧结算画面的 OCR、结果文字和摧毁率。"""
        OCR结果, _ = self.ocr引擎(屏幕图像)
        文本 = "".join(str(项[1]) for 项 in (OCR结果 or []) if len(项) > 1)
        结果 = self.从OCR文本判断战斗结果(文本)
        if 结果 == "未知":
            横幅文本 = self.识别结果页横幅文本(屏幕图像)
            if 横幅文本:
                文本 += 横幅文本
                结果 = self.从OCR文本判断战斗结果(文本)
        摧毁率 = self.从OCR结果提取摧毁率(OCR结果, 文本)
        return OCR结果, 文本, 结果, 摧毁率

    @staticmethod
    def 从OCR文本提取摧毁率(OCR文本: str):
        """提取带百分号的摧毁率；没有识别到时返回 None。"""
        文本 = (
            str(OCR文本 or "")
            .replace("％", "%")
            .replace("摧毀", "摧毁")
            .replace("推毀", "摧毁")
            .replace("推毁", "摧毁")
            .replace("破壞率", "摧毁率")
            .replace("破坏率", "摧毁率")
        )
        百分比列表 = [int(值) for 值 in re.findall(r"(?<!\d)(100|[1-9]?\d)\s*%", 文本)]
        return 百分比列表[0] if 百分比列表 else None

    @staticmethod
    def 从OCR结果提取摧毁率(OCR结果, OCR文本: str = ""):
        """兼容 OCR 把“摧毁率”和数字/百分号拆成多个识别框的情况。"""
        文本 = (
            str(OCR文本 or "")
            .replace("％", "%")
            .replace("摧毀", "摧毁")
            .replace("推毀", "摧毁")
            .replace("推毁", "摧毁")
            .replace("破壞率", "摧毁率")
            .replace("破坏率", "摧毁率")
        )
        直接值 = 等待战斗结束并回营任务.从OCR文本提取摧毁率(文本)
        if 直接值 is not None:
            return 直接值

        项目 = []
        for 项 in OCR结果 or []:
            if len(项) < 2:
                continue
            框, 内容 = 项[0], str(项[1]).replace("％", "%")
            try:
                中心x = sum(float(点[0]) for 点 in 框) / len(框)
                中心y = sum(float(点[1]) for 点 in 框) / len(框)
            except Exception:
                中心x, 中心y = 0.0, 0.0
            项目.append((中心x, 中心y, 内容))

        # 先处理“摧毁率 67”或“摧毁率67%”同框的情况。
        for _, _, 内容 in 项目:
            if any(词 in 内容 for 词 in ("摧毁", "摧毀", "推毁", "推毀", "破坏", "破壞")):
                匹配 = re.search(r"摧毁[^0-9]{0,8}(100|[1-9]?\d)", 内容)
                if 匹配:
                    return int(匹配.group(1))

        # 再找“摧毁率”标签附近的 0-100 数字，避免把顶部资源数字当结果。
        标签 = [
            (x, y)
            for x, y, 内容 in 项目
            if any(词 in 内容 for 词 in ("摧毁", "摧毀", "推毁", "推毀", "破坏", "破壞"))
        ]
        if 标签:
            标签x, 标签y = 标签[0]
            候选 = []
            for x, y, 内容 in 项目:
                if abs(y - 标签y) > 70:
                    continue
                数字文本 = re.findall(r"(?<!\d)(100|[1-9]?\d)(?!\d)", 内容)
                for 数字 in 数字文本:
                    值 = int(数字)
                    if 0 <= 值 <= 100:
                        候选.append((abs(x - 标签x) + abs(y - 标签y) * 1.5, 值))
            if 候选:
                return min(候选, key=lambda 项: 项[0])[1]
        return None

    @staticmethod
    def 识别星数(屏幕图像, OCR文本: str):
        """优先从 OCR 读取星数，再按固定结果页星形几何检测。"""
        文本 = str(OCR文本 or "")
        匹配 = re.search(r"([0-3])\s*星", 文本)
        if 匹配:
            return int(匹配.group(1))
        # 战败的结果语义本身就确定为 0 星；先返回，避免把金色结算
        # 横幅或资源图标误当成星形区域。
        if any(词 in 文本 for 词 in ("失败", "失敗", "战败", "戰敗", "败", "敗")):
            return 0
        有结果语义 = any(
            词 in 文本
            for 词 in ("胜利", "勝利", "获胜", "獲勝", "胜出", "勝出", "胜", "勝")
        )
        if 屏幕图像 is None or getattr(屏幕图像, "ndim", 0) != 3:
            return None

        高, 宽 = 屏幕图像.shape[:2]
        if 高 <= 0 or 宽 <= 0:
            return None

        # CoC 结果页的三颗星不是一条水平线，而是“左下、中央上、
        # 右下”的三角排布。相对位置和大小在不同分辨率下保持稳定；
        # 只检测每个星形内部相对周边的亮度差，不再把整条金色横幅
        # 当作连通块计数。
        灰度 = cv2.cvtColor(屏幕图像, cv2.COLOR_BGR2GRAY)

        # 测试服/夜世界的结果页可能只有“摧毁率 + 星形图标”，不显示
        # “胜利/战败”文字。该布局的三颗星按“左下、中央上、右下”
        # 排列，亮星为高饱和金色，空星为低饱和灰色。先用颜色在三角
        # 布局中计数；没有强证据时仍返回 None，禁止猜测结果。
        hsv = cv2.cvtColor(屏幕图像, cv2.COLOR_BGR2HSV)
        三角星中心 = (
            (宽 * 0.388, 高 * 0.300),
            (宽 * 0.500, 高 * 0.240),
            (宽 * 0.612, 高 * 0.300),
        )
        金色掩码 = (
            (hsv[:, :, 0] >= 5)
            & (hsv[:, :, 0] <= 40)
            & (hsv[:, :, 1] >= 80)
            & (hsv[:, :, 2] >= 100)
        )
        亮星数 = 0
        取样半径 = max(14, round(min(宽, 高) * 0.055))
        for 中心x, 中心y in 三角星中心:
            x = round(中心x)
            y = round(中心y)
            x1 = max(0, x - 取样半径)
            x2 = min(宽, x + 取样半径 + 1)
            y1 = max(0, y - 取样半径)
            y2 = min(高, y + 取样半径 + 1)
            区域面积 = max(1, (x2 - x1) * (y2 - y1))
            if int(np.count_nonzero(金色掩码[y1:y2, x1:x2])) / 区域面积 >= 0.18:
                亮星数 += 1
        if not 有结果语义:
            # 一星以上是 CoC 的确定胜利证据；没有亮星时不猜战败，
            # 由结果文字或调用方明确的战败状态处理。夜世界测试服的
            # 结算横幅有时完全没有“战败”文字，但会稳定显示“摧毁率
            # xx%”和三颗全部熄灭的星；在已确认的结果页中，这组证据
            # 足以记录 0 星，不能把真实结算页留成未知而卡住回营。
            if 亮星数 > 0:
                return 亮星数
            if (
                any(词 in 文本 for 词 in ("摧毁率", "摧毀率", "破坏率", "破壞率"))
                and re.search(r"(?<!\d)(100|[1-9]?\d)\s*%", 文本)
            ):
                return 0
            return None
        半径 = min(宽 * 0.07, 高 * 0.095)

        def 星形掩码(中心x, 中心y, 半径值, 比例):
            点列表 = []
            for 索引 in range(10):
                角度 = -np.pi / 2 + 索引 * np.pi / 5
                当前半径 = 半径值 * 比例 * (1.0 if 索引 % 2 == 0 else 0.42)
                点列表.append(
                    (
                        round(中心x + 当前半径 * np.cos(角度)),
                        round(中心y + 当前半径 * np.sin(角度)),
                    )
                )
            掩码 = np.zeros((高, 宽), dtype=np.uint8)
            cv2.fillPoly(掩码, [np.asarray(点列表, dtype=np.int32)], 255)
            return 掩码.astype(bool)

        星形中心 = (
            (宽 * 0.381, 高 * 0.220),
            (宽 * 0.506, 高 * 0.125),
            (宽 * 0.625, 高 * 0.225),
        )
        已点亮 = 0
        for 中心x, 中心y in 星形中心:
            内部 = 星形掩码(中心x, 中心y, 半径, 0.62)
            外环 = (
                星形掩码(中心x, 中心y, 半径 * 1.45, 1.0)
                & ~星形掩码(中心x, 中心y, 半径, 1.05)
            )
            if not np.any(内部) or not np.any(外环):
                continue
            亮度差 = float(灰度[内部].mean() - 灰度[外环].mean())
            # 结果动画可能整体变白，故阈值不能写成绝对亮度；
            # 实机过渡结算样本中，点亮星约 6~8 以上，空星约 0~1。
            if 亮度差 >= 5.0:
                已点亮 += 1
        return 已点亮 if 已点亮 else (亮星数 if 亮星数 > 0 else None)

    @staticmethod
    def 校正星数(结果: str, 星数, 摧毁率):
        """按 CoC 结果语义校正星数，过滤结果页视觉误报。"""
        # “战败”表示本场没有取得战斗之星；不能让结算横幅的
        # 金色连通区域把它误识别成 1~3 星。
        if 结果 == "失败":
            return 0
        # 胜利且低于 50% 时，只可能是摧毁了大本营，确定为 1 星。
        if 结果 == "胜利" and 摧毁率 is not None and 摧毁率 < 50:
            return 1
        if 结果 == "胜利" and 摧毁率 == 100:
            return 3
        if 星数 == 3 and (
            结果 == "胜利" and 摧毁率 is not None and 摧毁率 < 100
        ):
            return None
        return 星数

    @staticmethod
    def 星数校正说明(结果: str, 原始星数, 星数, 摧毁率):
        """返回本次星数校正的可解释日志；无需校正时返回空值。"""
        if 原始星数 == 星数:
            return None
        if 结果 == "失败":
            return "结算结果为战败，已按规则校正为0星"
        if 结果 == "胜利" and 摧毁率 is not None and 摧毁率 < 50:
            return "胜利但摧毁率低于50%，已按大本营被摧毁校正为1星"
        if 结果 == "胜利" and 摧毁率 == 100 and 星数 == 3:
            # 100% 摧毁在 CoC 规则上必然是三星。结果页动画、主题色
            # 或 OCR 偶尔会把亮星读成 1/2 星；这是安全的规则校正，
            # 不应再被记录成“星数与摧毁率矛盾”。
            return "最终摧毁率100%，按规则确认3星，已覆盖结果页星形误识别"
        return "结果页星数与摧毁率矛盾，已标记星数待复核"

    @staticmethod
    def 合并本场摧毁率(结算摧毁率, 实时摧毁率):
        """合并结算页与战斗中实时进度，避免过渡帧覆盖真实值。

        摧毁率只会随战斗推进增加。回营按钮刚出现时，结算页 OCR
        可能把百分号识别成 0%，所以实时值是可靠的下限；两个值都
        有效时取较大值，避免把已确认的实时进度降回 0。
        """
        def 有效值(值):
            try:
                值 = int(值)
            except (TypeError, ValueError):
                return None
            return 值 if 0 <= 值 <= 100 else None

        结算值 = 有效值(结算摧毁率)
        实时值 = 有效值(实时摧毁率)
        if 结算值 is None:
            return 实时值
        if 实时值 is None:
            return 结算值
        return max(结算值, 实时值)

    def 记录战斗结果(self, 上下文, 屏幕图像=None) -> bool:
        """强制记录每场战斗的胜负、星数和摧毁率。

        返回值表示三项统计是否都已确认。未确认时仍保存诊断和截图，
        但调用方必须阻止回营后的下一场，避免把“待识别”伪装成完整结果。
        """
        try:
            if 屏幕图像 is None:
                屏幕图像 = getattr(上下文, "_战斗结束截图", None)
            if 屏幕图像 is None:
                屏幕图像 = 上下文.op.获取屏幕图像cv(0, 0, 800, 600)
            OCR结果, 文本, 结果, 摧毁率 = self.识别结算帧(屏幕图像)
            if 结果 == "未知":
                # 回营按钮会先于横幅动画稳定出现。不要用这张过渡帧
                # 写入“未知”；短暂等待后强制抓一张新帧再识别一次。
                上下文.置脚本状态("结算动画尚未稳定，等待后重新识别结果页")
                延时 = getattr(上下文, "脚本延时", None)
                if callable(延时):
                    延时(800)
                try:
                    try:
                        新屏幕图像 = 上下文.op.获取屏幕图像cv(
                            0, 0, 800, 600, 强制刷新=True
                        )
                    except TypeError:
                        新屏幕图像 = 上下文.op.获取屏幕图像cv(0, 0, 800, 600)
                except Exception:
                    # 重新抓帧失败不能阻断已经确认的回营流程；保留
                    # 首帧的摧毁率/实时值，下一场再继续采集。
                    新屏幕图像 = None
                if isinstance(新屏幕图像, np.ndarray) and 新屏幕图像.size:
                    新OCR结果, 新文本, 新结果, 新摧毁率 = self.识别结算帧(
                        新屏幕图像
                    )
                    if 新结果 != "未知":
                        屏幕图像 = 新屏幕图像
                        OCR结果 = 新OCR结果
                        文本 = 新文本
                        结果 = 新结果
                        摧毁率 = 新摧毁率
                        上下文.置脚本状态(
                            f"稳定结算帧已识别：{结果}"
                        )
            实时摧毁率 = max(
                int(getattr(上下文, "本场实时摧毁率", 0) or 0),
                int(getattr(上下文, "本场最高实时摧毁率", 0) or 0),
            )
            合并前摧毁率 = 摧毁率
            摧毁率 = self.合并本场摧毁率(摧毁率, 实时摧毁率)
            if 合并前摧毁率 != 摧毁率 and 实时摧毁率:
                上下文.置脚本状态(
                    f"结算摧毁率{合并前摧毁率 if 合并前摧毁率 is not None else '未识别'}%"
                    f"与实时最高{实时摧毁率}%合并为{摧毁率}%"
                )

            self.保存战斗结果截图(上下文, 屏幕图像)

            星数 = self.识别星数(屏幕图像, 文本)
            if 结果 == "未知" and 星数 is not None:
                # 夜世界/测试服结果页有时不渲染胜负文字，但星数仍是
                # CoC 的确定结果证据：一星以上为胜利，亮星缺失时不猜。
                结果 = "胜利" if 星数 > 0 else "失败"
                上下文.置脚本状态(
                    f"结果页未识别胜负文字，已依据星数{星数}推断结果：{结果}"
                )
            # CoC 的“战败”结算语义就是未取得任何战斗之星；即使
            # 星形图标被动画/背景遮挡，也必须把这场结果完整记录为 0 星。
            # 100% 胜利同理可确定为三星，不依赖图标 OCR。
            if 星数 is None and 结果 == "失败":
                星数 = 0
            elif 星数 is None and 结果 == "胜利" and 摧毁率 == 100:
                星数 = 3

            # Clash of Clans 的三星必须达到 100% 摧毁；“49%＋3星”
            # 是 OCR/结果页误识别，不能写入学习统计。
            原始星数 = 星数
            星数 = self.校正星数(结果, 星数, 摧毁率)
            校正说明 = self.星数校正说明(结果, 原始星数, 星数, 摧毁率)
            if 校正说明:
                上下文.置脚本状态(校正说明)
            目标战利品 = getattr(上下文, "本场目标战利品", {}) or {}
            目标战利品.setdefault(
                "资源易窃取评分",
                getattr(上下文, "本场资源易窃取评分", None),
            )
            目标战利品.setdefault(
                "资源易窃取评分依据",
                getattr(上下文, "本场资源评估", {}),
            )
            目标战利品.setdefault(
                "资源评分状态",
                getattr(上下文, "本场资源评分状态", "未知"),
            )
            目标战利品.setdefault(
                "资源评分原因",
                getattr(上下文, "本场资源评分说明", ""),
            )

            旧状态 = 上下文.数据库.获取最新完整状态(上下文.机器人标志)
            统计 = dict(旧状态.状态数据.get("战斗胜率", {}))
            统计["完成场次"] = int(统计.get("完成场次", 0)) + 1
            if 结果 in {"胜利", "失败"}:
                统计["识别场次"] = int(统计.get("识别场次", 0)) + 1
                键 = "胜场" if 结果 == "胜利" else "负场"
                统计[键] = int(统计.get(键, 0)) + 1
            if 星数 is not None:
                统计["最近星数"] = 星数
                统计["累计星数"] = int(统计.get("累计星数", 0)) + 星数
                统计["平均星数"] = round(统计["累计星数"] / 统计["完成场次"], 2)
            else:
                统计["最近星数"] = None
            if 摧毁率 is not None:
                统计["最近摧毁率"] = 摧毁率
                统计["累计摧毁率"] = int(统计.get("累计摧毁率", 0)) + 摧毁率
                统计["平均摧毁率"] = round(统计["累计摧毁率"] / 统计["完成场次"], 2)
            else:
                统计["最近摧毁率"] = None
            统计["最近结果"] = 结果
            统计["最近战利品目标"] = {
                "金币": 目标战利品.get("金币"),
                "圣水": 目标战利品.get("圣水"),
                "黑油": 目标战利品.get("黑油"),
            }
            统计["最近资源易窃取评分"] = 目标战利品.get("资源易窃取评分")
            统计["最近资源评分状态"] = 目标战利品.get("资源评分状态")
            统计["最近资源评分说明"] = 目标战利品.get("资源评分原因", "")
            统计["最近英雄技能状态"] = getattr(上下文, "英雄技能状态", {}) or {}
            诊断 = self.生成战斗诊断(
                结果, 星数, 摧毁率, 目标战利品, 上下文
            )
            统计["最近诊断"] = 诊断
            识别场次 = int(统计.get("识别场次", 0))
            统计["胜率"] = round(统计.get("胜场", 0) / 识别场次 * 100, 1) if 识别场次 else None
            上下文.数据库.更新状态(上下文.机器人标志, "战斗胜率", 统计)
            self.更新战斗学习(上下文, 结果, 星数, 摧毁率, 目标战利品)
            上下文.置脚本状态(
                f"战斗结果：{结果}；星数：{星数 if 星数 is not None else '待识别'}；"
                f"摧毁率：{摧毁率 if 摧毁率 is not None else '待识别'}%；"
                f"当前胜率：{统计['胜率'] if 统计['胜率'] is not None else '待识别'}%；"
                f"英雄技能：{统计['最近英雄技能状态'] or '无英雄'}；{诊断}"
            )
            return bool(
                结果 in {"胜利", "失败"}
                and 星数 is not None
                and 摧毁率 is not None
            )
        except Exception as 异常:
            上下文.置脚本状态(f"试战结果统计失败：{异常}")
            return False

    def 保存战斗结果截图(self, 上下文, 屏幕图像) -> None:
        """可选保存结果页，给后续模板校准/策略复盘提供样本。"""
        try:
            if not 上下文.设置.是否采集进攻界面图像:
                return
            目录 = Path("数据集") / "战斗结果"
            目录.mkdir(parents=True, exist_ok=True)
            文件名 = 目录 / f"result_{int(time.time() * 1000)}.png"
            # Windows 版 OpenCV 的 imwrite 对包含中文目录的路径可能静默
            # 返回 False；先编码，再由 pathlib 写字节，确保“采集进攻
            # 界面图像”真的留下结果页样本。
            编码成功, PNG数据 = cv2.imencode(".png", 屏幕图像)
            if not 编码成功:
                raise RuntimeError("PNG 编码失败")
            文件名.write_bytes(PNG数据.tobytes())
        except Exception as 异常:
            上下文.置脚本状态(f"保存战斗结果截图失败：{异常}")

    def 更新战斗学习(self, 上下文, 结果: str, 星数, 摧毁率, 目标战利品: dict) -> None:
        """保存可解释的在线反馈，并给下一场提供策略建议。"""
        try:
            旧状态 = 上下文.数据库.获取最新完整状态(上下文.机器人标志)
            学习 = dict(旧状态.状态数据.get("战斗学习", {}))
            近期 = list(学习.get("近期", []))
            记录 = {
                "结果": 结果,
                "星数": 星数,
                "摧毁率": 摧毁率,
                "目标战利品": {
                    "金币": 目标战利品.get("金币"),
                    "圣水": 目标战利品.get("圣水"),
                    "黑油": 目标战利品.get("黑油"),
                },
                "资源易窃取评分": 目标战利品.get("资源易窃取评分"),
                "资源易窃取评分依据": 目标战利品.get("资源易窃取评分依据", {}),
                "资源评分状态": 目标战利品.get("资源评分状态"),
                "资源评分说明": 目标战利品.get("资源评分原因", ""),
                "策略": getattr(上下文, "本场进攻策略", "集中资源"),
                "方向": getattr(上下文, "本场进攻方向", []),
                "目标数量": int(getattr(上下文, "本场进攻目标数量", 0) or 0),
                "边缘目标数量": int(getattr(上下文, "本场边缘目标数量", 0) or 0),
                "进攻方向数量": int(getattr(上下文, "本场进攻方向数量", 0) or 0),
                "英雄技能": getattr(上下文, "英雄技能状态", {}),
                "时间": int(time.time()),
            }
            近期.append(记录)
            学习["近期"] = 近期[-20:]
            学习["总场次"] = int(学习.get("总场次", 0)) + 1
            学习["胜场"] = int(学习.get("胜场", 0)) + (1 if 结果 == "胜利" else 0)
            学习["负场"] = int(学习.get("负场", 0)) + (1 if 结果 == "失败" else 0)
            有效百分比 = [项["摧毁率"] for 项 in 学习["近期"] if 项.get("摧毁率") is not None]
            学习["平均摧毁率"] = round(sum(有效百分比) / len(有效百分比), 1) if 有效百分比 else None
            低表现次数 = sum(
                项.get("结果") == "失败"
                or (项.get("摧毁率") is not None and int(项["摧毁率"]) < 50)
                for 项 in 学习["近期"][-3:]
            )
            最新证据 = {
                "目标数量": 记录["目标数量"],
                "边缘目标数量": 记录["边缘目标数量"],
                "进攻方向数量": 记录["进攻方向数量"],
            }
            已完成分散覆盖 = (
                最新证据["目标数量"] >= 8
                # 两个相对方向（例如实机常见的左上/右上）已经足以
                # 证明不是单点死磕；要求 3 个方向会让双侧地图永远
                # 停留在“分散探索”，无法进入下一阶段的高可达目标聚焦。
                and 最新证据["进攻方向数量"] >= 2
                and 最新证据["边缘目标数量"] >= max(
                    4, round(最新证据["目标数量"] * 0.5)
                )
            )
            if 低表现次数 >= 2 and 已完成分散覆盖:
                学习["下一场建议"] = "提高目标可达评分"
            else:
                学习["下一场建议"] = "分散探索" if 低表现次数 >= 2 else "集中资源"
            学习["最近原因"] = self.生成战斗诊断(
                结果, 星数, 摧毁率, 目标战利品, 上下文
            )
            上下文.数据库.更新状态(上下文.机器人标志, "战斗学习", 学习)
            上下文.置脚本状态(
                f"学习反馈：{学习['最近原因']}；下一场建议【{学习['下一场建议']}】"
            )
        except Exception as 异常:
            上下文.置脚本状态(f"战斗学习记录失败：{异常}")

    @staticmethod
    def 生成战斗诊断(
        结果: str, 星数, 摧毁率, 目标战利品: dict, 上下文=None
    ) -> str:
        if 结果 == "未知":
            return "未识别战斗结果：已保留结束画面，检查结果页模板与OCR"
        if 摧毁率 is None:
            return "未识别最终摧毁率：需要保留结果页截图复核"
        if 结果 == "失败":
            if 摧毁率 < 50:
                目标数量 = int(getattr(上下文, "本场进攻目标数量", 0) or 0)
                边缘目标数量 = int(getattr(上下文, "本场边缘目标数量", 0) or 0)
                方向数量 = int(getattr(上下文, "本场进攻方向数量", 0) or 0)
                if 目标数量 >= 8 and 方向数量 >= 3:
                    边缘比例 = 边缘目标数量 / 目标数量 if 目标数量 else 0
                    if 边缘比例 >= 0.5:
                        return (
                            "已完成多方向边缘资源覆盖但摧毁率低："
                            "更可能是敌方核心防御或内圈储存建筑不可达；"
                            "下一场优先筛选可达评分更高的阵营"
                        )
                    return (
                        "已执行多方向下兵但边缘目标比例偏低："
                        "下一场优先筛选边缘资源更多、入口更清晰的阵营"
                    )
                if 目标数量 < 4 or 方向数量 < 2:
                    return (
                        "失败且摧毁率低：资源目标或进攻入口不足；"
                        "检查目标识别、边界候选点和兵栏反馈"
                    )
                return "失败且摧毁率低：检查敌方布局、兵种等级和攻城器械"
            return "失败但摧毁率尚可：检查大本营/星数目标和英雄技能"
        if 星数 is not None and 星数 < 2:
            return "已获胜但星数偏低：下一场增加分散入口并优先核心建筑"
        if 摧毁率 < 50:
            return "资源获取偏少：摧毁率低，下一场扩大入口分布"
        if not any(目标战利品.get(资源) for 资源 in ("金币", "圣水", "黑油")):
            return "结果正常但目标战利品缺失：检查搜索页资源 OCR"
        return "本场表现正常，保留当前策略"
