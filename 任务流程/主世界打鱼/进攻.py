            检测结果列表 = self.检测器.检测(全屏图像)

            # 每场战斗先读取一次实际兵栏，后续使用槽位和识别出的数量，
            # 即使换了配兵顺序也不会继续套用旧模板名称。
            兵栏清单 = self.检查当前配兵(上下文)
            上下文.当前兵栏清单 = 兵栏清单
            # 该子任务由“搜索目标”成功后调用，此处即视为已进入战斗。
            # 不再要求结束按钮模板必须持续可见。
