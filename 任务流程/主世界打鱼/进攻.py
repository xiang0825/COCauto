            上下文._本场被拒绝下兵点 = set()
            # 1. 获取并检测目标
            全屏图像 = 上下文.op.获取屏幕图像cv(0, 0, 800, 600)
            # 英雄技能状态需要知道英雄槽位在本场战斗前后的变化；
            # 只保存一张 800×600 截图，避免额外增加 ADB/ONNX 压力。
