    def 执行漏下兵种下兵流程(self, 上下文, 有效目标列表: list):
        """检测并补下遗漏的兵种

        参数:
            上下文: 任务上下文
            有效目标列表: 筛选后的有效目标列表
        """
        if not 有效目标列表:
            return

        self.准备可下兵区域(上下文)
        # 定义所有可能的兵种格子坐标（从左到右：第1格到第5格）
        所有格子坐标 = [
            ("第一格", (37,537,68,573)),
            ("第二格", (101,522,144,577)),
            ("第三格", (169,527,206,575)),
            ("第四格", (234,527,275,575)),
            ("第五格", (318,522,358,578)),
        ]

        # 从配置中读取需要检测的格数（默认3格）
        配置的检测格数 = 上下文.数据库.获取机器人设置(上下文.机器人标志).漏下兵种检测格数

        # 截取前N格作为实际检测的格子
        兵种所在格子映射 = 所有格子坐标[:配置的检测格数]

        上下文.置脚本状态(f"开始检测前{配置的检测格数}格是否有遗漏兵种")

        检测区域 = (11, 506, 775, 594)
        有效目标数量 = len(有效目标列表)
        目标索引 = 0

        for 格子名称, 格子区域 in 兵种所在格子映射:
            if not self.战斗是否仍在进行(上下文):
                上下文.置脚本状态("检测到战斗结束，停止补下兵")
                return
            x1, y1, x2, y2 = 格子区域
            格子中心x = (x1 + x2) // 2
            格子中心y = (y1 + y2) // 2
            偏移x = 格子中心x - 检测区域[0]
            偏移y = 格子中心y - 检测区域[1]

            # 格子为灰色说明已下完，跳过
            格子图像 = 上下文.op.获取屏幕图像cv(x1, y1, x2, y2)
            if self.是否为灰色图片(格子图像):
                上下文.置脚本状态(f"{格子名称}已全部下完，跳过")
                continue

            上下文.置脚本状态(f"{格子名称}有剩余兵种，开始补下")
            上下文.发送企业微信通知(f"{格子名称}是彩色图像，可能有剩余兵种，开始补下,可能又有活动兵种了",包含截图=True)

            循环次数 = 0
            连续失败次数 = 0
            while True:
                if not self.战斗是否仍在进行(上下文):
                    上下文.置脚本状态(f"检测到战斗结束，停止{格子名称}补下")
                    return
                循环次数 += 1
                if 循环次数 > self.单兵种最大循环次数:
                    raise RuntimeError(f"漏下兵种流程疑似死循环，{格子名称}循环{循环次数}次")

                # 格子变灰则该格已补完，进入下一格
                格子图像 = 上下文.op.获取屏幕图像cv(x1, y1, x2, y2)
                if self.是否为灰色图片(格子图像):
                    上下文.置脚本状态(f"{格子名称}兵种已全部下完")
                    break

                # 格子中心未被白框包裹（未选中）时才点击选中，避免重复点击反选
                屏幕图像 = 上下文.op.获取屏幕图像cv(*检测区域)
                是否有白框, 白框列表, _ = self.检测白色矩形框(屏幕图像)
                已选中, _ = self.判断点是否被白框包裹((偏移x, 偏移y), 白框列表)
                if not (是否有白框 and 已选中):
                    上下文.点击(格子中心x, 格子中心y)
                if not getattr(上下文, "_部署边界已刷新", False):
                    self.刷新选中兵种后的下兵边界(上下文)

                # 对有效目标执行下兵，复用下兵坐标计算和延时逻辑
                当前目标 = 有效目标列表[目标索引]
                目标坐标 = 当前目标['中心坐标']
                是否下兵成功, _ = self.尝试下兵至可用位置(
                    上下文,
                    {"名称": 格子名称, "区域": 格子区域, "类别": "未知"},
                    目标坐标,
                    self.生成可下兵候选点(上下文, 目标坐标),
                    self.默认下兵间隔,
                )
                目标索引 = (目标索引 + 1) % 有效目标数量
                if not 是否下兵成功:
                    连续失败次数 += 1
                    if 连续失败次数 >= self.最大下兵失败次数:
                        上下文.置脚本状态(
                            f"{格子名称}连续{连续失败次数}次没有可用下兵点，停止补兵避免卡住"
                        )
                        break
                else:
                    连续失败次数 = 0
