from 任务流程.主世界打鱼.打开进攻页面 import 打开进攻页面任务
from 任务流程.主世界打鱼.等待战斗结束并回营 import 等待战斗结束并回营任务
from 任务流程.主世界打鱼.进攻 import 进攻任务
from 任务流程.基础任务框架 import 任务上下文
from 任务流程.夜世界.夜世界打鱼.夜世界基础任务类 import 夜世界基础任务
from 任务流程.主世界打鱼.搜索敌人 import 搜索目标敌人任务



class 主世界打鱼任务(夜世界基础任务):
    """注释字符"""
    def __init__(self, 上下文: 任务上下文):
        super().__init__(上下文)

    @staticmethod
    def _重置本场目标评估(上下文: 任务上下文) -> None:
        """在新一场开始前清除上一场的目标证据。"""
        上下文.本场目标战利品 = {}
        上下文.本场资源易窃取评分 = None
        上下文.本场资源评估 = {}
        上下文.本场资源评分状态 = "未确认"
        上下文.本场资源评分说明 = "本场尚未确认敌方搜索页"


    def 执行(self) -> bool:
        """执行进入夜世界的主逻辑"""
        self.上下文.置脚本状态("主世界打鱼任务")
        try:
            self._重置本场目标评估(self.上下文)
            任务列表 = [
                打开进攻页面任务(self.上下文),
                搜索目标敌人任务(self.上下文),
                进攻任务(self.上下文),
                等待战斗结束并回营任务(self.上下文),

            ]

            for 索引, 子任务 in enumerate(任务列表, start=1):
                任务名 = type(子任务).__name__
                # 入口状态机可能在启动/点击后的复核中发现画面已经是
                # 战斗结算页。此时搜索和下兵都会把结果页当成未知页面，
                # 必须直接交给回营流程完成结果记录和回营确认。
                if (
                    任务名 == "搜索目标敌人任务"
                    and getattr(self.上下文, "_入口已进入结算", False)
                ):
                    continue
                if (
                    任务名 == "搜索目标敌人任务"
                    and getattr(self.上下文, "_入口已进入战斗", False)
                ):
                    self.上下文.置脚本状态(
                        "入口复核已确认战斗页，跳过搜索敌人任务"
                    )
                    continue
                if (
                    任务名 == "进攻任务"
                    and getattr(self.上下文, "_入口已进入结算", False)
                ):
                    continue
                self.上下文.置脚本状态(f"{索引}, {任务名}",60*3)
                if not 子任务.执行():
                    self.上下文.置脚本状态(f"[失败] 子任务 [{任务名}] 执行失败，终止主世界打鱼任务链")
                    return False
            # 结算恢复只对当前任务链有效；回营成功后必须允许下一轮
            # 正常经过主世界、搜索页和进攻页。
            self.上下文._入口已进入结算 = False
            return True

        except RuntimeError as e:
            self.异常处理(e)
            return False

