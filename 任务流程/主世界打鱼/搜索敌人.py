    def 是否有足够资源建筑靠近边缘(self,上下文,
            距离阈值: float,
            最少靠近数量: int = None,
            最少靠近比例: float = None,
            允许检测的类别: list = None,
            截图区域: tuple = (0, 0, 800, 600),
            检测结果列表: list = None,
    ) -> bool:
        """
        判断是否存在足够数量（或比例）的金矿/圣水采集器靠近地图边缘。

        参数:
            距离阈值: float - 距离边缘小于此值时，视为“靠近边缘”
            最少靠近数量: int - 至少多少个靠近边缘（与比例二选一）
            最少靠近比例: float - 至少多少比例的目标靠近边缘（与数量二选一）
            允许检测的类别: list[str] - 默认为 ['金矿', '圣水采集器']
            截图区域: tuple - 截图区域 (x, y, 宽, 高)

        返回:
            bool - 是否达到靠近边缘的数量或比例条件
        """
        #YOLO检测器 = 线程安全YOLO检测器()
        if 允许检测的类别 is None:
            允许检测的类别 = ['金矿', '圣水采集器']

        if 最少靠近数量 is None and 最少靠近比例 is None:
            最少靠近数量 = 1  # 默认最少要一个目标靠近边缘

        if 检测结果列表 is None:
            左上x, 左上y, 宽, 高 = 截图区域
            全屏图像 = 上下文.op.获取屏幕图像cv(左上x, 左上y, 宽, 高)
            检测结果列表 = self.检测器.检测(全屏图像)

        总资源目标数量 = 0
        靠近边缘数量 = 0

        for 目标 in 检测结果列表:
            类别 = 目标['类别名称']
            if 类别 not in 允许检测的类别:
                continue

            总资源目标数量 += 1
            左, 上, 右, 下 = 目标['裁剪坐标']
            中心坐标 = 坐标((左 + 右) // 2, (上 + 下) // 2)

            if 判断目标点到可进攻边缘距离是否小于设定值(中心坐标, 距离阈值):
                靠近边缘数量 += 1


        上下文.置脚本状态("识别到的资源建筑数量为"+str(总资源目标数量)+"目前有"+str(靠近边缘数量)+"资源建筑靠近边缘")

        if 总资源目标数量 == 0:
            上下文.置脚本状态(
                "未识别到资源建筑靠近边缘")
            return False  # 没有可判断的目标

        if 最少靠近比例 is not None:
            实际比例 = 靠近边缘数量 / 总资源目标数量
            return 实际比例 >= 最少靠近比例

        # 否则按数量判断
        return 靠近边缘数量 >= 最少靠近数量

    def 等待下一个按钮出现(self, 上下文) -> bool:
        """识别繁体/简体搜索按钮，避免只依赖简体文字模板。"""

        按钮区域 = (0, 0, 800, 600)
        # 进入页由“打开进攻页面任务”负责确认；这里保留有限等待，
        # 避免页面点击失败后再次卡住 200 秒。
        超时时间 = 30  # 秒
        开始时间 = time.time()

        while time.time() - 开始时间 < 超时时间:
            # 获取按钮区域图像
            屏幕图像 = 上下文.op.获取屏幕图像cv(*按钮区域)

            是否匹配, _, 依据, 分数 = 搜索页面识别器.查找下一个按钮(
                屏幕图像, self.模板识别
            )
            if 是否匹配:
                上下文.置脚本状态(
                    f"已确认敌方搜索页面：{依据}，评分{分数:.2f}"
                )
                return True

            # 间隔检测
            上下文.脚本延时(500)

        # 超时处理
        上下文.置脚本状态("等待下一个按钮超时：未进入敌方搜索页面", 超时的时间=10)
        return False

    @打印运行耗时
    def 识别当前资源(self, 上下文, 屏幕图像=None) -> dict:
        """修复后的资源识别方法"""
        try:
            if 屏幕图像 is None:
                资源图像 = 上下文.op.获取屏幕图像cv(14, 67, 151, 146)
            else:
                资源图像 = 屏幕图像[67:146, 14:151]

            # 单次OCR识别（结果按顺序对应各区域）
            OCR返回 = self.ocr引擎(资源图像)
            if isinstance(OCR返回, tuple):
                result = OCR返回[0]
            else:
                result = OCR返回
            # RapidOCR 在空帧/模型恢复期间可能返回 (None, None)，
            # 不能直接对 None 调 len；空结果应当作为本轮未识别，
            # 交给调用方继续搜索或安全跳过。
            result = result or []
            # 不要假设 OCR 返回顺序或固定返回格式。RapidOCR 的完整结果通常是
            # ``[四边形, 文本, 置信度]``，轻量配置也可能返回
            # ``[文本, 置信度]``；而检测顺序在不同版本/分辨率下不一定稳定。
            # 统一抽取文字并按屏幕 Y 坐标排序，避免把空置信度、错行文字写成
            # 战利品，或因结果顺序变化而交换金币/圣水/黑油。
            资源文本 = self._提取资源行文本(result)
            金币文本 = 资源文本[0] if len(资源文本) > 0 else "0"
            圣水文本 = 资源文本[1] if len(资源文本) > 1 else "0"
            黑油文本 = 资源文本[2] if len(资源文本) > 2 else "0"

            设置 = 上下文.数据库.获取机器人设置(上下文.机器人标志)
            战利品评分 = self.计算战利品评分(
                self.文本转数值(金币文本),
                self.文本转数值(圣水文本),
                self.文本转数值(黑油文本),
                设置.战利品优先级,
            )
            return {
                "金币": self.文本转数值(金币文本),
                "圣水": self.文本转数值(圣水文本),
                "黑油": self.文本转数值(黑油文本),
                "总资源": self.文本转数值(金币文本) + self.文本转数值(圣水文本),
                "战利品评分": 战利品评分,
                "资源易窃取评分": 0.0,
                "资源易窃取评分依据": {},
            }

        except Exception as e:
            判断内存异常 = getattr(self.上下文, "是否内存异常", None)
            触发内存保护 = getattr(self.上下文, "触发内存保护", None)
            if callable(判断内存异常) and 判断内存异常(e) and callable(触发内存保护):
                触发内存保护("敌方资源OCR", e)
            上下文.置脚本状态(f"资源识别失败: {str(e)}")
            return {
                "金币": 0,
                "圣水": 0,
                "黑油": 0,
                "总资源": 0,
                "战利品评分": 0,
                "资源易窃取评分": 0.0,
                "资源易窃取评分依据": {},
            }

    @staticmethod
    def _提取资源行文本(OCR结果) -> list[str]:
        """从敌方资源栏 OCR 结果提取按纵向排列的三行文字。

        兼容完整检测结果、轻量 ``[文字, 置信度]`` 结果和空/异常条目。
        资源栏已经是窄裁剪区域，只保留包含数字的条目；没有坐标的轻量
        结果沿用引擎返回顺序。
        """
        if not isinstance(OCR结果, (list, tuple)):
            return []

        行结果 = []
        for 索引, 条目 in enumerate(OCR结果):
            if not isinstance(条目, (list, tuple)):
                continue

            文本 = None
            中心Y = None
            if len(条目) >= 3 and isinstance(条目[1], str):
                文本 = 条目[1]
                框 = 条目[0]
                try:
                    点集 = [点 for 点 in 框 if len(点) >= 2]
                    if 点集:
                        中心Y = sum(float(点[1]) for 点 in 点集) / len(点集)
                except (TypeError, ValueError):
                    中心Y = None
            elif len(条目) >= 2 and isinstance(条目[0], str):
                文本 = 条目[0]

            if 文本 is None:
                continue
            清理文本 = str(文本).replace("O", "0").replace("o", "0")
            数字 = "".join(字符 for 字符 in 清理文本 if 字符.isdigit())
            if 数字:
                # 没有坐标时使用稳定的原始顺序；有坐标时优先按画面行排序。
                行结果.append((中心Y if 中心Y is not None else float("inf"), 索引, 数字))

        if any(中心Y != float("inf") for 中心Y, _, _ in 行结果):
            行结果.sort(key=lambda 项: (项[0], 项[1]))
        else:
            行结果.sort(key=lambda 项: 项[1])
        return [数字 for _, _, 数字 in 行结果[:3]]

    @staticmethod
    def 计算战利品评分(金币: int, 圣水: int, 黑油: int, 优先级: str) -> int:
        """把三种资源换算为可比较的搜索评分，黑油按稀缺资源折算。"""
        if 优先级 == "金币":
            return round(金币 + 圣水 * 0.25 + 黑油 * 20)
        if 优先级 == "圣水":
            return round(圣水 + 金币 * 0.25 + 黑油 * 20)
        if 优先级 == "黑水":
            return round(黑油 * 100 + (金币 + 圣水) * 0.15)
        return round(金币 + 圣水 + 黑油 * 20)

    def 文本转数值(self, 文本: str) -> int:
        """增强型文本转换"""
        try:
            # 处理常见OCR错误字符
            清理文本 = 文本.replace('O', '0').replace('o', '0').replace(' ', '')
            return int(''.join(filter(str.isdigit, 清理文本)))
        except Exception:
            return 0  # 确保始终返回数值

    def 调整搜索目标(self, 上下文, 原始目标: int, 当前次数: int) -> int:
        """每10次降低搜索标准"""
        新目标 = max(原始目标 - int(原始目标 * 0.1), 100000)  # 最低不低于10万
        上下文.置脚本状态(
            f"搜索达{当前次数}次，降低目标至{新目标}",
            超时的时间=10
        )
        return 新目标

    def 点击下一个按钮(self, 上下文) -> bool:
        """再次确认搜索页后，动态点击“下一個/下一个”按钮。"""
        # 资源 OCR 完成时画面可能仍在入场过渡。旧版只试一次，低分
        # 绿色地图区域被拒后立即停掉机器人；有限重试等待真按钮稳定。
        for 尝试 in range(8):
            if 尝试:
                上下文.脚本延时(600)
            try:
                屏幕图像 = 上下文.op.获取屏幕图像cv(
                    0, 0, 800, 600, 强制刷新=True
                )
            except TypeError:
                屏幕图像 = 上下文.op.获取屏幕图像cv(0, 0, 800, 600)
            命中, 中心, 依据, 分数 = 搜索页面识别器.查找下一个按钮(
                屏幕图像, self.模板识别
            )
            if (
                not 命中
                or not 搜索页面识别器.按钮证据可信(依据, 分数)
                or int(中心[0]) < 搜索页面识别器.点击安全最左x
            ):
                上下文.置脚本状态(
                    f"搜索页按钮尚未可靠出现（第{尝试 + 1}/8次）："
                    f"{依据}，评分{分数:.2f}，位置{中心[0]},{中心[1]}"
                )
                continue
            上下文.置脚本状态(
                f"确认搜索页按钮后点击下一场：{中心[0]},{中心[1]}"
                f"（{依据}，评分{分数:.2f}）"
            )
            # 两张新帧再确认同一按钮并排除弹窗；不盲点绿色地图。
            专用点击 = getattr(上下文, "点击已确认搜索按钮", None)
            if callable(专用点击):
                if 专用点击(中心[0], 中心[1]):
                    return True
            elif 上下文.点击(
                中心[0], 中心[1], 延时=500, 是否精确点击=True
            ):
                return True
        上下文.置脚本状态("搜索按钮连续八次未通过复核，停止盲点下一场")
        return False
