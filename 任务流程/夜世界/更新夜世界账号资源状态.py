from 任务流程.基础任务框架 import 任务上下文, 基础任务
from 工具包.工具函数 import 显示图像, 单行资源识别
from 模块.检测.OCR识别器 import 安全OCR引擎
from 模块.检测.YOLO检测器 import 线程安全YOLO检测器
from 模块.检测.模板匹配器 import 模板匹配引擎

资源字段 = ("金币", "圣水")


class 更新夜世界资源状态任务(基础任务):
    """识别夜世界资源，并更新数据库"""

    def 执行(self) -> bool:
        上下文 = self.上下文
        资源字典 = self.识别当前资源(上下文)
        上下文.置脚本状态("夜世界资源识别结果："+str(资源字典))
        if not 资源字典.get("识别成功", False):
            # OCR 失败时不能把全 0 写入数据库；0 会被资源打满判断
            # 误认为末尾有足够多的零，进而错误结束夜世界任务。
            上下文.置脚本状态(
                "本次夜世界资源识别未完成，保留上一份已确认资源状态"
            )
            return False
        上下文.数据库.更新状态(上下文.机器人标志, "夜世界资源", 资源字典)
        return True

    @staticmethod
    def _读取已确认资源(上下文) -> dict | None:
        """读取上一份识别成功的夜世界资源；缺失或异常时返回 None。"""
        数据库 = getattr(上下文, "数据库", None)
        获取状态 = getattr(数据库, "获取最新完整状态", None)
        if not callable(获取状态):
            return None
        try:
            状态 = 获取状态(上下文.机器人标志)
            数据 = getattr(状态, "状态数据", None) or {}
            资源 = 数据.get("夜世界资源") if isinstance(数据, dict) else None
            if not isinstance(资源, dict) or not 资源.get("识别成功", False):
                return None
            结果 = {字段: int(资源[字段] or 0) for 字段 in 资源字段}
        except Exception:
            return None
        return 结果 if all(值 > 0 for 值 in 结果.values()) else None

    def _截取资源行(self, 上下文) -> dict:
        全屏图像 = 上下文.op.获取屏幕图像cv(593,3,793,105)
        row_h = 全屏图像.shape[0] // 2
        return {
            "金币": 全屏图像[0:row_h, :],
            "圣水": 全屏图像[row_h:row_h*2, :],
        }

    @staticmethod
    def _保活心跳(上下文, 说明: str) -> None:
        保活 = getattr(上下文, "保活心跳", None)
        if callable(保活):
            保活(说明)

    def _独立复读(self, 上下文, 字段) -> tuple[int, int] | None:
        """重新截图后用轻量/完整两条 OCR 路径各读一次；异常返回 None。"""
        try:
            self._保活心跳(上下文, f"夜世界{字段}独立复读")
            新行 = self._截取资源行(上下文)[字段]
            轻量复读 = 单行资源识别(self.ocr引擎, 新行, 裁到数字范围=True)
            self._保活心跳(上下文, f"夜世界{字段}完整OCR复读")
            完整复读 = 单行资源识别(
                self.ocr引擎, 新行, 允许完整识别=True, 裁到数字范围=True
            )
        except Exception as 异常:
            上下文.置脚本状态(f"夜世界{字段}独立复读失败，判为不可信：{异常}")
            return None
        return 轻量复读, 完整复读

    def _无基线复核(self, 上下文, 字段, 首读) -> int:
        """没有已确认夜世界资源时，首读也必须经独立双路复读一致才确认。

        冷启动/首次进入夜世界没有旧值可比位数，漏中间位的首读
        （3 119 754 → 319754）仍是合法正数；直接写库会成为错误基线。
        新截图的轻量与完整 OCR 一致即采用该读数，否则返回 0 保持未确认。
        """
        复读 = self._独立复读(上下文, 字段)
        if 复读 is None:
            return 0
        轻量复读, 完整复读 = 复读
        if 轻量复读 > 0 and 轻量复读 == 完整复读:
            if 轻量复读 != 首读:
                上下文.置脚本状态(
                    f"夜世界{字段}无历史基线，首读{首读}与独立复读不一致，采用复读{轻量复读}"
                )
            return 轻量复读
        上下文.置脚本状态(
            f"夜世界{字段}无历史基线且独立复读不一致"
            f"（{首读}/{轻量复读}/{完整复读}），保持未确认"
        )
        return 0

    def _位数一致性复核(self, 上下文, 字段, 首读, 旧值) -> int:
        """首读位数与上一次确认值不同时，重新截图并双路径复读。

        rc161 现场夜世界资源 OCR 偶发漏掉中间一位（3 119 754 → 319754、
        37x x459 → 373459）：千分位空格两侧的窄字“1”被识别模型吞掉，
        得到一个合法但少一位的正数，旧逻辑直接写库。资源在两次读数之间
        极少跨越一个数量级，位数变化先视为可疑：
        - 新截图的轻量与完整 OCR 一致且与旧值位数相同 → 采用该读数；
        - 三次读数完全一致（真实跨位，如大额消耗或首次破百万）→ 采用；
        - 其余情况（含仅单路复读回到旧位数）返回 0，判为不可信，
          保留上一份已确认快照。
        """
        复读 = self._独立复读(上下文, 字段)
        if 复读 is None:
            return 0
        轻量复读, 完整复读 = 复读
        旧位数 = len(str(旧值))
        if 轻量复读 > 0 and 轻量复读 == 完整复读:
            if len(str(轻量复读)) == 旧位数:
                上下文.置脚本状态(
                    f"夜世界{字段}首读{首读}与上次{旧值}位数不一致，双路复读一致采用{轻量复读}"
                )
                return 轻量复读
            if 轻量复读 == 首读:
                上下文.置脚本状态(
                    f"夜世界{字段}三次读数一致为{首读}，确认位数由{旧位数}变为{len(str(首读))}"
                )
                return 首读
        上下文.置脚本状态(
            f"夜世界{字段}读数位数与上次{旧值}不一致且复读不一致"
            f"（{首读}/{轻量复读}/{完整复读}），判为不可信"
        )
        return 0

    def 识别当前资源(self, 上下文) -> dict:
        try:
            行图 = self._截取资源行(上下文)

            # 夜世界资源条半透明，数字左侧的船帆/地图会被 OCR 读成多余
            # 首位或吞掉首位；裁到白色数字串范围再识别。
            读数 = {
                字段: 单行资源识别(self.ocr引擎, 行图[字段], 裁到数字范围=True)
                for 字段 in 资源字段
            }
            旧资源 = self._读取已确认资源(上下文)
            for 字段 in 资源字段:
                self._保活心跳(上下文, f"夜世界{字段}读数复核")
                值 = 读数[字段]
                if 值 <= 0:
                    continue
                if not 旧资源:
                    读数[字段] = self._无基线复核(上下文, 字段, 值)
                elif len(str(值)) != len(str(旧资源[字段])):
                    读数[字段] = self._位数一致性复核(
                        上下文, 字段, 值, 旧资源[字段]
                    )
            金币文本 = 读数["金币"]
            圣水文本 = 读数["圣水"]

            return {
                "金币": 金币文本,
                "圣水": 圣水文本,
                "总资源": 金币文本 + 圣水文本,
                # 两行必须都读到正数才允许覆盖上次可信快照；单行
                # OCR 漏读或读成 0 时保留旧值，避免误触发满仓判断。
                "识别成功": bool(金币文本 > 0 and 圣水文本 > 0),
            }
        except Exception as e:
            上下文.置脚本状态(f"资源识别失败: {str(e)}")
            return {
                "金币": 0,
                "圣水": 0,
                "总资源": 0,
                "识别成功": False,
            }
