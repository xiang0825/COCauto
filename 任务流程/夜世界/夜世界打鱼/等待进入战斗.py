import time
from 任务流程.基础任务框架 import 任务上下文
from 任务流程.夜世界.夜世界打鱼.夜世界基础任务类 import 夜世界基础任务


class 等待进入战斗(夜世界基础任务):
    """注释字符"""
    # 首个兵槽点击被安全护栏拒绝时的最多尝试次数（含首次）。
    首兵槽最大尝试次数 = 4
    # 与 基础任务框架.检查宝石商店危险页面 的结算视觉跨帧保护秒数一致。
    结算视觉保护秒数 = 2.5
    def __init__(self,上下文: 任务上下文):
        super().__init__(上下文)


    def 执行(self) -> bool:
        """执行进入夜世界的主逻辑"""
        try:
            超时时间 = 200  # 秒
            开始时间 = time.time()
            首兵槽被拒次数 = 0
            self.上下文._夜世界首兵槽未选中 = False

            while time.time() - 开始时间 < 超时时间:
                页面结果, 有页面识别 = self._读取页面状态()
                页面 = str(getattr(页面结果, "页面", "") or "")

                # 夜世界从“立即寻找”进入战斗时，测试服可能短暂显示上一
                # 场的星级奖励遮罩。模板箭头会透过遮罩误命中，旧流程因此
                # 先标记“已进入战斗”再把下兵交给错误页面。只要页面识别器
                # 已经返回奖励页，必须先安全确认奖励并重新等待；奖励页不
                # 得作为战斗开始证据。
                if 页面 == "战斗星级奖励":
                    self.上下文._战斗中 = False
                    处理奖励 = getattr(
                        self.上下文, "处理战斗星级奖励弹窗", None
                    )
                    if callable(处理奖励):
                        处理奖励()
                    self.上下文.置脚本状态(
                        "进入夜世界战斗时识别到星级奖励过渡，已阻止下兵并重新确认战斗页"
                    )
                    self.上下文.脚本延时(350)
                    continue

                if 页面 in {"战斗结算", "断线弹窗", "系统维护"}:
                    self.上下文.页面恢复失败 = True
                    self.上下文.置脚本状态(
                        f"进入夜世界战斗时识别到{页面}，禁止误判为新战斗"
                    )
                    return False

                # 夜世界战场左下角不一定渲染红色“放弃”按钮，普通主页
                # 识别因此可能暂时返回“未知”。专用战斗复核会以
                # “战斗中=True”复用顶部倒计时证据；只有它确认战斗后才
                # 允许点第一个普通兵槽。旧测试/兼容上下文没有页面识别器
                # 时才允许继续使用换兵种箭头模板作为唯一证据。
                战斗页已确认 = 页面 == "战斗中"
                if not 战斗页已确认 and 有页面识别 and 页面 not in {
                    "战斗奖励选择", "战斗结算", "断线弹窗", "系统维护"
                }:
                    战斗页已确认 = self._页面已确认夜世界战斗()
                if 战斗页已确认 or (
                    not 有页面识别 and self.是否出现换兵种箭头()
                ):
                    # 当前测试服的箭头素材在自适应画布中会降到约 0.57，
                    # 但顶部倒计时和左下“放弃”按钮是稳定的战斗证据。
                    # 选中第一个普通兵槽后再交给下兵流程，避免在真实
                    # 战斗页一直等待过时模板。
                    # 145,545 位于新版兵卡底部的绿色“更换部队”箭头，
                    # 会打开部队替换弹层并暂停倒计时；卡片中心应点击
                    # 逻辑坐标约 150,520。
                    if self.上下文.点击(150, 520, 是否精确点击=True) is False:
                        # rc155 实机：一帧“星级奖励”过渡误报会登记 2.5 秒
                        # 结算跨帧保护，紧接着确认战斗后的首个兵槽点击被
                        # 护栏拒绝；旧流程把这一次拒绝当成致命失败，整条
                        # 打鱼链进入安全待命，战斗页一直挂着不下兵。这里
                        # 只等保护窗口自然过期，再用新帧重新确认战斗后重试；
                        # 不清除、不放宽任何护栏状态。
                        首兵槽被拒次数 += 1
                        if 首兵槽被拒次数 >= self.首兵槽最大尝试次数:
                            self.上下文._战斗中 = True
                            self.上下文._夜世界首兵槽未选中 = True
                            self.上下文.置脚本状态(
                                f"已确认夜世界战斗，但首个兵槽输入连续{首兵槽被拒次数}次"
                                "被安全护栏拒绝；不再点击兵槽，交给回营流程等待本场结束"
                            )
                            return False
                        等待秒 = self._结算视觉保护剩余秒()
                        self.上下文.置脚本状态(
                            f"首个兵槽输入被安全护栏暂时拒绝（第{首兵槽被拒次数}次），"
                            f"等待{等待秒:.1f}秒后用新帧复核战斗再重试"
                        )
                        self.上下文.脚本延时(int(等待秒 * 1000))
                        continue
                    self.上下文._战斗中 = True
                    self.上下文.置脚本状态(
                        "已通过战斗倒计时和放弃按钮确认夜世界战斗，选中首个普通兵槽"
                    )
                    return True
                self.上下文.脚本延时(50)

            raise RuntimeError(f"操作超时：一直卡白云或者某处,导致一直没能进入战斗！已经等待了{超时时间}")
        except Exception as e:
            self.异常处理(e)
            return False

    def _结算视觉保护剩余秒(self) -> float:
        """返回结算跨帧保护还需等待的秒数（含少量余量，限制在 0.6~3.0 秒）。"""
        try:
            最近 = float(getattr(self.上下文, "_最近结算视觉时间", 0.0) or 0.0)
        except (TypeError, ValueError):
            最近 = 0.0
        剩余 = 0.0
        if 最近 > 0:
            剩余 = self.结算视觉保护秒数 - (time.monotonic() - 最近) + 0.2
        return min(3.0, max(0.6, 剩余))

    def _页面已确认夜世界战斗(self) -> bool:
        """使用共享轻量页面识别器确认夜世界战斗页。"""
        try:
            屏幕 = self.上下文.op.获取屏幕图像cv(0, 0, 800, 600)
            获取识别器 = getattr(self.上下文, "_获取点击页面识别器", None)
            if not callable(获取识别器):
                return False
            结果 = 获取识别器().识别(屏幕, 战斗中=True)
            return getattr(结果, "页面", "") == "战斗中"
        except Exception:
            return False

    def _读取页面状态(self):
        """返回页面识别结果和“是否有真实页面识别器”标志。"""
        识别 = getattr(self.上下文, "识别点击画面", None)
        if not callable(识别):
            return None, False
        try:
            return 识别(), True
        except Exception:
            return None, True

    def 是否出现换兵种箭头(self):
        """验证是否已开始战斗"""
        是否匹配, (x, y) = self.是否出现图片(
            "更换兵种箭头[1].bmp|更换兵种箭头[2].bmp",
            (100, 480, 550, 600),
            相似度阈值=0.50,
        )
        if 是否匹配:
            if self.上下文.点击(x-18, y-28) is False:
                self.上下文.置脚本状态(
                    "夜世界换兵种箭头点击被安全输入层拒绝，禁止继续下兵"
                )
                return False
            return True
        else:
            return False
