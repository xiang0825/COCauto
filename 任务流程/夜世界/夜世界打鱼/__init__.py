from 任务流程.基础任务框架 import 任务上下文, 基础任务
from 任务流程.夜世界.夜世界打鱼.下兵 import 下兵, 停止并等待英雄技能线程
from 任务流程.夜世界.夜世界打鱼.打开进攻页面任务 import 打开进攻页面
from 任务流程.夜世界.夜世界打鱼.等待回营或第二场战斗 import 等待回营或第二次战斗
from 任务流程.夜世界.夜世界打鱼.等待进入战斗 import 等待进入战斗
from 任务流程.夜世界.夜世界打鱼.现场截图 import 保存夜世界现场截图
from 模块.检测.模板匹配器 import 模板匹配引擎


class 夜世界打鱼任务(基础任务):
    """注释字符"""

    def 执行(self) -> bool:
        """执行进入夜世界的主逻辑"""
        上下文 = self.上下文
        上下文.置脚本状态("夜世界打鱼任务")
        try:
            任务列表 = [
                打开进攻页面(上下文),
                等待进入战斗(上下文),
                下兵(上下文),
                等待回营或第二次战斗(上下文),
                # 更多任务...
            ]

            # 第 2 步“等待进入战斗”：兵槽一直未选中时需要走回营收尾。
            等待进入战斗序号 = 2
            for 索引, 子任务 in enumerate(任务列表, start=1):
                任务名 = type(子任务).__name__
                上下文.置脚本状态(f"{索引}, {任务名}",60*3)
                if not 子任务.执行():
                    保存夜世界现场截图(上下文, 任务名)
                    if (
                        索引 == 等待进入战斗序号
                        and getattr(上下文, "_夜世界首兵槽未选中", False)
                        and not getattr(上下文, "页面恢复失败", False)
                    ):
                        return self._兵槽未选中时结束本场()
                    上下文.置脚本状态(f"[失败] 子任务 [{任务名}] 执行失败，终止夜世界打鱼任务链")
                    return False
            return True

        except RuntimeError as e:
            保存夜世界现场截图(上下文, "任务异常")
            self.异常处理(e)
            return False
        finally:
            上下文._夜世界首兵槽未选中 = False
            # 无论回营成功、失败还是收到停止事件，都不能把战斗护栏
            # 状态带到下一项世界/资源任务。下兵任务可能已经启动后台
            # 英雄技能线程；如果它在中途失败，不能让该线程越过任务边界
            # 继续向主世界、结算页或模拟器其它页面发送点击。
            技能线程已退出 = 停止并等待英雄技能线程(
                self.上下文, 超时秒=5.0
            )
            if 技能线程已退出:
                self.上下文._战斗中 = False
            else:
                self.上下文.置脚本状态(
                    "夜世界英雄技能线程未确认退出，保留战斗输入护栏"
                )

    def _兵槽未选中时结束本场(self) -> bool:
        """已确认在战斗页但兵槽点击一直被护栏拒绝：走现有回营流程结束本场。

        不再把战斗页挂着进入安全待命。复用 ``等待回营或第二次战斗``：
        以“只等待回营”模式运行：结算前绝不点换兵种箭头/兵槽、不下兵，
        只在新截图复核为结算页并定位到回营按钮时才安全点击回营。不点放弃/投降，
        不发送 ESC，也不触碰任何宝石入口。
        """
        上下文 = self.上下文
        上下文._战斗中 = True
        上下文.置脚本状态(
            "夜世界本场未能选中兵槽，改为等待本场结束并安全回营，再继续下一场"
        )
        if 等待回营或第二次战斗(上下文, 只等待回营=True).执行():
            上下文.置脚本状态("夜世界未下兵的本场已安全回营，继续下一场")
            return True
        保存夜世界现场截图(上下文, "未下兵回营")
        上下文.页面恢复失败 = True
        上下文.置脚本状态("夜世界未下兵的本场未能确认回营，停止后续进攻并保留当前画面")
        return False
