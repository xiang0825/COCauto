from 任务流程.基础任务框架 import 基础任务, 任务上下文
from 核心.核心异常们 import 图像获取失败


class 检查图像任务(基础任务):
    """检查模拟器图像是否可以正常获取"""

    def 执行(self) -> bool:
        try:
            上下文 = self.上下文
            图像 = 上下文.op.获取屏幕图像cv(0, 0, 2000, 2000)
            高度, 宽度 = 图像.shape[:2]
            if (宽度, 高度) != (800, 600):
                raise 图像获取失败(
                    f"截图分辨率为 {宽度}×{高度}；任务流程要求 800×600。"
                    "请在“模拟器连接”页将已确认的模拟器分辨率设为 800×600后重试。"
                )

            上下文.置脚本状态("模拟器图像获取正常")
            return True

        except Exception as e:
            self.异常处理(e, 是否重启游戏=False)
            return False

