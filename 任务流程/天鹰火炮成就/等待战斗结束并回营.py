"""
等待战斗结束并回营任务 - 放弃战斗并返回营地
"""
import time

from 任务流程.基础任务框架 import 基础任务, 任务上下文
from 任务流程.主世界打鱼.等待战斗结束并回营 import (
    等待战斗结束并回营任务 as 主世界回营任务,
)


class 等待战斗结束并回营任务(基础任务):
    """放弃战斗并返回营地"""

    def __init__(self, 上下文: '任务上下文'):
        super().__init__(上下文)
        # 模板识别器已在基类初始化

    def 执行(self) -> bool:
        """主执行流程"""
        上下文 = self.上下文
        上下文.置脚本状态("开始执行放弃战斗回营地操作", 3*60)

        # 主世界回营状态机已经覆盖国际服/测试服的低模板分数、红色
        # 放弃按钮几何定位、投降确认框几何定位和结果页视觉确认。天鹰
        # 任务不能继续使用旧的 0.90 固定模板，否则实机会在明确的
        # 战斗页等待 30 秒后误报失败，既不能回营也无法交回任务计划。
        # 这里保留天鹰任务的“立即放弃”语义，但复用统一的安全点击和
        # 回营确认实现，所有输入仍经过同一个上下文护栏。
        通用回营 = 主世界回营任务(上下文)

        if not 通用回营.点击放弃战斗按钮(上下文):
            上下文.置脚本状态("放弃战斗按钮未能安全点击，停止回营流程")
            return False
        if not 通用回营.点击确定(上下文):
            # 测试服和部分网络切换会在点击放弃后直接回到主世界，
            # 不渲染投降确认或结算页。此时页面已经安全恢复，不能
            # 把已成功回营误报成卡死；同时明确记录本场没有结算证据。
            if 通用回营.等待主界面就绪(上下文):
                上下文.置脚本状态(
                    "放弃战斗后测试服直接回到主世界，未出现投降确认/结算页；"
                    "天鹰任务安全结束，本场结果未统计"
                )
                return True
            上下文.置脚本状态("放弃战斗确认按钮未能安全点击，停止回营流程")
            return False
        if not 通用回营.等待回营地按钮出现(上下文):
            上下文.置脚本状态("回营按钮未能安全点击或未完成转场")
            return False
        return True

    def 点击放弃战斗按钮(self) -> bool:
        """点击放弃战斗按钮"""
        上下文 = self.上下文
        按钮区域 = (0, 0, 800, 600)
        模板路径 = "放弃战斗1.bmp|放弃战斗2.bmp|放弃战斗3.bmp"
        超时时间 = 30  # 等待30秒
        开始时间 = time.time()

        while time.time() - 开始时间 < 超时时间:
            # 获取按钮区域图像
            屏幕图像 = 上下文.op.获取屏幕图像cv(*按钮区域)
            # 执行模板匹配
            是否匹配, (x, y), _ = self.模板识别.执行匹配(屏幕图像, 模板路径, 相似度阈值=0.9)
            if 是否匹配:
                if 上下文.点击(x, y) is False:
                    上下文.页面恢复失败 = True
                    return False
                return True

            # 间隔检测
            上下文.脚本延时(1000)

        return False

    def 点击确定(self) -> bool:
        """点击确定按钮"""
        上下文 = self.上下文
        按钮区域 = (0, 0, 800, 600)
        模板路径 = "点击确定1.bmp|点击确定2.bmp|点击确定3.bmp"
        超时时间 = 30  # 等待30秒
        开始时间 = time.time()

        while time.time() - 开始时间 < 超时时间:
            # 获取按钮区域图像
            屏幕图像 = 上下文.op.获取屏幕图像cv(*按钮区域)
            # 执行模板匹配
            是否匹配, (x, y), _ = self.模板识别.执行匹配(屏幕图像, 模板路径, 相似度阈值=0.9)
            if 是否匹配:
                if 上下文.点击(x, y) is False:
                    上下文.页面恢复失败 = True
                    return False
                return True

            # 间隔检测
            上下文.脚本延时(1000)

        return False

    def 等待回营地按钮出现(self) -> bool:
        """使用模板匹配检测回营按钮"""
        上下文 = self.上下文

        按钮区域 = (0, 0, 800, 600)
        模板路径 = "回营1.bmp|回营.bmp|回营2.bmp|回营3.bmp|领取奖励.bmp|回营_领取奖励.bmp"
        超时时间 = 3*60  # 等待3分钟就超时
        开始时间 = time.time()

        是否已点击回营 = False
        while time.time() - 开始时间 < 超时时间:
            # 获取按钮区域图像
            屏幕图像 = 上下文.op.获取屏幕图像cv(*按钮区域)
            # 执行模板匹配
            是否匹配, (x, y), _ = self.模板识别.执行匹配(屏幕图像, 模板路径, 相似度阈值=0.9)
            if 是否匹配:
                是否已点击回营 = True
                if 上下文.点击(x, y) is False:
                    上下文.页面恢复失败 = True
                    return False

            if 是否已点击回营 and not 是否匹配:
                return True

            # 间隔检测
            上下文.脚本延时(1000)

        return False
