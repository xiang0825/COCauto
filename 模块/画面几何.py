"""设备画面几何：让识别与点击不依赖某一个固定分辨率。

背景
----
任务流程统一在 800×600 的逻辑画布上工作；ADB 截图层把任意尺寸的设备
画面各向异性地缩放到这个画布（x÷(W/800)、y÷(H/600)），点击层用同一套
映射反算回设备坐标，因此坐标在任何尺寸下都自洽。

自 2026-09 起，项目的坐标、页面阈值和回放样本主要是在 MuMu 1280×720
（16:9）拉伸到 800×600 的画布上校准的，所以：

* 任意尺寸的 16:9（1280×720、1600×900、1920×1080、2560×1440）与
  1280×720 在逻辑画布上完全等价，属于已验证配置；
* 早期从 4:3 客户端截取的少量小模板（换兵箭头、飞艇等）在 16:9 画布里
  尺寸不一致：实测 1280×720 上换兵箭头需要按 (sx=0.9, sy=1.2) 缩放模板
  才能达到 0.92~0.96 的分数，原尺度只有 0.66~0.78；
* 其它长宽比（4:3、16:10、20:9 …）中，CoC 的 HUD 按画面高度等比缩放并
  贴边布局，单纯拉伸会让贴边按钮偏离 16:9 校准坐标。

本模块只做纯计算：记录当前设备尺寸、给出模板多尺度候选，以及把
“16:9 校准坐标”按 HUD 锚点换算到其它长宽比。它从不发送输入。
800×600 旧参考尺寸与 16:9 的换算都是恒等变换，原有行为保持不变。
"""
from __future__ import annotations

import threading
from typing import Iterable

参考宽度 = 800
参考高度 = 600
# 坐标、模板校准所用的设备长宽比（MuMu 1280×720）。
校准长宽比 = 16.0 / 9.0
# 16:9 长宽比判定容差（相对误差）。
长宽比容差 = 0.03

# 早期 4:3 来源模板相对当前 1280×720 设备的 UI 倍率实测约为 1.44，
# 即“模板来源 UI 单位 ≈ 设备高度 / 500”。只用于生成少量候选尺度，
# 最终仍由各调用方的原阈值把关。
_模板来源高度单位 = 500.0
_倍率扰动 = (0.92, 1.0, 1.08)

_线程状态 = threading.local()
_全局锁 = threading.Lock()
_全局最近尺寸: tuple[int, int] | None = None

锚点名称 = ("左上", "上", "右上", "左", "中", "右", "左下", "下", "右下")


def _规范尺寸(宽度, 高度) -> tuple[int, int] | None:
    try:
        宽 = int(宽度)
        高 = int(高度)
    except (TypeError, ValueError):
        return None
    if 宽 <= 0 or 高 <= 0:
        return None
    return 宽, 高


def 记录设备尺寸(宽度, 高度) -> None:
    """由截图层在拿到真实画面后调用；线程内优先，进程内兜底。"""
    尺寸 = _规范尺寸(宽度, 高度)
    if 尺寸 is None:
        return
    _线程状态.尺寸 = 尺寸
    global _全局最近尺寸
    with _全局锁:
        _全局最近尺寸 = 尺寸


def 清除设备尺寸() -> None:
    """测试和设备切换时清空记录。"""
    _线程状态.尺寸 = None
    global _全局最近尺寸
    with _全局锁:
        _全局最近尺寸 = None


def 当前设备尺寸() -> tuple[int, int] | None:
    尺寸 = getattr(_线程状态, "尺寸", None)
    if 尺寸 is not None:
        return 尺寸
    with _全局锁:
        return _全局最近尺寸


def _解析尺寸(尺寸=None) -> tuple[int, int] | None:
    if 尺寸 is None:
        return 当前设备尺寸()
    try:
        return _规范尺寸(尺寸[0], 尺寸[1])
    except (TypeError, IndexError):
        return None


def 是16比9(宽度, 高度) -> bool:
    尺寸 = _规范尺寸(宽度, 高度)
    if 尺寸 is None:
        return False
    比例 = 尺寸[0] / 尺寸[1]
    return abs(比例 - 校准长宽比) / 校准长宽比 <= 长宽比容差


def 是旧参考尺寸(宽度, 高度) -> bool:
    return _规范尺寸(宽度, 高度) == (参考宽度, 参考高度)


def 坐标恒等(尺寸=None) -> bool:
    """当前设备是否与校准画布等价（无需锚点换算）。

    未知尺寸、任意 16:9、以及历史 800×600 参考尺寸都视为恒等，保证旧
    回放与旧设备行为不变。
    """
    解析 = _解析尺寸(尺寸)
    if 解析 is None:
        return True
    return 是16比9(*解析) or 是旧参考尺寸(*解析)


def 分辨率提示(宽度, 高度) -> str | None:
    """返回分辨率提示文案；已验证配置返回 None。"""
    尺寸 = _规范尺寸(宽度, 高度)
    if 尺寸 is None:
        return None
    宽, 高 = 尺寸
    if 是16比9(宽, 高) or 是旧参考尺寸(宽, 高):
        return None
    return (
        f"[提示] 检测到设备实际分辨率为 {宽}×{高}（长宽比 {宽 / 高:.2f}:1）；"
        "已验证配置为任意尺寸的 16:9（如 1280×720、1920×1080）。"
        "当前比例启用 HUD 锚点换算与模板多尺度回退，属实验性支持，"
        "建议优先使用 16:9 分辨率"
    )


def 模板尺度候选(尺寸=None) -> list[tuple[float, float]]:
    """返回早期 4:3 模板在当前设备画布上的 (sx, sy) 候选尺度。

    800×600 旧参考尺寸或未知尺寸返回空列表——调用方只做原尺度匹配，
    保证原有行为完全不变。其它尺寸按“UI 随设备高度等比缩放”推导：
    sx = k·800/W，sy = k·600/H，k = H/500 附近取少量扰动。
    """
    解析 = _解析尺寸(尺寸)
    if 解析 is None or 是旧参考尺寸(*解析):
        return []
    宽, 高 = 解析
    基准倍率 = 高 / _模板来源高度单位
    候选: list[tuple[float, float]] = []
    for 扰动 in _倍率扰动:
        k = 基准倍率 * 扰动
        sx = round(k * 参考宽度 / 宽, 3)
        sy = round(k * 参考高度 / 高, 3)
        if abs(sx - 1.0) < 0.02 and abs(sy - 1.0) < 0.02:
            continue
        if (sx, sy) not in 候选:
            候选.append((sx, sy))
    return 候选


def _设备与逻辑比例(尺寸) -> tuple[float, float, float, float]:
    宽, 高 = 尺寸
    # 校准设备：与目标设备同高的 16:9 画面。
    校准宽 = 高 * 校准长宽比
    return float(宽), float(高), float(校准宽), float(高)


def 锚点坐标(x, y, 锚: str = "中", 尺寸=None) -> tuple[int, int]:
    """把 16:9 校准画布上的逻辑坐标换算到当前设备的逻辑画布。

    HUD 元素按设备高度等比缩放并贴边：左侧元素保持与左边缘的距离，
    右侧元素保持与右边缘的距离，水平居中元素保持与中线的距离（均以
    设备高度为单位）。纵向逻辑坐标在同高设备之间不变。对 16:9 / 800×600
    / 未知尺寸返回原坐标。
    """
    if 锚 not in 锚点名称:
        raise ValueError(f"未知锚点：{锚}")
    解析 = _解析尺寸(尺寸)
    x0, y0 = float(x), float(y)
    if 坐标恒等(解析):
        return int(round(x0)), int(round(y0))
    宽, 高, 校准宽, _ = _设备与逻辑比例(解析)
    # 逻辑 x → 校准设备像素。
    校准x = x0 * 校准宽 / 参考宽度
    if 锚.startswith("左"):
        设备x = 校准x
    elif 锚.startswith("右"):
        设备x = 宽 - (校准宽 - 校准x)
    else:
        设备x = 宽 / 2 + (校准x - 校准宽 / 2)
    逻辑x = 设备x * 参考宽度 / 宽
    逻辑x = max(0.0, min(参考宽度 - 1.0, 逻辑x))
    return int(round(逻辑x)), int(round(y0))


def 锚点区域(区域: Iterable, 锚: str = "中", 尺寸=None) -> tuple[int, int, int, int]:
    """按同一锚点换算矩形区域 (左, 上, 右, 下)，并保持非空。"""
    左, 上, 右, 下 = [int(v) for v in 区域]
    新左, 新上 = 锚点坐标(左, 上, 锚, 尺寸)
    新右, 新下 = 锚点坐标(右, 下, 锚, 尺寸)
    if 右 >= 参考宽度:
        新右 = 参考宽度
    新右 = max(新左 + 1, min(参考宽度, 新右))
    新下 = max(新上 + 1, min(参考高度, 新下))
    return 新左, 新上, 新右, 新下


def 点在区域内(x, y, 区域, 边距: int = 0) -> bool:
    左, 上, 右, 下 = 区域
    return (左 - 边距) <= x <= (右 + 边距) and (上 - 边距) <= y <= (下 + 边距)


# 夜世界/主世界主页的固定 HUD（16:9 校准逻辑坐标，带锚点）。地图物体
# 识别（飞艇、圣水车）命中这些区域时一律拒绝点击。
主页HUD区域 = (
    ((0, 0, 145, 118), "左上"),      # 等级徽章/头像/名称
    ((0, 118, 100, 345), "左"),      # 联赛、部落聊天
    ((0, 435, 100, 600), "左下"),    # 战斗入口/星星
    ((100, 515, 270, 600), "左下"),  # 护盾、日历/活动条
    ((600, 0, 800, 118), "右上"),    # 资源栏
    ((720, 250, 800, 345), "右"),    # 商店
    ((570, 515, 800, 600), "右下"),  # 宝箱、背包、建造/工人
)


def 主页HUD矩形(尺寸=None) -> list[tuple[int, int, int, int]]:
    return [锚点区域(区域, 锚, 尺寸) for 区域, 锚 in 主页HUD区域]


def 点在主页HUD内(x, y, 边距: int = 6, 尺寸=None) -> bool:
    return any(点在区域内(x, y, 区域, 边距) for 区域 in 主页HUD矩形(尺寸))
