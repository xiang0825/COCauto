import threading
import queue
import time
from dataclasses import replace
from time import sleep

from 数据库.任务数据库 import 任务数据库, 机器人设置
from 模块.ADB设备操作类 import ADB设备操作类
from 线程.自动化机器人 import 自动化机器人


# ==== 监控中心 ====
class 机器人监控中心:
    """增强型监控服务"""

    def __init__(self,日志队列=None):
        self.机器人池 = {}
        # UI 停顿或窗口缩放时，日志不能无限堆积到内存；数据库仍保留
        # 日志历史，队列只承担实时显示职责。
        self.日志队列 = 日志队列 or queue.Queue(maxsize=2000)
        self.全局消息队列 = queue.Queue()#所有在线用户共用一个消息队列和数据库
        self.数据库 = 任务数据库()
        self.运行标志 = True#用于控制监控线程退出的标志

        # 启动监控线程,监控每一个机器人的行为
        self.监控线程 = threading.Thread(
            target=self._监控循环,
            name="机器人监控线程",
            daemon=True
        )
        self.监控线程.start()



    def 创建机器人(self,机器人标志: str, 初始设置: 机器人设置 = None):

        if 机器人标志 in self.机器人池:
            raise ValueError(f"机器人标志[{机器人标志}],已存在")
        else:
            机器人实例 = 自动化机器人(机器人标志, self.全局消息队列, self.数据库,self.日志队列)

        if 初始设置:
            self.数据库.保存机器人设置(机器人标志, 初始设置)

        self.机器人池[机器人标志] = 机器人实例

    def 创建并启动机器人(self, 机器人标志: str, 初始设置: 机器人设置 = None):
        """创建机器人并启动"""
        self.创建机器人(机器人标志,初始设置)
        self.机器人池[机器人标志].启动()

    def 关闭(self):
        """关闭监控中心，确保桌面程序退出时不留下后台进程。"""
        self.运行标志 = False
        for 机器人 in list(self.机器人池.values()):
            try:
                机器人.停止("控制台关闭", 等待=False)
            except Exception:
                pass
        if hasattr(self, "监控线程") and self.监控线程.is_alive():
            # 监控循环最多每秒检查一次；短等待即可释放数据库和互斥锁。
            self.监控线程.join(timeout=2)

    def _监控循环(self):
        """持续监控所有机器人的状态"""
        while self.运行标志:
            # 检查任务状态
            for 用户标识, 线程 in list(self.机器人池.items()):
                # print("监控中")
                超时状态, 原因 = 线程.检查超时()
                if  超时状态:

                    self.全局消息队列.put(f"机器人{用户标识} "+原因)
                    线程.停止("无心跳")
                    # 无心跳时画面可能正处于战斗、结算或 ADB 断连的中间态。
                    # 这里绝不能为了“恢复”把任意应用拉到前台，也不能重建
                    # 机器人线程；否则一次识别抖动就会中断游戏并造成掉线。
                    # 保留原实例，用户确认模拟器画面后可从界面再次启动。
                    self.全局消息队列.put(
                        f"机器人{用户标识} 已安全停止；无心跳时不自动切换、重启或关闭任何 Android 应用，"
                        "请确认当前页面后从界面手动继续。"
                    )

                # 处理消息
            self._处理消息()
            time.sleep(1)

    def _处理消息(self):
        """处理来自各个机器人的消息"""
        while not self.全局消息队列.empty():
            消息 = self.全局消息队列.get()
            if isinstance(消息, dict) and 消息.get("类型") == "死亡通知":
                self.处理死亡通知(消息["机器人标志"], 消息.get("原因", ""))
            else:
                print(f"[监控中心消息] {time.ctime()}: {消息}")
            self.全局消息队列.task_done()

    def 处理死亡通知(self, 机器人标志: str, 死亡原因: str):
        """处理机器人发起的死亡通知

        注意：机器人线程会自己设置停止事件并退出；连接、超时和战斗
        中异常只安全停止，不把 Android 前台切走或自动重启游戏。
        """
        self.全局消息队列.put(f"机器人 {机器人标志} 报告死亡，原因：{死亡原因}")
        不自动重试标记 = (
            "ADB", "实体 Android 设备", "模拟器连接", "ADB 设备序列号", "不在前台",
            "无心跳", "超时", "未找到主世界入口", "未找到下一个按钮",
            "战斗", "进攻任务",
        )
        if any(标记 in 死亡原因 for 标记 in 不自动重试标记):
            self.全局消息队列.put(
                f"机器人 {机器人标志} 因连接、超时或战斗安全锁停止；已禁止自动重启以避免切换游戏页面。"
                "修复连接或确认页面后请从界面手动启动。"
            )
            return
        if 机器人标志 in self.机器人池:
            机器人实例 = self.机器人池[机器人标志]

            # 等待线程自然结束（不主动调用停止，线程已经自己设置了停止事件）
            if hasattr(机器人实例, '主线程') and 机器人实例.主线程.is_alive():
                self.全局消息队列.put(f"等待机器人 {机器人标志} 线程自然退出...")
                机器人实例.主线程.join(timeout=30)  # 最多等待30秒

                # 如果超时还没退出，强制标记停止
                if 机器人实例.主线程.is_alive():
                    self.全局消息队列.put(f"警告：机器人 {机器人标志} 线程未能在30秒内退出，强制停止")
                    机器人实例.停止事件.set()
                    机器人实例.主线程.join(timeout=10)

            # 移除旧实例
            del self.机器人池[机器人标志]
            # 等待模拟器冷却
            time.sleep(2)
            # 创建新实例并启动
            self.创建并启动机器人(机器人标志)
            self.全局消息队列.put(f"机器人 {机器人标志} 重启完成")


# ==== 使用示例 ====
if __name__ == "__main__":
    # ==== 命令行解析 ====
    parser = argparse.ArgumentParser(description="启动指定机器人")

    parser.add_argument(
        "--机器人",
        action="append",
        nargs="+",  # 每个机器人是一组参数
        required=True,
        help="""机器人参数示例：
    --机器人 标志=模拟器0 雷电索引=1 服务器=国际服 最小资源=200000 刷墙 英雄=弓箭女皇,亡灵王子
    标志必填，其它可选，刷墙/刷主世界/刷夜世界只要存在即开启"""
    )

    args = parser.parse_args()

    # ==== 初始化监控系统 ====
    # 注意：这里假设 机器人监控中心 已经定义
    机器人监控系统 = 机器人监控中心()


    # ==== 帮助函数：解析一组参数为字典 ====
    def 解析机器人参数(参数列表):
        参数字典 = {}
        for item in 参数列表:
            if "=" in item:
                key, value = item.split("=", 1)
                参数字典[key] = value
            else:
                # 布尔参数
                参数字典[item] = True
        return 参数字典


    # ==== 遍历每个机器人参数组并启动机器人 ====
    for 单机器人参数 in args.机器人:
        参数字典 = 解析机器人参数(单机器人参数)
        标志 = 参数字典.get("标志")
        if not 标志:
            print("每个机器人必须指定标志")
            continue

        # 获取数据库旧设置
        旧设置 = 机器人监控系统.数据库.获取机器人设置(标志)
        if not 旧设置:
            旧设置 = 机器人设置()

        # 判断是否只传入了标志参数
        # 参数字典中可能包含"标志"和其他参数，如果只有"标志"，则直接使用旧设置
        传入参数数量 = len([k for k in 参数字典.keys() if k != "标志"])

        if 传入参数数量 == 0:
            # 只传了标志，直接使用旧设置
            最终设置 = 旧设置
        else:
            # 处理英雄列表参数
            欲升级的英雄列表 = None
            if "英雄" in 参数字典:
                # 将逗号分隔的字符串转换为列表
                欲升级的英雄列表 = [英雄.strip() for 英雄 in 参数字典["英雄"].split(",") if 英雄.strip()]

            # 从旧设置复制后只覆盖命令行明确传入的字段。旧实现重新
            # 构造 dataclass，漏掉的开关会回到默认值（例如传“刷墙”
            # 会意外打开“建议建筑”任务），导致任务计划被悄悄改变。
            最终设置 = replace(旧设置)
            if "雷电索引" in 参数字典:
                最终设置.雷电模拟器索引 = int(参数字典["雷电索引"])
            if "服务器" in 参数字典:
                最终设置.服务器 = 参数字典["服务器"]
                最终设置.__post_init__()
            if "最小资源" in 参数字典:
                最终设置.欲进攻的最小资源 = int(参数字典["最小资源"])
            if "刷墙" in 参数字典:
                最终设置.开启刷墙 = True
            if "边缘比例" in 参数字典:
                最终设置.欲进攻资源建筑靠近地图边缘最小比例 = float(参数字典["边缘比例"])
            if "刷墙金币" in 参数字典:
                最终设置.刷墙起始金币 = int(参数字典["刷墙金币"])
            if "刷墙圣水" in 参数字典:
                最终设置.刷墙起始圣水 = int(参数字典["刷墙圣水"])
            if "刷主世界" in 参数字典:
                最终设置.是否刷主世界 = True
            if "刷夜世界" in 参数字典:
                最终设置.是否刷夜世界 = True
            if 欲升级的英雄列表:
                最终设置.欲升级的英雄或建筑 = 欲升级的英雄列表

        # 创建并启动机器人
        机器人监控系统.创建并启动机器人(标志, 最终设置)
        print(f"已启动机器人: {标志}")

    # 等待所有机器人线程结束
    try:
        短暂延迟 = 10  # 秒数，用于确认没有重启

        空闲计数 = 0
        确认次数 = 短暂延迟  # 每秒检查一次

        while True:
            活跃线程 = [
                r.主线程
                for r in 机器人监控系统.机器人池.values()
                if hasattr(r, "主线程") and r.主线程.is_alive()
            ]
            if not 活跃线程:
                空闲计数 += 1
            else:
                空闲计数 = 0  # 有线程活动，重置计数

            if 空闲计数 >= 确认次数:
                print("所有机器人线程已结束，监控系统退出")
                break

            sleep(1)
    except KeyboardInterrupt:
        print("收到退出信号，停止所有机器人")
        机器人监控系统.运行标志 = False
        for 机器人实例 in 机器人监控系统.机器人池.values():
            if hasattr(机器人实例, "主线程") and 机器人实例.主线程.is_alive():
                机器人实例.停止("手动终止")
                机器人实例.主线程.join()
        print("所有机器人已安全停止，退出程序")
