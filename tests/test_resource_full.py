import unittest
import tempfile
from pathlib import Path

from 工具包.工具函数 import 是否家乡资源打满, 是否夜世界资源打满, 是否目标资源打满
from 数据库.任务数据库 import 任务数据库


class 资源打满判断测试(unittest.TestCase):
    def test_黑水十六万零二百五十三不能误判满仓且五十万应识别满仓(self):
        self.assertFalse(是否目标资源打满({
            "金币": 16_738_000,
            "圣水": 22_595_000,
            "黑油": 160_253,
            "识别成功": True,
        }, "黑水"))
        self.assertTrue(是否目标资源打满({
            "金币": 16_738_000,
            "圣水": 22_595_000,
            "黑油": 500_000,
            "识别成功": True,
        }, "黑水", 黑油储存上限=500_000))

    def test_黑水优先时黑水满仓即可进入待机(self):
        self.assertTrue(是否目标资源打满({
            "金币": 17_090_286,
            "圣水": 25_000_000,
            "黑油": 480_000,
            "识别成功": True,
        }, "黑水", 黑油储存上限=480_000))

    def test_黑水优先时黑水未满不能因其他资源满而待机(self):
        self.assertFalse(是否目标资源打满({
            "金币": 25_000_000,
            "圣水": 31_000_000,
            "黑油": 470_000,
            "识别成功": True,
        }, "黑水", {"黑油": 480_000}, 黑油储存上限=480_000))

    def test_黑水距十四万容量尚有一千八百时继续进攻(self):
        self.assertFalse(是否目标资源打满({
            "金币": 10_485_883,
            "圣水": 16_599_241,
            "黑油": 138_200,
            "识别成功": True,
        }, "黑水", 黑油储存上限=140_000))

    def test_黑水进入容量OCR容差内才算已满(self):
        self.assertTrue(是否目标资源打满({
            "金币": 10_485_883,
            "圣水": 16_599_241,
            "黑油": 139_600,
            "识别成功": True,
        }, "黑水", 黑油储存上限=140_000))

    def test_黑水十万零三百五十不能当作容量上限(self):
        for 黑油 in (100_350, 102_020, 105_516):
            with self.subTest(黑油=黑油):
                self.assertFalse(是否目标资源打满({
                    "金币": 10_578_084,
                    "圣水": 16_708_156,
                    "黑油": 黑油,
                    "识别成功": True,
                }, "黑水", 黑油储存上限=140_000))

    def test_黑水优先时识别失败不能误判满仓(self):
        self.assertFalse(是否目标资源打满({
            "金币": 17_090_286,
            "圣水": 25_000_000,
            "黑油": 480_000,
            "识别成功": False,
        }, "黑水", 黑油储存上限=480_000))

    def test_均衡优先继续使用所有已储存资源的满仓规则(self):
        self.assertFalse(是否目标资源打满({
            "金币": 17_090_286,
            "圣水": 25_000_000,
            "黑油": 480_000,
            "识别成功": True,
        }, "均衡", 黑油储存上限=480_000))

    def test_新版三千一百万容量应识别资源已满(self):
        self.assertTrue(是否家乡资源打满({
            "金币": 31_000_000,
            "圣水": 31_000_000,
            "黑油": 480_000,
            "识别成功": True,
        }, {
            "金币": 31_000_000,
            "圣水": 31_000_000,
            "黑油": 480_000,
        }, 黑油储存上限=480_000))

    def test_三千万仍不能按三千一百万容量误判已满(self):
        self.assertFalse(是否家乡资源打满({
            "金币": 30_000_000,
            "圣水": 30_000_000,
            "黑油": 480_000,
            "识别成功": True,
        }, 黑油储存上限=480_000))

    def test_主世界允许OCR在容量末尾有小偏差(self):
        self.assertTrue(是否家乡资源打满({
            "金币": 20_000_634,
            "圣水": 20_010_071,
            "黑油": 361_500,
            "识别成功": True,
        }, 黑油储存上限=360_000))

    def test_低本黑油为零不阻塞打满判断(self):
        self.assertTrue(是否家乡资源打满({
            "金币": 1_000_000,
            "圣水": 1_000_000,
            "黑油": 0,
        }))

    def test_历史实测容量更高时禁止误判已满(self):
        self.assertFalse(是否家乡资源打满(
            {"金币": 31_000_000, "圣水": 31_000_000, "黑油": 139_500},
            {"金币": 31_000_000, "圣水": 31_000_000, "黑油": 480_000},
            黑油储存上限=480_000,
        ))

    def test_黑油低于历史容量超出OCR容差时禁止误判已满(self):
        self.assertFalse(是否家乡资源打满(
            {"金币": 31_000_000, "圣水": 31_000_000, "黑油": 476_000},
            {"金币": 31_000_000, "圣水": 31_000_000, "黑油": 480_000},
            黑油储存上限=480_000,
        ))

    def test_黑油在历史容量OCR容差内仍可判断已满(self):
        self.assertTrue(是否家乡资源打满(
            {"金币": 31_000_000, "圣水": 31_000_000, "黑油": 478_000},
            {"金币": 31_000_000, "圣水": 31_000_000, "黑油": 480_000},
            黑油储存上限=480_000,
        ))

    def test_历史OCR离群峰值不阻止真实满仓判断(self):
        self.assertTrue(是否家乡资源打满(
            {"金币": 31_000_000, "圣水": 31_000_000, "黑油": 480_000, "识别成功": True},
            {"金币": 31_000_000, "圣水": 411_067_075, "黑油": 480_000},
            黑油储存上限=480_000,
        ))

    def test_峰值只读取同一机器人已确认的资源(self):
        with tempfile.TemporaryDirectory() as 临时目录:
            数据库 = 任务数据库(str(Path(临时目录) / "任务系统.db"))
            数据库.更新状态("robot_1", "家乡资源", {
                "金币": 31_000_000, "圣水": 30_000_000,
                "黑油": 480_000, "识别成功": True,
            })
            数据库.更新状态("robot_1", "家乡资源", {
                "金币": 99_000_000, "圣水": 99_000_000,
                "黑油": 900_000, "识别成功": False,
            })
            数据库.更新状态("robot_2", "家乡资源", {
                "金币": 50_000_000, "圣水": 50_000_000,
                "黑油": 450_000, "识别成功": True,
            })
            self.assertEqual(
                数据库.获取近期家乡资源峰值("robot_1"),
                {"金币": 31_000_000, "圣水": 30_000_000, "黑油": 480_000},
            )

    def test_识别失败或中间值不能误判已满(self):
        self.assertFalse(是否家乡资源打满({
            "金币": 20_000_000,
            "圣水": 20_000_000,
            "黑油": 0,
            "识别成功": False,
        }))
        self.assertFalse(是否家乡资源打满({
            "金币": 19_000_000,
            "圣水": 20_000_000,
            "黑油": 0,
        }))

    def test_夜世界仍需同时确认两种资源(self):
        self.assertFalse(是否夜世界资源打满({
            "金币": 20_000_000,
            "圣水": 19_000_000,
        }))
        self.assertTrue(是否夜世界资源打满({
            "金币": 20_000_634,
            "圣水": 20_010_071,
        }))

    def test_夜世界按明确建筑大师大厅等级判断总储量(self):
        self.assertTrue(是否夜世界资源打满(
            {"金币": 49_800, "圣水": 49_800}, 模式="夜世界", 等级=1
        ))
        self.assertFalse(是否夜世界资源打满(
            {"金币": 35_000, "圣水": 35_000}, 模式="夜世界", 等级=1
        ))
        self.assertTrue(是否夜世界资源打满(
            {"金币": 2_500_000, "圣水": 2_500_000},
            模式="夜世界",
            等级=6,
        ))
        self.assertFalse(是否夜世界资源打满(
            {"金币": 2_500_000, "圣水": 2_500_000},
            模式="夜世界",
            等级=7,
        ))
        self.assertTrue(是否夜世界资源打满(
            {"金币": 6_500_000, "圣水": 6_500_000},
            模式="建筑大师",
            等级="BH10",
        ))

    def test_夜世界容量等级无效或模式不匹配时拒绝满仓(self):
        资源 = {"金币": 6_500_000, "圣水": 6_500_000}
        self.assertFalse(是否夜世界资源打满(
            资源, 模式="主世界", 等级=10
        ))
        self.assertFalse(是否夜世界资源打满(
            资源, 模式="夜世界", 等级=11
        ))


if __name__ == "__main__":
    unittest.main()
