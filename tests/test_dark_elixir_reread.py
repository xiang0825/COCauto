"""黑油中等存量骤降（如 70,303 → 157 的误读）要触发独立复读。"""
import unittest

from 任务流程.更新主世界账号资源状态 import 更新家乡资源状态任务 as 任务类


def _资源(金币, 圣水, 黑油):
    return {"金币": 金币, "圣水": 圣水, "黑油": 黑油, "总资源": 金币 + 圣水 + 黑油, "识别成功": True}


class 黑油复读测试(unittest.TestCase):
    def test_七万黑油读成157要复读(self):
        self.assertTrue(任务类._资源跳变需要复核(
            _资源(8_445_731, 10_733_812, 70_303), _资源(9_263_832, 11_857_825, 157)))

    def test_黑油正常增加不复读(self):
        self.assertFalse(任务类._资源跳变需要复核(
            _资源(8_445_731, 10_733_812, 70_303), _资源(9_263_832, 11_857_825, 74_917)))

    def test_黑油很少时不复读(self):
        self.assertFalse(任务类._资源跳变需要复核(
            _资源(8_445_731, 10_733_812, 5_000), _资源(8_445_731, 10_733_812, 100)))


if __name__ == "__main__":
    unittest.main()
