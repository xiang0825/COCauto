"""机器人统一异常体系。

过去“能否自动恢复”靠在异常文本里搜关键字（“超时”“战斗”“ADB”…），
关键字表在多个文件各维护一份，改一句报错文案就可能改变安全行为。
这里把分类收敛到异常类型上，并保留一份关键字兜底，兼容尚未迁移的
``raise RuntimeError("...超时...")`` 旧代码。

原则不变：凡是无法确认安全的情况，一律禁止自动恢复（fail-closed）。
"""
from __future__ import annotations


class 机器人停止请求(SystemExit):
    """用户/监控中心要求结束任务线程。

    继承 ``SystemExit``，因此现有 ``except SystemExit: raise`` 的护栏
    代码无需修改即可放行；新代码应优先捕获本类型。
    """


class 主机内存保护暂停请求(BaseException):
    """宿主机内存预算不足时暂停当前任务并进入只读恢复等待。

    继承 ``BaseException`` 而非 ``Exception`` 或 ``SystemExit``，确保
    业务层的 ``except Exception:`` 不会意外吞掉，同时也不会被
    ``except SystemExit:`` 当作用户退出而直接结束机器人线程。
    """


class 机器人异常(Exception):
    """机器人业务异常基类。``允许自动恢复`` 为 False 时只安全停止。"""

    允许自动恢复: bool = False


class 安全锁异常(机器人异常):
    """画面、连接或战斗状态不可确认：必须停下等人工确认。"""

    允许自动恢复 = False


class ADB异常(安全锁异常):
    """ADB 断线、设备离线、截图失败。"""


class 战斗安全异常(安全锁异常):
    """战斗/结算/回营过程中的异常。"""


class 页面超时异常(安全锁异常):
    """等待页面出现超时或页面无法识别。"""


class 资源保护异常(安全锁异常):
    """主机或模拟器内存不足等资源保护。"""


class 可恢复任务异常(机器人异常):
    """明确知道画面安全、可以把游戏切回前台重试的异常。"""

    允许自动恢复 = True


# 旧代码以文本描述异常类别；这些关键字出现时视为安全锁。
# 这是唯一的一份关键字表，主入口和任务框架都从这里取。
安全锁关键字: tuple[str, ...] = (
    "ADB",
    "device",
    "截图",
    "超时",
    "无心跳",
    "实体 Android 设备",
    "模拟器连接",
    "ADB 设备序列号",
    "不在前台",
    "未找到主世界入口",
    "未找到下一个按钮",
    "战斗",
    "进攻任务",
)


def 文本命中安全锁(文本: object) -> bool:
    文本 = str(文本 or "")
    return any(关键字 in 文本 for 关键字 in 安全锁关键字)


def 是否禁止自动恢复(异常: BaseException | str | None) -> bool:
    """判断一个异常（或死亡原因文本）是否必须安全停止、禁止自动恢复。

    - ``机器人停止请求`` 是正常停止，不涉及恢复，返回 True（不恢复）。
    - ``机器人异常`` 子类以类属性为准。
    - 其它异常/文本按关键字兜底；命中即禁止。
    """
    if 异常 is None:
        return True
    if isinstance(异常, (机器人停止请求, 主机内存保护暂停请求)):
        return True
    if isinstance(异常, 机器人异常):
        if not 异常.允许自动恢复:
            return True
        return False
    return 文本命中安全锁(异常)
